# === NODE: Read the ticket and its categories ===
# Reads the ticket, its current category fields and the categories the PSA allows for it (on
# ConnectWise, the ticket's own board). Only fields that are blank or "Unclassified" are open; a
# field a technician already set is never changed, and the board is never touched. The open
# levels and the allowed values go to the AI step.
# Accepts a flat {key:value} body (PSA webhook, ServiceAI Action, manual run), the CloudRadial
# {Ticket:{...}, Company:{...}} shape, or either one wrapped in {trigger:...}.
# Read-only: this step never writes to the PSA.
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
# @@ src/psa-categories.ps1 @@
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
$stopState = @{ done = $false }
$warnings = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    param($Own)
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($Own) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
function Stop-Run {
    param([string]$Status, [string]$Why, [string]$TicketId = '')
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{
            status = $Status; message = $Why; public_note = ''
            internal_note = "Auto-categorize stopped before anything was changed: $Why"
            ticket_id = $TicketId; actions = @(); warnings = @(Get-AllWarnings $warnings)
        })
    throw $Why
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = [string]$_.Exception.Message; public_note = ''; internal_note = "Auto-categorize failed while reading the PSA: $($_.Exception.Message) Nothing was changed."; ticket_id = ''; actions = @(); warnings = @(Get-AllWarnings $warnings) }) }; break }

$raw = Get-NodeInput
if ($null -eq $raw) { Stop-Run 'incomplete' 'No input was received. Send at least ticketId.' }
if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The input was text that is not valid JSON.' } }
$wrap = Get-Prop $raw 'trigger'; if ($null -ne $wrap) { $raw = $wrap; if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The trigger body was text that is not valid JSON.' } } }

$answers = @{}
if ($raw -is [System.Collections.IDictionary]) { foreach ($k in @($raw.Keys)) { $answers[[string]$k] = $raw[$k] } }
else { foreach ($p in $raw.PSObject.Properties) { $answers[$p.Name] = $p.Value } }
$crTicket = Get-Prop $raw 'Ticket'
if ($null -ne $crTicket) {
    foreach ($q in @(Get-Prop $crTicket 'Questions')) { $qid = [string](Get-Prop $q 'Id'); if ($qid) { $answers[$qid] = Get-Prop $q 'Value' } }
    $tid = Get-Prop $crTicket 'TicketId'; if ($null -ne $tid) { $answers['ticketId'] = $tid }
}
function Get-Field {
    param([string[]]$Names)
    foreach ($n in $Names) {
        if (-not $answers.ContainsKey($n)) { continue }
        $v = $answers[$n]
        if ($null -eq $v -or $v -is [System.Management.Automation.PSCustomObject] -or $v -is [System.Collections.IDictionary]) { continue }
        $s = ([string]$v).Trim()
        if (-not $s -or $s.StartsWith('@') -or $s -match '^\{\{.*\}\}$' -or $s -match '^<[^>]*>$') { continue }
        return $s
    }
    return ''
}
function Get-Flag { param([string[]]$Names, [bool]$Default) $s = (Get-Field $Names).ToLowerInvariant(); if (-not $s) { return $Default }; return (@('true', 'yes', '1', 'y') -contains $s) }

$f = [ordered]@{
    ticketId      = (Get-Field @('ticketId', 'ticket_id', 'TicketId', 'ticketNumber', 'id'))
    psa           = (Get-Field @('psa'))
    confirm       = (Get-Flag @('confirm', 'approvedToWrite') $false)
    addNote       = (Get-Flag @('addNote') $true)
    minConfidence = 0.7
}
$s = Get-Field @('minConfidence')
if ($s) { $d = 0.0; if (-not [double]::TryParse($s, [System.Globalization.NumberStyles]::Float, [System.Globalization.CultureInfo]::InvariantCulture, [ref]$d) -or $d -lt 0 -or $d -gt 1) { Stop-Run 'incomplete' "minConfidence must be a number from 0 to 1; '$s' isn't. Nothing was read." }; $f.minConfidence = $d }
if (-not $f.ticketId) { Stop-Run 'incomplete' 'ticketId is missing. Send the PSA ticket number of the ticket to categorize. Nothing was read.' }

$actions = New-Object System.Collections.ArrayList
$conn = Connect-Psa -Psa (Get-PsaType $f.psa)
$f.psa = $conn.Psa
$psaName = Get-PsaName
$id = ''
try { $id = Resolve-PsaTicketId $f.ticketId } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) wasn't found in $($psaName): $($_.Exception.Message)" $f.ticketId }
$t = $null
try { $t = Get-PsaTicket -Id $id } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) couldn't be read from $($psaName): $($_.Exception.Message)" $f.ticketId }
$null = $actions.Add("Read ticket $($f.ticketId) from $psaName.")
$state = $null
try { $state = Get-PsaCategoryState -Id $id -Raw $t.raw } catch { Stop-Run 'incomplete' "The categories for ticket $($f.ticketId) couldn't be read from $($psaName): $($_.Exception.Message) Nothing was changed." $f.ticketId }
$labels = @($state.labels)

# The open levels: the first blank level and the blank levels right after it. A level a technician
# already set is never opened, and nothing below it either.
$open = @()
for ($i = 0; $i -lt $labels.Count; $i++) {
    $b = Test-CatBlank $state.current[$i].name
    if ($open.Count -and -not $b) { break }
    if ($b) { $open += $i }
}
$skip = ''
if (-not $open.Count) { $skip = "Ticket $($f.ticketId) already has its $($labels -join ', ') set, so nothing was changed." }
elseif (-not @($state.options).Count) { $skip = "$psaName has no $($labels[0]) values to choose from for ticket $($f.ticketId), so nothing was changed." }
$null = $actions.Add("Read the $($labels -join ' / ') values $psaName allows$(if ($state.boardId) { " on the ticket's board" }): $(Get-CatNodeCount $state.options).")

# What the AI sees: the ticket text, the fixed levels and, for the open ones, only the allowed names.
function ConvertTo-CatNames { param($List, [int]$Depth) return @(@($List) | Where-Object { $null -ne $_ } | ForEach-Object { if ($Depth -le 1 -or -not @($_.children).Count) { [string]$_.name } else { [ordered]@{ name = [string]$_.name; children = @(ConvertTo-CatNames $_.children ($Depth - 1)) } } }) }
$fixed = [ordered]@{}; for ($i = 0; $i -lt $labels.Count; $i++) { if ($open -notcontains $i) { $fixed[$labels[$i]] = [string]$state.current[$i].name } }
$choices = @($state.options)
foreach ($i in 0..($labels.Count - 1)) { if ($open -contains $i) { break }; $n = Find-CatChild $choices $state.current[$i].name; $choices = $(if ($n) { @($n.children) } else { @() }) }
$desc = [string]$t.description; if ($desc.Length -gt 3000) { $desc = $desc.Substring(0, 3000) + ' [cut]' }
$facts = [ordered]@{
    ticket  = [ordered]@{ summary = [string]$t.summary; description = $desc }
    levels  = @($labels)
    fixed   = $fixed
    choose  = @($open | ForEach-Object { $labels[$_] })
    options = @(ConvertTo-CatNames $choices ($labels.Count - $(if ($open.Count) { $open[0] } else { 0 })))
}
$request = [ordered]@{ ticketId = $id; number = $f.ticketId; psa = $f.psa; confirm = $f.confirm; addNote = $f.addNote; minConfidence = $f.minConfidence; skip = $skip }

Set-NodeOutput ([ordered]@{
        status        = 'ok'
        request_json  = ($request | ConvertTo-Json -Depth 6 -Compress)
        state_json    = ([ordered]@{ labels = $labels; current = $state.current; options = $state.options; open = @($open); boardId = $state.boardId } | ConvertTo-Json -Depth 12 -Compress)
        facts_json    = $(if ($skip) { '{"skip": true}' } else { $facts | ConvertTo-Json -Depth 12 -Compress })
        warnings_json = (@(Get-AllWarnings $warnings) | ConvertTo-Json -Depth 3 -Compress -AsArray)
        actions_json  = (@($actions) | ConvertTo-Json -Depth 3 -Compress -AsArray)
    })
