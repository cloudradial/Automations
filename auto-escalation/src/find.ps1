# ---- single-ticket mode (a portal form) ----
# The requester asked for this one ticket to be escalated, so it always is (the untouched-time and SLA rules are
# for the sweep), once its ownership is checked: the ticket's company must be company_psa_id and the requester
# must be its contact (or, with allow_company_colleagues, anyone at that company). With no requester or company
# it is refused unless technician_run is true. A ticket the requester can't escalate gets the same message
# whether it exists or not, so nothing about another company's ticket is revealed.
function Stop-EscForm {
    param([string]$Message, [string]$Detail)
    Set-NodeOutput ([ordered]@{ status = 'rejected'; message = $Message; public_note = ''; internal_note = "$Message $Detail".Trim(); ticket_id = ''; preview = $preview; mode = 'form'; escalations = @(); counts = @{}; settings = $settings; actions = @($run.actions); warnings = @(Get-EscWarnings $run.warnings) })
    throw $Message
}
function Invoke-EscSingle {
    $ref = $form.ticket.TrimStart('#').Trim()
    $denied = "Ticket $ref couldn't be escalated because it isn't one of your tickets. Check the ticket number, or contact the service desk."
    if (-not $form.technician -and (-not $form.requester -or -not $form.companyId)) {
        Stop-EscForm "Ticket $ref wasn't escalated because the request didn't say who sent it. The form's webhook must send requester_email (@UserEmail) and company_psa_id (@CompanyPsaId), or a technician run must set technician_run to true." 'Nothing was changed.'
    }
    $id = ''; $row = $null
    try {
        $id = Resolve-PsaTicketId $ref
        $tk = Get-PsaTicket $id
        $row = ConvertTo-PsaTicketRow $tk.raw
    }
    catch {
        if ($form.technician) { Stop-EscRun 'error' "Auto-Escalation couldn't read ticket $ref from $($psaName): $($_.Exception.Message)" }
        Stop-EscForm $denied "The ticket couldn't be read: $($_.Exception.Message)"
    }
    if (-not $form.technician) {
        if ([string]$row.companyId -ne $form.companyId) { Stop-EscForm $denied "The ticket's company doesn't match company_psa_id $($form.companyId). Nothing was changed." }
        if (-not $form.colleagues) {
            $email = [string]$row.contactEmail
            if (-not $email -and $row.contactId) {
                try { $hit = @((Get-PsaCompanyContacts $row.companyId).contacts | Where-Object { $_.id -eq [string]$row.contactId }) | Select-Object -First 1; if ($hit) { $email = [string]$hit.email } }
                catch { $null = $run.warnings.Add("Couldn't read the company's contacts to find the ticket contact's email: $($_.Exception.Message)") }
            }
            if (-not $email -or $email.Trim() -ine $form.requester) { Stop-EscForm $denied "The requester isn't the ticket's contact (set allow_company_colleagues to true to let anyone at the company escalate). Nothing was changed." }
        }
    }
    try { Resolve-PsaTicketNames @($row) } catch { $null = $run.warnings.Add("Couldn't look up some company or technician names: $($_.Exception.Message)") }
    $num = [string]$row.number; if (-not $num) { $num = $ref }
    $who = if ($form.requester) { $form.requester } else { 'a technician' }
    $base = [ordered]@{
        status = 'success'; message = ''; public_note = ''; internal_note = ''; ticket_id = [string]$row.id
        preview = $preview; mode = 'form'; psa = $conn.Psa; psaName = $psaName; companyId = [string]$row.companyId; companyName = [string]$row.companyName; generatedAt = [datetime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ')
        form = [ordered]@{ ticket = $num; requester = $form.requester; reason = $form.reason; technician_run = $form.technician }
        escalations = @(); counts = [ordered]@{ open = 1; skipped = 0; atRisk = 1; alreadyEscalated = 0; notesUnreadable = 0; selected = 0; toReassign = 0; noteOnly = 0; overLimit = 0 }; settings = $settings
        actions = @($run.actions); warnings = @()
    }
    if ($row.isClosed) {
        $base.message = "Ticket $num is closed, so it wasn't escalated. If the problem is back, open a new request."; $base.internal_note = $base.message; $base.form_result = 'closed'; $base.counts.skipped = 1
        $base.warnings = @(Get-EscWarnings $run.warnings); Set-NodeOutput $base; return
    }
    $notes = $null
    try { $notes = @(Get-PsaTicketNotes -Id $row.id -TextOnly) }
    catch { Stop-EscRun 'error' "Auto-Escalation couldn't read the notes on ticket $num to check for an earlier escalation, so it wasn't escalated: $($_.Exception.Message)" }
    if (Test-PsaNoteMarker -Id $row.id -Marker $escMarker -Notes $notes) {
        $base.message = "Ticket $num has already been escalated, so it wasn't escalated again. Someone from the team will be in touch."; $base.internal_note = $base.message; $base.form_result = 'already-escalated'; $base.counts.alreadyEscalated = 1
        $base.warnings = @(Get-EscWarnings $run.warnings); Set-NodeOutput $base; return
    }

    # The plan: one tier up through the escalation map, like the sweep.
    $qid = ([string]$row.queueId).ToLowerInvariant(); $qname = ([string]$row.queueName).Trim().ToLowerInvariant()
    $entry = @($map | Where-Object { $_.from -ne '*' -and (($qid -and $_.from -eq $qid) -or ($qname -and $_.from -eq $qname)) }) | Select-Object -First 1
    if (-not $entry) { $entry = @($map | Where-Object { $_.from -eq '*' }) | Select-Object -First 1 }
    $qLabel = if ($row.queueName) { $row.queueName } elseif ($row.queueId) { "queue $($row.queueId)" } else { 'no queue' }
    $action = 'note-only'; $why = ''; $toQ = ''; $toA = ''; $toR = ''; $queueProblem = ''
    if (-not $entry) { $why = "There is no escalation_map entry for $qLabel, so it wasn't moved; it is flagged for the dispatcher instead." }
    else {
        $toQ = $entry.queue; $toA = $entry.assignee; $toR = $entry.role
        if ($toQ -and ($toQ.ToLowerInvariant() -eq $qid -or $toQ.ToLowerInvariant() -eq $qname)) { $toQ = '' }
        if ($toA -and $toA -eq [string]$row.assigneeId) { $toA = '' }
        if ($toQ) {
            $qc = $null
            try { $qc = Test-PsaQueue -Queue $toQ } catch { $null = $run.warnings.Add("Couldn't check the escalation target '$toQ': $($_.Exception.Message)") }
            if ($null -ne $qc -and -not $qc.ok) { $queueProblem = "can't move it to $($toQ): $($qc.reason)"; $toQ = '' }
        }
        if ($toQ -or $toA) { $action = 'reassign' }
        elseif ($queueProblem) { $why = "The escalation_map target can't be used ($queueProblem), so it wasn't moved; it is flagged for the dispatcher instead." }
        else { $why = "It is already where the escalation_map sends $qLabel tickets, so it wasn't moved again; it is flagged for the dispatcher instead." }
    }
    $asked = if ($form.requester) { "$($form.requester) asked for it to be escalated from the portal." } else { 'A technician asked for it to be escalated.' }
    $reasonText = $asked + $(if ($form.reason) { " Reason: $($form.reason)" } else { ' No reason was given.' })
    $e = [ordered]@{
        id = [string]$row.id; number = $num; summary = $row.summary; company = $row.companyName; technician = $row.assigneeName; assigneeId = $row.assigneeId
        queue = $qLabel; queueId = $row.queueId; priority = $(if ($row.priorityLevel) { $row.priorityLevel } else { 'medium' }); priorityLabel = $row.priority; status = $row.status
        minutesUntouched = $(if ($null -ne $row.updated) { [int][Math]::Round(([datetime]::UtcNow - $row.updated).TotalMinutes) } else { 0 }); untouched = $false; slaAtRisk = $false
        reason = $reasonText; noteLead = 'This ticket was escalated at the requester''s request.'; requester = $form.requester
        action = $action; whyNotMoved = $why; queueProblem = $queueProblem; toQueue = $toQ; toAssignee = $toA; toRole = $toR
        result = $(if ($preview) { 'preview' } else { 'planned' }); outcome = ''; error = ''; noted = $false
    }
    if ($queueProblem -and $action -eq 'reassign') { $null = $run.warnings.Add("Ticket $($num): $queueProblem") }
    $base.escalations = @($e)
    $base.counts.selected = 1
    if ($action -eq 'reassign') { $base.counts.toReassign = 1 } else { $base.counts.noteOnly = 1 }
    if ($preview) {
        $base.status = 'pending_confirmation'
        $base.message = "Preview: ticket $num would be escalated for $who ($(if ($action -eq 'reassign') { 'moved up a tier' } else { 'noted and flagged only' })). Nothing was changed. Run again with preview set to false to make the changes."
    }
    else { $base.message = "Ticket $num to escalate for $($who): $(if ($action -eq 'reassign') { 'move up a tier' } else { 'note and flag only' })." }
    $base.internal_note = $base.message
    $base.warnings = @(Get-EscWarnings $run.warnings)
    Set-NodeOutput $base
}
if ($form.ticket) { Invoke-EscSingle; return }
# Optional company input: a PSA company id or exact name. Only that company's tickets are read, moved or noted.
try { $co = Resolve-PsaCompanyId $settings.company; $settings.companyId = $co.id; $settings.companyName = $co.name }
catch { Stop-EscRun 'rejected' "Auto-Escalation didn't run because the company input couldn't be matched: $($_.Exception.Message)" }
$scope = if ($settings.companyName) { " for $($settings.companyName)" } elseif ($settings.companyId) { " for company $($settings.companyId)" } else { '' }
$now = [datetime]::UtcNow
try { $open = @(Find-PsaTickets -Open -CompanyId $settings.companyId -Max $maxScan -IncludeSla) }
catch { Stop-EscRun 'error' "Auto-Escalation couldn't read open tickets from $psaName. $($_.Exception.Message)" }
$null = $run.actions.Add("Read $($open.Count) open tickets$scope from $psaName.")
if ($PsaState.FindTruncated) { $null = $run.warnings.Add("Stopped reading at max_scan ($maxScan) open tickets, so some weren't checked.") }

$counts = [ordered]@{ open = $open.Count; skipped = 0; atRisk = 0; alreadyEscalated = 0; notesUnreadable = 0; selected = 0; toReassign = 0; noteOnly = 0; overLimit = 0 }
$cands = New-Object System.Collections.ArrayList
$slaWarned = @{ done = $false }
foreach ($t in $open) {
    $st = $t.status.ToLowerInvariant()
    if (@($skip | Where-Object { $st.Contains($_) }).Count) { $counts.skipped++; continue }
    $prio = if ($t.priorityLevel) { $t.priorityLevel } else { 'medium' }
    $limit = [int]$limits[$prio]
    $idle = if ($null -ne $t.updated) { ($now - $t.updated).TotalMinutes } else { 0 }
    $untouched = $idle -ge $limit
    $slaRisk = $false; $slaText = ''; $pct = 0
    if ($checkSla) {
        $sla = $null
        try { $sla = Get-PsaTicketSla $t }
        catch { if (-not $slaWarned.done) { $slaWarned.done = $true; $null = $run.warnings.Add("Couldn't read $psaName SLA details for some tickets, so only the untouched time was checked for them. First error: $($_.Exception.Message)") } }
        if ($null -ne $sla -and $sla.source -eq 'psa') {
            $what = switch ($sla.kind) { 'respond' { 'respond-by' } 'resolve' { 'resolve-by' } default { 'due' } }
            if ($null -ne $sla.target) {
                $total = ($sla.target - $sla.start).TotalMinutes
                $pct = if ($total -gt 0) { [int][Math]::Round(100 * ($now - $sla.start).TotalMinutes / $total) } else { 100 }
                $when = $sla.target.ToString('ddd d MMM HH:mm', [Globalization.CultureInfo]::InvariantCulture) + ' UTC'
                if ($now -ge $sla.target) { $slaRisk = $true; $slaText = "Its SLA $what time ($when) has passed." }
                elseif ($pct -ge $riskPct) { $slaRisk = $true; $slaText = "It has used $pct% of the time to its SLA $what time ($when)." }
            }
            elseif ($sla.breached -eq $true) { $slaRisk = $true; $slaText = "$psaName marks it as out of SLA." }
        }
    }
    if (-not $untouched -and -not $slaRisk) { continue }
    $counts.atRisk++
    $score = [Math]::Max($(if ($limit -gt 0) { $idle / $limit } else { 0 }), $pct / 100.0)
    $null = $cands.Add(@{ t = $t; prio = $prio; limit = $limit; idle = $idle; untouched = $untouched; slaRisk = $slaRisk; slaText = $slaText; score = $score })
}

# Most overdue first; skip tickets already escalated (marker note); stop at max_tickets.
$picked = New-Object System.Collections.ArrayList
$noteReads = 0
foreach ($cd in @($cands | Sort-Object { $_.score } -Descending)) {
    if ($picked.Count -ge $maxT) { $counts.overLimit++; continue }
    if ($noteReads -ge ($maxT * 5 + 20)) { $counts.overLimit++; continue }
    $noteReads++
    $notes = $null
    try { $notes = @(Get-PsaTicketNotes -Id $cd.t.id -TextOnly) }
    catch {
        # Fail closed: without the notes we can't tell whether it was already escalated.
        $counts.notesUnreadable++
        $null = $run.warnings.Add("Skipped ticket $($cd.t.number) because its notes couldn't be read to check for an earlier escalation: $($_.Exception.Message)")
        continue
    }
    if (Test-PsaNoteMarker -Id $cd.t.id -Marker $escMarker -Notes $notes) { $counts.alreadyEscalated++; continue }
    $null = $picked.Add($cd)
}
if ($counts.overLimit) { $null = $run.warnings.Add("$($counts.overLimit) more at-risk tickets were left for the next run because of max_tickets ($maxT).") }
try { Resolve-PsaTicketNames @($picked | ForEach-Object { $_.t }) }
catch { $null = $run.warnings.Add("Couldn't look up some company or technician names: $($_.Exception.Message)") }

# ---- plan each escalation ----
# A preview checks each move target once (Test-PsaQueue, read-only), so a board or queue that doesn't exist, or
# can't take the ticket, shows in the plan instead of failing on the live run.
$queueChecks = @{}
$escalations = @(foreach ($cd in $picked) {
        $t = $cd.t
        $qid = $t.queueId.ToLowerInvariant(); $qname = $t.queueName.Trim().ToLowerInvariant()
        $entry = @($map | Where-Object { $_.from -ne '*' -and (($qid -and $_.from -eq $qid) -or ($qname -and $_.from -eq $qname)) }) | Select-Object -First 1
        if (-not $entry) { $entry = @($map | Where-Object { $_.from -eq '*' }) | Select-Object -First 1 }
        $reasons = @()
        if ($cd.untouched) { $reasons += "It has had no update for $(Format-EscSpan $cd.idle), past the $($cd.limit)-minute limit for $($cd.prio) priority tickets." }
        if ($cd.slaRisk) { $reasons += $cd.slaText }
        $qLabel = if ($t.queueName) { $t.queueName } elseif ($t.queueId) { "queue $($t.queueId)" } else { 'no queue' }
        $active = (-not $cd.untouched) -and [bool]$t.assigneeId
        $action = 'note-only'; $why = ''; $toQ = ''; $toA = ''; $toR = ''; $queueProblem = ''
        if ($active) { $why = "It was updated recently and is assigned to $($t.assigneeName), so it stays with them." }
        elseif (-not $entry) { $why = "There is no escalation_map entry for $qLabel, so it wasn't moved." }
        else {
            $toQ = $entry.queue; $toA = $entry.assignee; $toR = $entry.role
            $sameQ = $toQ -and ($toQ.ToLowerInvariant() -eq $qid -or $toQ.ToLowerInvariant() -eq $qname)
            if ($sameQ) { $toQ = '' }
            $sameA = $toA -and ($toA -eq $t.assigneeId)
            if ($sameA) { $toA = '' }
            if ($preview -and $toQ) {
                $qk = $toQ.ToLowerInvariant()
                if (-not $queueChecks.Contains($qk)) {
                    try { $queueChecks[$qk] = Test-PsaQueue -Queue $toQ }
                    catch { $queueChecks[$qk] = @{ ok = $true; reason = ''; id = ''; name = $toQ }; $null = $run.warnings.Add("Couldn't check the escalation target '$toQ': $($_.Exception.Message)") }
                }
                $qc = $queueChecks[$qk]
                if (-not $qc.ok) { $queueProblem = "can't move it to $($toQ): $($qc.reason)"; $toQ = '' }
            }
            if ($toQ -or $toA) { $action = 'reassign' }
            elseif ($queueProblem) { $why = "Would be flagged, $queueProblem" }
            else { $why = "It is already where the escalation_map sends $qLabel tickets, so it wasn't moved again." }
        }
        if ($action -eq 'reassign') { $counts.toReassign++ } else { $counts.noteOnly++ }
        [ordered]@{
            id = $t.id; number = $t.number; summary = $t.summary; company = $t.companyName; technician = $t.assigneeName; assigneeId = $t.assigneeId
            queue = $qLabel; queueId = $t.queueId; priority = $cd.prio; priorityLabel = $t.priority; status = $t.status
            minutesUntouched = [int][Math]::Round($cd.idle); untouched = $cd.untouched; slaAtRisk = $cd.slaRisk
            reason = ($reasons -join ' '); action = $action; whyNotMoved = $why; queueProblem = $queueProblem; toQueue = $toQ; toAssignee = $toA; toRole = $toR
            result = $(if ($preview) { 'preview' } else { 'planned' }); outcome = ''; error = ''; noted = $false
        }
    })
$counts.selected = $escalations.Count

$checked = $open.Count - $counts.skipped
if (-not $escalations.Count) {
    $msg = "No open tickets$scope need escalating. $checked open tickets were checked."
    if ($counts.alreadyEscalated) { $msg += " $($counts.alreadyEscalated) at-risk tickets were already escalated earlier." }
}
elseif ($preview) {
    $msg = "Preview: $($escalations.Count) ticket$(if ($escalations.Count -ne 1) { 's' }) would be escalated$scope ($($counts.toReassign) moved up a tier, $($counts.noteOnly) noted and flagged only). Nothing was changed."
    $bad = @($escalations | Where-Object { $_.queueProblem }).Count
    if ($bad) { $msg += " $bad can't be moved because the escalation_map target isn't valid; each ticket's outcome says why. Fix the map before a live run." }
    $msg += ' Run again with preview set to false to make the changes.'
}
else { $msg = "$($escalations.Count) ticket$(if ($escalations.Count -ne 1) { 's' }) to escalate: $($counts.toReassign) to move up a tier and $($counts.noteOnly) to note and flag only." }

Set-NodeOutput ([ordered]@{
        status = $(if ($preview -and $escalations.Count) { 'pending_confirmation' } else { 'success' }); message = $msg; public_note = ''; internal_note = $msg; ticket_id = ''
        preview = $preview; psa = $conn.Psa; psaName = $psaName; companyId = $settings.companyId; companyName = $settings.companyName; generatedAt = $now.ToString('yyyy-MM-ddTHH:mm:ssZ')
        escalations = @($escalations); counts = $counts; settings = $settings
        actions = @($run.actions); warnings = @(Get-EscWarnings $run.warnings)
    })
