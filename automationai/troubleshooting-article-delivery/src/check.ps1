# === NODE: Check the ticket and the article ===
# Reads only; changes nothing. Decides what the next step does and why.
# Send mode:
#   - the confidence must be at least min_confidence (default 0.75)
#   - the ticket must exist and be open, and must not already have had this article sent (ServiceAI Retry replays requests)
#   - the ticket's company must map to one CloudRadial company (its psaKey), or companyId names it
#   - the article must exist in CloudRadial, belong to that company or be MSP-wide (companyId 0 or mspCompanyId),
#     be published (datePublished set and not in the future), and the link must point at it
#   - the contact must not be a portal user of a different company
# Reply mode:
#   - the ticket must have had a troubleshooting article sent by this workflow (the internal note marker)
#   - the reply must clearly say it's fixed (conservative match); anything else leaves the ticket open
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/cloudradial.ps1
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
