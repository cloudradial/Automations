# === NODE: Create the Halo ticket ===
# Creates a HaloPSA ticket from a CloudRadial request form that was made from a Halo ticket template (see
# halo-template-migration), with the template's ticket type, team, priority, status and category, and every
# answer written into its Halo custom field. CloudRadial's own ticket submission can't fill Halo custom fields,
# so Halo rejects a form whose ticket type has mandatory ones ("First Name is mandatory", verified 2026-10-19);
# this creates the ticket through Halo's API instead. The form runs with Send to PSA off.
# Input: the form submission as CloudRadial sends it ({User, Company, Ticket: {TicketSubject, TicketDescription,
# Questions: [{Id, Label, Value}]}}), a flat body, or either wrapped in {trigger: ...}. Each answer is found by its
# question's Field ID, which is the Halo custom field name (CFfirstName). The template comes from the answer
# "haloTemplateId", a templateId input, or the form's subject matching a template name.
# A form submission creates the ticket; a manual run previews it unless confirm is true.
# Unverified until a live run: Halo's ticket-create custom field shape ({id, name, value}), and the values for
# list fields (the option's id; several ids joined with commas) and checkboxes (true or false).
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
# The first of -Names that has a value. A list counts when it has items (cast to text, a list of objects looks blank).
function Get-First {
    param($o, [string[]]$Names)
    foreach ($n in $Names) {
        $v = Get-Prop $o $n
        if ($null -eq $v) { continue }
        if ($v -is [string]) { if (-not [string]::IsNullOrWhiteSpace($v)) { return $v }; continue }
        if ($v -is [System.Collections.IList]) { if ($v.Count) { return , $v }; continue }
        return $v
    }
    return $null
}
$stopState = @{ done = $false; ticket = '' }
$warnings = New-Object System.Collections.ArrayList
$actions = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($warnings) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
function Stop-Run {
    param([string]$Status, [string]$Why)
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = $Status; message = $Why; public_note = ''; internal_note = "No Halo ticket was created: $Why"; ticket_id = ''; counts = [ordered]@{ ticketsCreated = 0; fieldsFilled = 0 }; actions = @($actions); warnings = @(Get-AllWarnings) })
    throw $Why
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = "Creating the Halo ticket failed: $($_.Exception.Message)"; public_note = ''; internal_note = "No Halo ticket was created: $($_.Exception.Message)"; ticket_id = ''; counts = [ordered]@{ ticketsCreated = 0; fieldsFilled = 0 }; actions = @($actions); warnings = @(Get-AllWarnings) }) }; break }

# ---- the input ----
$raw = Get-NodeInput
if ($null -eq $raw) { Stop-Run 'incomplete' 'No input was received. Send the form submission (or at least templateId and companyPsaId).' }
if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The input was text that is not valid JSON.' } }
$wrap = Get-Prop $raw 'trigger'; if ($null -ne $wrap) { $raw = $wrap; if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The trigger body was text that is not valid JSON.' } } }

# Every answer by its Field ID (case-insensitive), from the form's Questions, a "fields" object and the flat body.
$answers = @{}
$put = { param([string]$k, $v) if (-not $k) { return }; $answers[$k.ToLowerInvariant()] = $v }
if ($raw -is [System.Collections.IDictionary]) { foreach ($k in @($raw.Keys)) { & $put ([string]$k) $raw[$k] } } else { foreach ($p in $raw.PSObject.Properties) { & $put $p.Name $p.Value } }
$fieldsObj = Get-Prop $raw 'fields'
if ($null -ne $fieldsObj -and $fieldsObj -isnot [string]) { if ($fieldsObj -is [System.Collections.IDictionary]) { foreach ($k in @($fieldsObj.Keys)) { & $put ([string]$k) $fieldsObj[$k] } } else { foreach ($p in $fieldsObj.PSObject.Properties) { & $put $p.Name $p.Value } } }
$crTicket = Get-Prop $raw 'Ticket'; $crUser = Get-Prop $raw 'User'; $crCompany = Get-Prop $raw 'Company'
$fromForm = $false
foreach ($q in @(Get-Prop $crTicket 'Questions')) { $qid = [string](Get-Prop $q 'Id'); if ($qid) { $fromForm = $true; & $put $qid (Get-Prop $q 'Value') } }
# A value is missing when blank, a CloudRadial token nobody filled ("@CFfirstName"), or a placeholder.
function Get-Answer {
    param([string[]]$Names)
    foreach ($n in $Names) {
        $k = $n.ToLowerInvariant(); if (-not $answers.ContainsKey($k)) { continue }
        $v = $answers[$k]
        if ($null -eq $v -or $v -is [System.Management.Automation.PSCustomObject] -or $v -is [System.Collections.IDictionary]) { continue }
        if ($v -is [System.Collections.IList]) { $v = (@($v) | ForEach-Object { [string]$_ }) -join ', ' }
        $s = ([string]$v).Trim()
        if (-not $s -or $s.StartsWith('@') -or $s -match '^\{\{.*\}\}$' -or $s -match '^<[^>]*>$') { continue }
        return $s
    }
    return ''
}
$templateIdText = Get-Answer @('haloTemplateId', 'templateId', 'template_id')
$companyPsaId = Get-Answer @('companyPsaId', 'company_psa_id', 'clientId', 'client_id'); if (-not $companyPsaId) { $companyPsaId = [string](Get-Prop $crCompany 'CompanyPsaId') }
$userPsaId = Get-Answer @('userPsaId', 'user_psa_id', 'userId', 'user_id'); if (-not $userPsaId) { $userPsaId = [string](Get-Prop $crUser 'UserPsaId') }
$userEmail = Get-Answer @('userEmail', 'requester_email'); if (-not $userEmail) { $userEmail = [string](Get-Prop $crUser 'UserEmail') }
$subject = Get-Answer @('subject', 'ticketSubject'); if (-not $subject) { $subject = [string](Get-Prop $crTicket 'TicketSubject') }
$description = Get-Answer @('description', 'ticketDescription'); if (-not $description) { $description = [string](Get-Prop $crTicket 'TicketDescription') }
$confirmText = (Get-Answer @('confirm', 'approvedToWrite')).ToLowerInvariant()
$confirm = if ($confirmText) { @('true', 'yes', '1', 'y') -contains $confirmText } else { $fromForm }
if ($templateIdText -and $templateIdText -notmatch '^\d+$') { Stop-Run 'incomplete' "haloTemplateId must be a Halo template number; '$templateIdText' isn't." }
if (-not $companyPsaId -or $companyPsaId -notmatch '^\d+$' -or [long]$companyPsaId -le 0) { Stop-Run 'incomplete' 'The Halo client is missing: the submission has no CompanyPsaId. Check that the CloudRadial company is linked to a Halo client (Partner > Companies).' }

# ---- Halo: the template ----
$null = Connect-Psa -Psa 'halopsa'
$need = 'read ticket templates, ticket types and custom fields, and create tickets'
if (-not $templateIdText) {
    # No id: find the template whose name the form's subject starts with (the form is named after it).
    $all = New-Object System.Collections.ArrayList
    for ($p = 1; $p -le 20; $p++) {
        $r = Invoke-PsaRead "/Template?pageinate=true&page_size=50&page_no=$p" 'read the ticket templates' $need
        $rows = @(Get-PsaListReply $r @('stdrequests', 'templates', 'records', 'data'))
        foreach ($t in $rows) { $null = $all.Add($t) }
        if ($rows.Count -lt 50) { break }
    }
    $hits = @($all | Where-Object { $n = ([string](Get-First $_ @('name'))).Trim(); $n -and $subject -and ($subject -eq $n -or $subject.StartsWith("$n ") -or $subject.StartsWith("$n -") -or $subject.StartsWith("${n}:")) } | Sort-Object { ([string](Get-First $_ @('name'))).Length } -Descending)
    if (-not $hits.Count) { Stop-Run 'incomplete' "No Halo template matches the form '$subject'. Add a haloTemplateId answer to the form, or send templateId." }
    $templateIdText = [string](Get-First $hits[0] @('id'))
    $null = $actions.Add("Matched the form '$subject' to Halo template $templateIdText by name.")
}
$tpl = Invoke-PsaRead "/Template/$($templateIdText)?includedetails=true" 'read the ticket template' $need
$tplName = [string](Get-First $tpl @('name'))
$typeId = [string](Get-First $tpl @('tickettype_id', 'tickettypeid'))
$null = $actions.Add("Read Halo template $templateIdText ('$tplName').")

# ---- Halo: the ticket type's custom fields (field groups expanded, definitions from /FieldInfo) ----
# Verified 2026-10-16/19: field rows are links (fieldid, groupid, endusernew, technew); fieldid 0 + groupid N is a
# field group (/FieldGroup/{id}); definitions come from /FieldInfo/{id}; visibility 3 = Visible - Required.
$defs = @{}
function Get-HaloFieldDef {
    param([string]$FieldId)
    if (-not $defs.ContainsKey($FieldId)) {
        $defs[$FieldId] = $null
        try { $defs[$FieldId] = Invoke-PsaRead "/FieldInfo/$($FieldId)?includedetails=true" 'read a custom field' $need }
        catch { $null = $warnings.Add("HaloPSA field $FieldId couldn't be read, so it was left out: $($_.Exception.Message)") }
    }
    return $defs[$FieldId]
}
$rows = New-Object System.Collections.ArrayList
if ($typeId -and $typeId -ne '0') {
    $type = Invoke-PsaRead "/TicketType/$($typeId)?includedetails=true" 'read the ticket type' $need
    foreach ($tf in @(Get-PsaListReply (Get-First $type @('fields', 'field_list')) @('fields'))) {
        $fid = [string](Get-First $tf @('fieldid', 'field_id')); $gid = [string](Get-Prop $tf 'groupid')
        if ((-not $fid -or $fid -eq '0') -and $gid -and $gid -ne '0') {
            $g = $null; try { $g = Invoke-PsaRead "/FieldGroup/$($gid)?includedetails=true" 'read a field group' $need } catch { $null = $warnings.Add("Halo field group $gid couldn't be read: $($_.Exception.Message)") }
            foreach ($x in @(Get-PsaListReply (Get-First $g @('fields', 'field_list', 'fieldgroup_fields', 'fieldlist')) @('fields'))) { $null = $rows.Add(@{ row = $x; parent = $tf }) }
        }
        else { $null = $rows.Add(@{ row = $tf; parent = $null }) }
    }
}
$fields = New-Object System.Collections.ArrayList
foreach ($r in $rows) {
    $tf = $r.row
    $fid = [string](Get-First $tf @('fieldid', 'field_id')); if (-not $fid -or $fid -eq '0') { $fid = [string](Get-First $tf @('id')) }
    $eu = Get-Prop $tf 'endusernew'; if ($null -eq $eu) { $eu = Get-Prop $r.parent 'endusernew' }
    $tn = Get-Prop $tf 'technew'; if ($null -eq $tn) { $tn = Get-Prop $r.parent 'technew' }
    $def = Get-HaloFieldDef $fid
    $name = [string](Get-First $tf @('name', 'fieldname')); if (-not $name) { $name = [string](Get-First $def @('name', 'fieldname')) }
    if (-not $name) { continue }
    $label = [string](Get-First $def @('label', 'display_name')); if (-not $label) { $label = $name }
    $tv = [string](Get-First $def @('type', 'fieldtype', 'inputtype'))
    $opts = New-Object System.Collections.ArrayList
    # Assign first: Get-First hands a list back as one object, so @(Get-First ...) would nest it.
    $vals = Get-First $def @('values', 'lookup_values', 'options', 'choices')
    foreach ($v in @($vals)) {
        if ($null -eq $v -or $v -is [string]) { continue }
        $oid = [string](Get-First $v @('id', 'value_id')); $on = ([string](Get-First $v @('name', 'value', 'label', 'display'))).Trim()
        if ($on) { $null = $opts.Add(@{ id = $oid; name = $on }) }
    }
    $null = $fields.Add([ordered]@{ id = $fid; name = $name; label = $label; type = $tv; options = $opts; custom = ($name -match '^(?i)cf'); mandatory = (([string]$eu) -eq '3' -or ([string]$tn) -eq '3') })
}

# ---- the answers into Halo custom fields ----
# CloudRadial sends a multi-select answer as '"A", "B"' and a checkbox as true or false.
function Split-Choices { param([string]$s) $m = [regex]::Matches($s, '"([^"]*)"'); if ($m.Count) { return @($m | ForEach-Object { $_.Groups[1].Value.Trim() } | Where-Object { $_ }) }; return @($s -split '\s*,\s*' | Where-Object { $_ }) }
$custom = New-Object System.Collections.ArrayList
$missing = New-Object System.Collections.ArrayList
foreach ($f in $fields) {
    if (-not $f.custom) { if ($f.mandatory) { $null = $warnings.Add("Halo makes its built-in field '$($f.label)' mandatory, and a form can't fill it. Set it to Visible - Not Required in Halo, or the ticket is rejected.") }; continue }
    $ans = Get-Answer @($f.name)
    if (-not $ans) { if ($f.mandatory) { $null = $missing.Add($f.label) }; continue }
    $value = $ans
    if ($f.options.Count) {
        $picked = @(Split-Choices $ans)
        $ids = New-Object System.Collections.ArrayList
        foreach ($c in $picked) { $hit = @($f.options | Where-Object { $_.name -eq $c }); if ($hit.Count -and $hit[0].id) { $null = $ids.Add($hit[0].id) } else { $null = $warnings.Add("'$($f.label)': '$c' isn't one of Halo's values, so it was left out.") } }
        if (-not $ids.Count) { if ($f.mandatory) { $null = $missing.Add($f.label) }; continue }
        $value = ($ids -join ',')
    }
    elseif ($ans -match '^(?i)(true|false)$' -and $f.type -in @('6', 'checkbox')) { $value = ($ans -eq 'true') }
    $null = $custom.Add([ordered]@{ id = [long]$f.id; name = $f.name; value = $value })
}
if ($missing.Count) { Stop-Run 'incomplete' "Halo requires $($missing -join ', '), and the form didn't answer them. Make those questions required on the form. No ticket was created." }

# ---- the ticket ----
$ticket = [ordered]@{ summary = $(if ($subject) { $subject } else { $tplName }); details = $(if ($description) { $description } else { [string](Get-First $tpl @('details_html', 'details')) }); client_id = [long]$companyPsaId }
# The end user: the submission's Halo user id, else the client's user with that email (verified 2026-10-19: with
# neither, Halo files the ticket under its "General User").
if ($userPsaId -match '^\d+$' -and [long]$userPsaId -gt 0) { $ticket.user_id = [long]$userPsaId }
elseif ($userEmail) {
    $match = @()
    try {
        $ur = Invoke-PsaRead "/Users?client_id=$($companyPsaId)&search=$(ConvertTo-PsaQuery $userEmail)" 'look up the user' $need
        $match = @(Get-PsaListReply $ur @('users', 'records') | Where-Object { ([string](Get-First $_ @('emailaddress', 'email'))).Trim() -eq $userEmail })
    }
    catch { $null = $warnings.Add("The Halo user '$userEmail' couldn't be looked up: $($_.Exception.Message)") }
    if ($match.Count -eq 1) { $ticket.user_id = [long](Get-First $match[0] @('id')); $null = $actions.Add("Found Halo user $($ticket.user_id) by email.") }
    else { $ticket.reportedby = $userEmail; $null = $warnings.Add("No single Halo user under client $companyPsaId has the email '$userEmail', so the ticket is reported by that email and Halo files it under its general user.") }
}
foreach ($pair in @(@('tickettype_id', @('tickettype_id', 'tickettypeid')), @('priority_id', @('priority_id', 'priorityid')), @('status_id', @('status_id', 'statusid')), @('category_1', @('category_1')))) {
    $v = Get-First $tpl $pair[1]
    if ($null -ne $v -and [string]$v -and [string]$v -ne '0') { $ticket[$pair[0]] = $(if ([string]$v -match '^\d+$') { [long]$v } else { [string]$v }) }
}
# The team: Halo ignores a team name on a new ticket (verified 2026-10-19: "1st Line Support" became "New Team"),
# so the template's team is sent as team_id from Halo's team list.
$teamId = [string](Get-First $tpl @('team_id', 'teamid'))
$teamName = [string](Get-First $tpl @('team', 'team_name'))
if ((-not $teamId -or $teamId -eq '0') -and $teamName) {
    try {
        $teams = @(Get-PsaListReply (Invoke-PsaRead '/Team' 'read the teams' $need) @('teams', 'records'))
        $hit = @($teams | Where-Object { ([string](Get-First $_ @('name'))).Trim() -eq $teamName.Trim() })
        if ($hit.Count) { $teamId = [string](Get-First $hit[0] @('id')) } else { $null = $warnings.Add("Halo has no team named '$teamName', so Halo's default team was used.") }
    }
    catch { $null = $warnings.Add("Halo's teams couldn't be read, so Halo's default team was used: $($_.Exception.Message)") }
}
if ($teamId -match '^\d+$' -and [long]$teamId -gt 0) { $ticket.team_id = [long]$teamId; if ($teamName) { $ticket.team = $teamName } }
if ($custom.Count) { $ticket.customfields = @($custom) }
$plan = "Halo ticket '$($ticket.summary)' for client $companyPsaId from template $templateIdText ('$tplName'), with $($custom.Count) custom field(s): $((@($custom) | ForEach-Object { $_.name }) -join ', ')."
if (-not $confirm) {
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = 'pending_confirmation'; message = "Preview only, nothing was created. Would create the $plan"; public_note = ''; internal_note = ''; ticket_id = ''; ticket = $ticket; counts = [ordered]@{ ticketsCreated = 0; fieldsFilled = $custom.Count }; actions = @($actions); warnings = @(Get-AllWarnings) })
    return
}
$res = Invoke-Psa POST '/Tickets' @($ticket)
$newId = [string](Get-Prop @($res)[0] 'id')
if (-not $newId) { Stop-Run 'error' 'Halo answered without a ticket id, so the ticket may not have been created. Check Halo before submitting again.' }
$null = $actions.Add("Created Halo ticket $newId with $($custom.Count) custom field(s).")
$stopState.done = $true
Set-NodeOutput ([ordered]@{
        status = 'success'; message = "Created Halo ticket $newId from template '$tplName'."
        public_note = ''; internal_note = "Created from the CloudRadial form '$($ticket.summary)' by AutomationAI, using Halo template '$tplName'."
        ticket_id = $newId; counts = [ordered]@{ ticketsCreated = 1; fieldsFilled = $custom.Count }; actions = @($actions); warnings = @(Get-AllWarnings)
    })
