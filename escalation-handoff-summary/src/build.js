// Builds ../escalation-handoff-summary.yml from the files in this folder.
// Step 1 (gather.ps1) and step 3 (note.ps1) get the _shared blocks they need, filled by _shared/inject.js.
// Step 2 is an AI Prompt step built from summarize.prompt.txt and summarize.system.txt.
// Usage: node build.js          write the .yml
//        node build.js --check  exit 1 if the .yml is out of date
//        node build.js --dump   print the PowerShell steps as JSON ([{ id, script }]) for test.ps1
// Edit the files here, never the .yml. Needs js-yaml: npm install in ../../_shared, or set JS_YAML_PATH.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
let y;
try { y = require('js-yaml'); } catch {
  try { y = require(path.join(__dirname, '..', '..', '_shared', 'node_modules', 'js-yaml')); } catch { y = require(process.env.JS_YAML_PATH); }
}

const FILE = 'escalation-handoff-summary.yml';
const here = __dirname;
const root = path.join(here, '..');
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();

if (process.argv.includes('--dump')) {
  const wf0 = y.load(fs.readFileSync(path.join(root, FILE), 'utf8'));
  process.stdout.write(JSON.stringify(wf0.definition.activities.filter((a) => a.type === 'powershell-script').map((a) => ({ id: a.id, script: a.properties.script }))));
  process.exit(0);
}

function psScript(file, shared) {
  const lines = [];
  for (const b of shared) lines.push(`# >>> _shared/${b} (generated by _shared/inject.js; edit the source, not this block)`, `# <<< _shared/${b}`);
  lines.push(...read(file).split('\n'));
  const bad = lines.findIndex((l) => /[ \t]+$/.test(l) || l.includes('\t'));
  if (bad >= 0) throw new Error(`${file}: trailing whitespace or a tab (line ${bad + 1}); YAML would quote the block`);
  return lines.join('\n') + '\n';
}

const testInput = { ticketId: '1001', reason: 'Needs a network engineer', escalateTo: 'Tier 2', addNote: false, triggerSource: 'manual' };
const activities = [
  // Enable the webhook in Properties after import; AutomationAI issues the URL and secret.
  { id: 'start', name: 'Start', type: 'start', position: { x: 100, y: 120 }, properties: { webhookEnabled: false } },
  {
    id: 'node-gather', name: 'Read the ticket history', type: 'powershell-script', position: { x: 300, y: 120 },
    properties: { script: psScript('gather.ps1', ['psa.ps1', 'psa-tickets.ps1']), timeoutSeconds: 300, retryCount: 0, parameters: [], aiExtensions: [], testInput: JSON.stringify(testInput, null, 2) },
  },
  {
    id: 'node-summarize', name: 'Write the handoff summary', type: 'ai-prompt', position: { x: 500, y: 120 },
    properties: { model: '', promptTemplate: read('summarize.prompt.txt'), systemMessage: read('summarize.system.txt'), maxTokens: 1500, outputKey: 'summary', parameters: [] },
  },
  {
    id: 'node-note', name: 'Post the handoff note', type: 'powershell-script', position: { x: 700, y: 120 },
    properties: {
      script: psScript('note.ps1', ['psa.ps1']), timeoutSeconds: 300, retryCount: 0, aiExtensions: [],
      parameters: [
        { name: 'ctx', expression: '{{ nodes.node-gather.output.ctx_json }}' },
        { name: 'facts', expression: '{{ nodes.node-gather.output.facts_json }}' },
        { name: 'summary', expression: '{{ nodes.node-summarize.output.summary }}' },
      ],
    },
  },
  { id: 'end', name: 'End', type: 'end', position: { x: 900, y: 120 } },
];
const ids = activities.map((a) => a.id);
const wf = {
  automationsWorkflow: 1,
  name: 'Escalation Handoff Summary',
  description: 'When a technician escalates or hands off a ticket, reads its notes and time entries and adds one internal note summing up the problem, what was tried, where it stands and the next steps. Run from a ServiceAI Action or Quick Action. Changes nothing else on the ticket.',
  definition: { schemaVersion: 1, activities, connections: ids.slice(1).map((t, i) => ({ source: ids[i], target: t, sourceHandle: null })), startActivityId: 'start' },
};

const header = '# Generated by src/build.js from src/*. Edit the sources, not this file.\n';
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ehs-'));
const tmpFile = path.join(tmp, FILE);
fs.writeFileSync(tmpFile, header + y.dump(wf, { lineWidth: -1, noRefs: true }));
execFileSync(process.execPath, [path.join(root, '..', '_shared', 'inject.js'), tmp], { stdio: ['ignore', 'ignore', 'inherit'] });
const next = fs.readFileSync(tmpFile, 'utf8').replace(/\r\n/g, '\n');
fs.rmSync(tmp, { recursive: true, force: true });

const back = y.load(next);
const act = (id) => back.definition.activities.find((a) => a.id === id);
if (!act('node-gather').properties.script.includes('function Get-PsaTimeEntries')) throw new Error('node-gather: _shared/psa-tickets.ps1 was not injected');
if (!act('node-note').properties.script.includes('function Add-PsaNote')) throw new Error('node-note: _shared/psa.ps1 was not injected');
for (const a of back.definition.activities) {
  const s = a.properties && a.properties.script;
  if (s && /# >>> _shared\/\S+[^\n]*\n\s*# <<< _shared/.test(s)) throw new Error(`${a.id}: a shared block is empty`);
}
if (act('node-summarize').properties.model !== '') throw new Error('the AI step must leave model blank');
if (!act('node-summarize').properties.promptTemplate.includes('{{ nodes.node-gather.output.facts_json }}')) throw new Error('the prompt must bind facts_json');
if (back.definition.activities[0].properties.webhookEnabled !== false) throw new Error('webhook must ship off');
if (/\{\{\s*input\./.test(next)) throw new Error('use nodes.<id>.output bindings, never input.*');
if (/[–—]/.test(next)) throw new Error('no en or em dashes');
JSON.parse(act('node-gather').properties.testInput);

const target = path.join(root, FILE);
const was = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
if (process.argv.includes('--check')) {
  console.log(`${FILE}: ${next === was ? 'current' : 'OUT OF DATE (run node build.js)'}`);
  process.exit(next === was ? 0 : 1);
}
fs.writeFileSync(target, next);
console.log(`${FILE}: ${next === was ? 'current' : 'written'} (${next.length} bytes)`);
