# === STEP: Add portal content ===
# Edit this file, then run: node first-30-days/src/build.js
# Adds the checked setup to the client's existing CloudRadial company, with no AI: the default domain, company
# group membership, users, replacement tokens, request forms and menu tiles. Every record is checked for a
# duplicate first and skipped when it's already there, so a re-run adds nothing twice. In preview it reads
# everything and lists what it would add; only mode "live" writes. It never creates, changes or deletes the
# company or any existing record, and it reports only what CloudRadial confirmed.
# Step parameters:
#   plan   the Read the client output (company, company_id, mode)
#   setup  the Check the portal setup output (its plan holds the checked domain, group, users, tokens, forms, tiles)
# Secrets: CloudRadial-BaseUrl, CloudRadial-PublicKey, CloudRadial-PrivateKey, through the run's AutomationAI company.
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/cloudradial.ps1
# >>> _shared/company.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/company.ps1

function ConvertTo-PcObject {
    param($v)
    if ($v -is [string]) { $s = $v.Trim(); if ($s.StartsWith('{')) { try { return ($s | ConvertFrom-Json -ErrorAction Stop) } catch { } }; return $null }
    return $v
}
function Get-PcText { param($o, [string]$n) $v = Get-CrProp $o $n; if ($null -eq $v) { return '' }; return ([string]$v).Trim() }
function Get-PcRows { param($o, [string]$n) return @(@(Get-CrProp $o $n) | Where-Object { $null -ne $_ }) }
# OData string literal: double any single quote.
function Get-PcQ { param([string]$s) return "'" + $s.Replace("'", "''") + "'" }

$pc = @{ live = $false; done = New-Object System.Collections.ArrayList; skipped = New-Object System.Collections.ArrayList; failed = New-Object System.Collections.ArrayList; warnings = New-Object System.Collections.ArrayList }
$manual = New-Object System.Collections.ArrayList
foreach ($m in @('Set the logo and theme.', 'Set up messaging.', 'Link the PSA and Microsoft 365.', 'Set security roles.', 'Invite the new users or send the welcome email.')) { $null = $manual.Add($m) }

function Write-PcOutput {
    param([string]$Status, [string]$Message)
    $lines = @(@($pc.done) + @($pc.skipped | ForEach-Object { "Skipped $_" }) + @($pc.failed | ForEach-Object { "Failed $_" }))
    Set-NodeOutput ([ordered]@{
            status        = $Status
            message       = $Message
            companyId     = $(if ($companyId) { [string]$companyId } else { '' })
            mode          = $mode
            actions       = @($pc.done)
            skipped       = @($pc.skipped)
            failed        = @($pc.failed)
            warnings      = @($pc.warnings)
            manualSteps   = @($manual)
            answer        = (@($Message) + $lines) -join "`n"
            public_note   = ''
            internal_note = (@($Message) + $lines) -join "`n"
            ticket_id     = ''
        })
}
function Stop-Pc { param([string]$Why) Write-PcOutput 'error' $Why; throw $Why }

# One create. In preview it only records what it would do; in live it records the result CloudRadial gave.
function Invoke-PcCreate {
    param([string]$What, [string]$Path, $Body, $Fallback = $null, [string]$FallbackStep = '', [string]$HintWhen = '', [string]$Hint = '')
    if (-not $pc.live) { $null = $pc.done.Add("Would create $What"); return $true }
    try { $null = Invoke-CrApi -Path $Path -Method POST -Body $Body; $null = $pc.done.Add("Created $What"); return $true }
    catch {
        $err = [string]$_.Exception.Message
        # A fallback body (fewer fields) is tried once, and its manual step added when it works.
        if ($null -ne $Fallback) {
            try {
                $null = Invoke-CrApi -Path $Path -Method POST -Body $Fallback
                $null = $pc.done.Add("Created $What"); if ($FallbackStep) { $null = $manual.Add($FallbackStep) }; return $true
            }
            catch { $err = [string]$_.Exception.Message }
        }
        # One line: CloudRadial's error body arrives as indented JSON.
        $err = ($err -replace '\s+', ' ').Trim()
        if ($HintWhen -and $err -match $HintWhen) { $err = "$err $Hint" }
        $null = $pc.failed.Add("$($What): $err"); return $false
    }
}

$in = Get-NodeInput
$plan = ConvertTo-PcObject (Get-CrProp $in 'plan')
$check = ConvertTo-PcObject (Get-CrProp $in 'setup')
$companyId = 0
$mode = (Get-PcText $plan 'mode').ToLowerInvariant(); if (-not $mode) { $mode = 'preview' }
$pc.live = ($mode -eq 'live')
$idText = Get-PcText $plan 'company_id'
if (-not [int]::TryParse($idText, [ref]$companyId) -or $companyId -le 0) { Stop-Pc "Portal setup needs the CloudRadial company number from Read the client (got '$idText')." }
$want = ConvertTo-PcObject (Get-CrProp $check 'plan')
if ($null -eq $want -or (Get-PcText $check 'status') -ne 'ok') { Stop-Pc "Portal setup has no checked plan from Check the portal setup$(if (Get-PcText $check 'message') { ": $(Get-PcText $check 'message')" } else { '.' })" }

try { $null = Select-RunCompany (Get-PcText $plan 'company') } catch { Stop-Pc ([string]$_.Exception.Message) }
try { $null = Connect-Cr } catch { Stop-Pc ([string]$_.Exception.Message) }

$company = $null
try { $company = @(Get-CrAll "/v2/odata/company?`$filter=companyId eq $companyId&`$select=companyId,name") | Select-Object -First 1 } catch { Stop-Pc "Couldn't read CloudRadial company $($companyId): $($_.Exception.Message)" }
if ($null -eq $company) { Stop-Pc "CloudRadial company $companyId was not found, so nothing was added. Check company_id." }
$companyName = Get-PcText $company 'name'; if (-not $companyName) { $companyName = "company $companyId" }

# ---- default domain ----
$domain = (Get-PcText $want 'domain').ToLowerInvariant()
if ($domain) {
    try {
        $hits = @(Get-CrAll "/v2/odata/domain?`$filter=$([uri]::EscapeDataString("name eq $(Get-PcQ $domain)"))&`$select=companyDomainId,companyId,name")
        $mine = @(Get-CrAll "/v2/odata/domain?`$filter=companyId eq $companyId and isDefault eq true&`$select=companyDomainId,name")
        $here = @($hits | Where-Object { [int](Get-CrProp $_ 'companyId') -eq $companyId })
        $other = @($hits | Where-Object { [int](Get-CrProp $_ 'companyId') -ne $companyId })
        if ($here.Count) { $null = $pc.skipped.Add("domain $($domain): $companyName already has it") }
        elseif ($other.Count) { $null = $pc.skipped.Add("domain $($domain): company $(Get-CrProp $other[0] 'companyId') already has it"); $null = $pc.warnings.Add("The domain $domain belongs to another CloudRadial company ($(Get-CrProp $other[0] 'companyId')), so it wasn't added.") }
        else {
            $isDefault = ($mine.Count -eq 0)
            $null = Invoke-PcCreate "domain $domain$(if ($isDefault) { ' (default)' })" '/v2/domain' ([ordered]@{ companyId = $companyId; name = $domain; isDefault = $isDefault })
        }
    }
    catch { $null = $pc.failed.Add("domain $($domain): $($_.Exception.Message)") }
}

# ---- company group membership (never creates a group) ----
$groupName = Get-PcText $want 'companyGroup'
if ($groupName) {
    try {
        $g = @(Get-CrAll '/v2/odata/companygroup') | Where-Object { (Get-PcText $_ 'group') -ieq $groupName } | Select-Object -First 1
        if ($null -eq $g) { $null = $pc.skipped.Add("company group $($groupName): no group has that name"); $null = $pc.warnings.Add("No company group is called '$groupName', so the company wasn't added to one. Create the group first if you need it.") }
        else {
            $gid = [int](Get-CrProp $g 'companyGroupId')
            $member = @(Get-CrAll "/v2/odata/companygroupcompany?`$filter=companyId eq $companyId and companyGroupId eq $gid")
            if ($member.Count) { $null = $pc.skipped.Add("company group $($groupName): already a member") }
            else { $null = Invoke-PcCreate "membership of company group $groupName" '/v2/companygroupcompany' ([ordered]@{ companyGroupId = $gid; companyId = $companyId }) }
        }
    }
    catch { $null = $pc.failed.Add("company group $($groupName): $($_.Exception.Message)") }
}

# ---- users (an email is unique across the whole portal) ----
foreach ($u in (Get-PcRows $want 'users')) {
    $email = (Get-PcText $u 'email').ToLowerInvariant(); $name = "$(Get-PcText $u 'firstName') $(Get-PcText $u 'lastName')".Trim()
    try {
        $hit = @(Get-CrAll "/v2/odata/user?`$filter=$([uri]::EscapeDataString("email eq $(Get-PcQ $email)"))&`$select=userId,companyId,email") | Select-Object -First 1
        if ($null -ne $hit) {
            $at = [int](Get-CrProp $hit 'companyId')
            if ($at -eq $companyId) { $null = $pc.skipped.Add("user $name <$email>: already in $companyName") }
            else { $null = $pc.skipped.Add("user $name <$email>: already a user in company $at"); $null = $pc.warnings.Add("$email is already a portal user in another company ($at), so it wasn't added to $companyName.") }
            continue
        }
        # A deleted portal user keeps its email but is hidden from the list above, so the create hits a
        # database error (seen live 2026-11-09). Say so, because the error itself doesn't.
        $null = Invoke-PcCreate "user $name <$email>" '/v2/user' ([ordered]@{ companyId = $companyId; email = $email; firstName = (Get-PcText $u 'firstName'); lastName = (Get-PcText $u 'lastName') }) `
            -HintWhen '(?i)database error|already (exists|in use)|duplicate' `
            -Hint 'This email probably belongs to a deleted portal user, which still holds it. Restore that user in CloudRadial, or use another email.'
    }
    catch { $null = $pc.failed.Add("user $name <$email>: $($_.Exception.Message)") }
}

# ---- replacement tokens (POST /v2/token overwrites, so an existing token is never sent) ----
$tokenRows = Get-PcRows $want 'tokens'
if ($tokenRows.Count) {
    $have = @()
    try { $have = @(Get-CrAll "/v2/odata/token?`$filter=companyId eq $companyId&`$select=companyId,name") | ForEach-Object { Get-PcText $_ 'name' } }
    catch { $null = $pc.failed.Add("tokens: couldn't read the existing tokens, so none were added: $($_.Exception.Message)"); $tokenRows = @() }
    foreach ($t in $tokenRows) {
        $tn = (Get-PcText $t 'token').TrimStart('@')
        if (@($have | Where-Object { $_ -ceq $tn }).Count) { $null = $pc.skipped.Add("token @$($tn): already set for $companyName (left as it is)"); continue }
        if (@($have | Where-Object { $_ -ieq $tn }).Count) { $null = $pc.skipped.Add("token @$($tn): a token with the same name in different case exists"); $null = $pc.warnings.Add("Token @$tn differs only in case from an existing token, so it wasn't added. Check the name."); continue }
        $null = Invoke-PcCreate "token @$tn" '/v2/token' ([ordered]@{ companyId = $companyId; token = $tn; value = (Get-PcText $t 'value') })
    }
}

# ---- request forms ----
$formRows = Get-PcRows $want 'requestForms'
if ($formRows.Count) {
    $forms = @()
    try { $forms = @(Get-CrAll "/v2/odata/catalog?`$filter=companyId eq $companyId&`$select=companyCatalogId,subject") | ForEach-Object { Get-PcText $_ 'subject' } }
    catch { $null = $pc.failed.Add("request forms: couldn't read the existing forms, so none were added: $($_.Exception.Message)"); $formRows = @() }
    foreach ($f in $formRows) {
        $subject = Get-PcText $f 'subject'; $desc = Get-PcText $f 'description'
        if (@($forms | Where-Object { $_ -ieq $subject }).Count) { $null = $pc.skipped.Add("request form '$($subject)': already in $companyName"); continue }
        # isSelfApproval, isAppendSubject, isSendToPsa and selectText left out get other defaults from CloudRadial.
        $body = [ordered]@{ companyId = $companyId; subject = $subject; category = (Get-PcText $f 'category'); description = $desc; shortDescription = $desc; isSelfApproval = $false; isAppendSubject = $true; isSendToPsa = $true; selectText = 'REQUEST' }
        $null = Invoke-PcCreate "request form '$subject'" '/v2/catalog' $body
    }
}

# ---- menu tiles (shown to Everyone; a tile with no group may not show) ----
$tileRows = Get-PcRows $want 'menuTiles'
if ($tileRows.Count) {
    $tiles = @()
    try { $tiles = @(Get-CrAll "/v2/odata/menu?`$filter=companyId eq $companyId&`$select=companyMenuId,name") | ForEach-Object { Get-PcText $_ 'name' } }
    catch { $null = $pc.failed.Add("menu tiles: couldn't read the existing tiles, so none were added: $($_.Exception.Message)"); $tileRows = @() }
    foreach ($m in $tileRows) {
        $tname = Get-PcText $m 'name'
        if (@($tiles | Where-Object { $_ -ieq $tname }).Count) { $null = $pc.skipped.Add("menu tile '$($tname)': already in $companyName"); continue }
        $body = [ordered]@{ companyId = $companyId; name = $tname; url = (Get-PcText $m 'url'); category = (Get-PcText $m 'category'); order = 0; editRights = 0; groups = @('Everyone') }
        $plain = [ordered]@{}; foreach ($k in $body.Keys) { if ($k -ne 'groups') { $plain[$k] = $body[$k] } }
        # Some portals refuse groups on create: add the tile without it and leave a manual step.
        $null = Invoke-PcCreate "menu tile '$tname'" '/v2/menu' $body $plain "Show the menu tile '$tname' to Everyone."
    }
}

$verb = if ($pc.live) { 'Added' } else { 'Would add' }
$n = $pc.done.Count
$msg = if ($n) { "$verb $n record(s) to $companyName" } else { "Nothing to add to $companyName" }
$msg += $(if ($pc.skipped.Count) { ", $($pc.skipped.Count) already there" } else { '' }) + $(if ($pc.failed.Count) { ", $($pc.failed.Count) failed" } else { '' }) + '.'
if (-not $pc.live) { $msg += ' Preview: nothing was written.' }
$status = if ($pc.failed.Count) { 'partial' } elseif ($pc.live) { 'success' } else { 'pending_confirmation' }
Write-PcOutput $status $msg
