# === NODE: Create the forms ===
# Builds one CloudRadial form per Halo template: the PSA values (ticket type, priority, category, team,
# status) and the question types come from Halo through the first step; the AI only chose which fields a
# requester answers, their wording and the short description. Anything the AI names that Halo didn't
# have is dropped. With confirm false nothing is written and the planned forms are returned. With
# confirm true each form is created with its questions in one POST /v2/catalog, tagged
# halo-template:<id> so a rerun skips it. Never writes to Halo; never changes or deletes an existing form.
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/cloudradial.ps1
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
function Read-Json { param($v) if ($null -eq $v) { return $null }; if ($v -isnot [string]) { return $v }; if (-not $v.Trim()) { return $null }; try { return ($v | ConvertFrom-Json -NoEnumerate) } catch { return $null } }
$stopState = @{ done = $false }
$warnings = New-Object System.Collections.ArrayList
$actions = New-Object System.Collections.ArrayList
$rows = New-Object System.Collections.ArrayList
function Stop-Create {
    param([string]$Status, [string]$Why)
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = $Status; message = $Why; forms = @($rows); remaining = 0; counts = [ordered]@{ formsCreated = 0; questionsCreated = 0 }; actions = @($actions); warnings = @($warnings) })
    throw $Why
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = "Creating the forms failed: $($_.Exception.Message)"; forms = @($rows); remaining = 0; counts = [ordered]@{ formsCreated = 0; questionsCreated = 0 }; actions = @($actions); warnings = @($warnings) }) }; break }

$req = Read-Json (Get-NodeInput -Name 'request')
$planRaw = Get-NodeInput -Name 'plan'
# An empty plan ("[]") is a real answer (nothing new to move), so only a missing binding stops here.
$plan = @(Read-Json $planRaw)
if ($null -eq $req -or $null -eq $planRaw -or ($planRaw -is [string] -and -not $planRaw.Trim())) { Stop-Create 'error' 'The template details from the first step are missing. Run the workflow from the start.' }
foreach ($w in @(Read-Json (Get-NodeInput -Name 'warnings_json'))) { if ($w -and -not $warnings.Contains([string]$w)) { $null = $warnings.Add([string]$w) } }
foreach ($a in @(Read-Json (Get-NodeInput -Name 'actions_json'))) { if ($a) { $null = $actions.Add([string]$a) } }
foreach ($s in @(Read-Json (Get-NodeInput -Name 'skipped'))) { if ($null -ne $s) { $null = $rows.Add($s) } }
$remaining = 0; try { $remaining = [int](Get-NodeInput -Name 'remaining') } catch { }
$confirm = (Get-Prop $req 'confirm') -eq $true
$sendToPsa = (Get-Prop $req 'sendToPsa') -ne $false
$companyId = [int](Get-Prop $req 'companyId')
$companyName = [string](Get-Prop $req 'companyName')
$plan = @($plan | Where-Object { $null -ne $_ })
if ($confirm -and $plan.Count) { $null = Connect-Cr }

# ---- the AI's answer: {"forms": [{key, shortDescription, description, questions: [{fieldId, label, info, required}]}]} ----
$aiRaw = Get-NodeInput -Name 'judgment'
$ai = $null; $aiText = [string]$aiRaw
if ($aiRaw -and $aiRaw -isnot [string]) { $ai = $aiRaw }
elseif ($aiText -match '(?s)\{.*\}') { try { $ai = $Matches[0] | ConvertFrom-Json } catch { $ai = $null } }
$aiForms = @{}
foreach ($af in @(Get-Prop $ai 'forms')) { $k = [string](Get-Prop $af 'key'); if ($k) { $aiForms[$k] = $af } }
if ($plan.Count -and -not $aiForms.Count) { $null = $warnings.Add('The AI step returned no usable answer, so every form uses Halo''s own field labels and the template name as its description.') }

function Get-Short { param([string]$s, [int]$Max) $t = ([regex]::Replace([string]$s, '\s+', ' ')).Trim(); if ($t.Length -gt $Max) { $t = $t.Substring(0, $Max - 1).TrimEnd() + '.' }; return $t }
$typeCode = @{ text = 0; memo = 10; checkbox = 20; number = 30; date = 40; multi = 90; choice = 130 }

$created = 0; $qCreated = 0; $planned = 0; $failed = 0
foreach ($p in $plan) {
    $key = [string](Get-Prop $p 'key'); $name = [string](Get-Prop $p 'name'); $tid = [int](Get-Prop $p 'templateId')
    $af = if ($aiForms.ContainsKey($key)) { $aiForms[$key] } else { $null }
    if ($aiForms.Count -and $null -eq $af) { $null = $warnings.Add("The AI step skipped '$name', so it uses Halo's own field labels.") }
    $fields = @{}; $order = New-Object System.Collections.ArrayList
    foreach ($fd in @(Get-Prop $p 'fields')) { if ($null -eq $fd) { continue }; $fields[[string](Get-Prop $fd 'id')] = $fd; $null = $order.Add([string](Get-Prop $fd 'id')) }

    # Questions: the AI's picks, kept only when the field exists in Halo; required Halo fields are always asked.
    $picked = New-Object System.Collections.ArrayList; $seen = @{}
    if ($null -ne $af) {
        foreach ($aq in @(Get-Prop $af 'questions')) {
            $fid = [string](Get-Prop $aq 'fieldId')
            if (-not $fid -or -not $fields.ContainsKey($fid)) { if ($fid) { $null = $warnings.Add("'$name': the AI named field $fid, which the Halo template doesn't have, so it was dropped.") }; continue }
            if ($seen.ContainsKey($fid)) { continue }
            $seen[$fid] = $true; $null = $picked.Add(@{ fd = $fields[$fid]; label = [string](Get-Prop $aq 'label'); info = [string](Get-Prop $aq 'info'); required = ((Get-Prop $aq 'required') -eq $true) })
        }
    }
    foreach ($fid in $order) {
        $fd = $fields[$fid]
        if ($seen.ContainsKey($fid)) { continue }
        if ($null -eq $af -or (Get-Prop $fd 'required') -eq $true) { $seen[$fid] = $true; $null = $picked.Add(@{ fd = $fd; label = ''; info = ''; required = $false }) }
    }
    $questions = New-Object System.Collections.ArrayList; $n = 0
    foreach ($q in $picked) {
        $fd = $q.fd; $n++
        $kind = [string](Get-Prop $fd 'kind'); if (-not $typeCode.ContainsKey($kind)) { $kind = 'text' }
        $label = Get-Short $(if ($q.label) { $q.label } else { [string](Get-Prop $fd 'label') }) 80
        if (-not $label) { $label = [string](Get-Prop $fd 'name') }
        $null = $questions.Add([ordered]@{
                label = $label; info = (Get-Short $q.info 200); options = ((@(Get-Prop $fd 'options') | Where-Object { $_ }) -join ',')
                placeholder = ''; type = $typeCode[$kind]; isRequired = ($q.required -or (Get-Prop $fd 'required') -eq $true)
                isSubject = $false; isDescription = $false; order = $n * 10; defaultValue = ''
                jsonId = [string](Get-Prop $fd 'name'); isIncludeInTicket = $true; isUserLookup = $false
                customFieldName = [string](Get-Prop $fd 'name'); hideConditions = @()
            })
    }
    # Always a free-text box last, so the requester can add detail; it becomes the ticket description.
    $null = $questions.Add([ordered]@{ label = 'Anything else we should know?'; info = ''; options = ''; placeholder = ''; type = 10; isRequired = $false; isSubject = $false; isDescription = $true; order = ($n + 1) * 10; defaultValue = ''; jsonId = 'details'; isIncludeInTicket = $true; isUserLookup = $false; customFieldName = ''; hideConditions = @() })

    $short = Get-Short ([string](Get-Prop $af 'shortDescription')) 120
    if (-not $short) { $short = Get-Short $(if (Get-Prop $p 'summary') { [string](Get-Prop $p 'summary') } else { $name }) 120 }
    $desc = [string](Get-Prop $p 'description')
    if (-not $desc.Trim()) { $plain = Get-Short ([string](Get-Prop $af 'description')) 600; $desc = if ($plain) { [System.Net.WebUtility]::HtmlEncode($plain) } else { [System.Net.WebUtility]::HtmlEncode($short) } }
    $psa = Get-Prop $p 'psa'
    $val = { param([string]$v, [string]$Default) if ($v.Trim()) { return $v.Trim() }; return $Default }
    $usage = [string](Get-Prop $p 'usage')
    $body = [ordered]@{
        companyId = $companyId; catalogUsage = $(if ($usage -eq 'problem') { 0 } else { 10 })
        category = [string](Get-Prop $p 'category'); subject = $name; shortDescription = $short; description = $desc
        selectText = $(if ($usage -eq 'problem') { 'REPORT' } else { 'REQUEST' })
        isSendToPsa = $sendToPsa; isIncludeDescription = $true; isAppendSubject = $true
        # Unverified: how CloudRadial maps these names onto a Halo ticket (check one live submission).
        psaType = (& $val ([string](Get-Prop $psa 'type')) ''); psaPriority = (& $val ([string](Get-Prop $psa 'priority')) '@DefaultPriority')
        psaCategory = (& $val ([string](Get-Prop $psa 'category')) ''); psaBoard = (& $val ([string](Get-Prop $psa 'board')) '@DefaultBoard')
        psaStatus = (& $val ([string](Get-Prop $psa 'status')) '@DefaultStatus')
        groups = @([ordered]@{ groupName = 'Everyone' }); tags = @([ordered]@{ tag = "halo-template:$tid" })
        questions = @($questions)
    }
    $row = [ordered]@{ templateId = $tid; template = $name; form = $(if ($usage -eq 'problem') { 'Problem Report' } else { 'Service Request' }); category = $body.category; action = ''; catalogId = 0; questions = $questions.Count; note = '' }
    if (-not $confirm) {
        $row.action = 'planned'; $planned++
        $row.note = "Questions: $((@($questions) | ForEach-Object { $_.label }) -join '; ')"
        $null = $rows.Add($row); continue
    }
    try {
        $r = Invoke-CrApi -Path '/v2/catalog' -Method POST -Body $body
        # The reply may be wrapped in {data: ...}.
        $data = Get-CrProp $r 'data'; if ($null -eq $data) { $data = $r }
        $cid = Get-CrId $data @('companyCatalogId', 'id')
        $row.catalogId = $cid; $row.action = 'created'; $created++
        $back = @(@(Get-CrProp $data 'questions') | Where-Object { $null -ne $_ })
        # Verified 2026-10-16: the inline create keeps only each question's label, type and order. Options, hint,
        # required, the description flag, jsonId and customFieldName are set afterwards with one PATCH per question.
        $fixFailed = 0; $missing = 0
        foreach ($q in $questions) {
            $ops = New-Object System.Collections.ArrayList
            foreach ($k in @('info', 'options', 'jsonId', 'customFieldName')) { if ([string]$q[$k]) { $null = $ops.Add([ordered]@{ op = 'replace'; path = "/$k"; value = [string]$q[$k] }) } }
            if ($q.isRequired) { $null = $ops.Add([ordered]@{ op = 'replace'; path = '/isRequired'; value = $true }) }
            if ($q.isDescription) { $null = $ops.Add([ordered]@{ op = 'replace'; path = '/isDescription'; value = $true }) }
            if (-not $ops.Count) { continue }
            $match = $null; foreach ($bq in $back) { if ([int](Get-CrProp $bq 'order') -eq [int]$q.order) { $match = $bq; break } }
            $qid = Get-CrId $match @('companyCatalogQuestionId', 'id')
            if (-not $qid) { $missing++; continue }
            try { $null = Invoke-CrApi -Path "/v2/catalogquestion/$($qid)?companyId=$companyId" -Method PATCH -Body (ConvertTo-Json -InputObject @($ops) -Depth 5 -Compress) }
            catch { $fixFailed++; $null = $warnings.Add("'$name' (form $cid): the details of question '$($q.label)' weren't saved: $($_.Exception.Message)") }
        }
        if ($back.Count -lt $questions.Count -or $missing -or $fixFailed) {
            $row.action = 'incomplete'
            $row.note = "CloudRadial saved $($back.Count) of $($questions.Count) questions$(if ($missing -or $fixFailed) { "; $($missing + $fixFailed) question(s) are missing their options or settings" }). Check form $cid."
            $null = $warnings.Add("'$name' (form $cid): $($row.note)")
        }
        $qCreated += $back.Count
        $null = $actions.Add("Created form '$name' ($cid) with $($questions.Count) question(s).")
    }
    catch {
        $row.action = 'error'; $row.note = [string]$_.Exception.Message; $failed++
        $null = $warnings.Add("'$name' wasn't created: $($_.Exception.Message)")
    }
    $null = $rows.Add($row)
}

$skippedCount = @($rows | Where-Object { (Get-Prop $_ 'action') -eq 'skipped' }).Count
$more = if ($remaining) { " $remaining more template(s) are left: run it again to move the next batch." } else { '' }
$status = 'success'
if (-not $plan.Count) { $msg = "Nothing new to move into '$companyName'. $skippedCount template(s) were already there or skipped." }
elseif (-not $confirm) { $status = 'pending_confirmation'; $msg = "Preview only, nothing was created. Would create $planned form(s) in '$companyName'.$more" }
else {
    if ($failed -and -not $created) { $status = 'error' } elseif ($failed -or @($rows | Where-Object { (Get-Prop $_ 'action') -eq 'incomplete' }).Count) { $status = 'incomplete' }
    $msg = "Created $created form(s) in '$companyName'$(if ($failed) { "; $failed failed" }). Review them, then add them to a package in Partner > Content and publish.$more"
}
$stopState.done = $true
Set-NodeOutput ([ordered]@{
        status = $status; message = $msg; forms = @($rows); remaining = $remaining
        counts = [ordered]@{ formsCreated = $created; questionsCreated = $qCreated; formsPlanned = $planned; formsSkipped = $skippedCount; formsFailed = $failed }
        actions = @($actions); warnings = @($warnings)
    })
