# === NODE: Read the Halo templates ===
# Reads the HaloPSA ticket templates, each with its ticket type, priority, category, team and status
# names and the custom fields a requester could answer. Templates already moved into the CloudRadial
# company (a form tagged halo-template:<id>) are skipped, so a rerun picks up only new ones.
# Read-only: this step writes nothing to Halo or CloudRadial.
# Input: {"companyId": 1, "confirm": false, "templateIds": [12, 15], "search": "", "maxTemplates": 10,
#         "includeInactive": false, "usage": "auto", "category": "", "sendToPsa": true}
# Unverified until read from a real Halo instance: the template, ticket type and field property names
# (tickettype_id, priority_id, category_1, team, status_id, inactive, group name, fields, field type numbers).
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/cloudradial.ps1
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
# The first of -Names that has a value. A list counts when it has items (cast to text, a list of objects looks blank).
function Get-First {
    param($o, [string[]]$Names)
    foreach ($n in $Names) {
        $v = Get-Prop $o $n
        if ($null -eq $v) { continue }
        if ($v -is [string]) { if (-not [string]::IsNullOrWhiteSpace($v)) { return $v }; continue }
        if ($v -is [System.Collections.IList]) { if ($v.Count) { return , $v }; continue }
        return $v
    }
    return $null
}
$stopState = @{ done = $false }
$warnings = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    param($Own)
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($Own) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
function Stop-Run {
    param([string]$Status, [string]$Why)
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = $Status; message = $Why; forms = @(); remaining = 0; actions = @(); warnings = @(Get-AllWarnings $warnings) })
    throw $Why
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = "Reading the Halo templates failed: $($_.Exception.Message) Nothing was created."; forms = @(); remaining = 0; actions = @(); warnings = @(Get-AllWarnings $warnings) }) }; break }

# ---- the run input ----
$raw = Get-NodeInput
if ($null -eq $raw) { Stop-Run 'incomplete' 'No input was received. Send at least companyId, the CloudRadial company the forms go into.' }
if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The input was text that is not valid JSON.' } }
$wrap = Get-Prop $raw 'trigger'; if ($null -ne $wrap) { $raw = $wrap; if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The trigger body was text that is not valid JSON.' } } }
function Get-Field {
    param([string[]]$Names)
    foreach ($n in $Names) {
        $v = Get-Prop $raw $n
        if ($null -eq $v -or $v -is [System.Management.Automation.PSCustomObject] -or $v -is [System.Collections.IDictionary] -or $v -is [array]) { continue }
        $s = ([string]$v).Trim()
        if (-not $s -or $s.StartsWith('@') -or $s -match '^\{\{.*\}\}$' -or $s -match '^<[^>]*>$') { continue }
        return $s
    }
    return ''
}
function Get-Flag { param([string[]]$Names, [bool]$Default) $s = (Get-Field $Names).ToLowerInvariant(); if (-not $s) { return $Default }; return (@('true', 'yes', '1', 'y') -contains $s) }

$f = [ordered]@{
    companyId       = 0
    companyName     = ''
    confirm         = (Get-Flag @('confirm', 'approvedToWrite') $false)
    templateIds     = @()
    search          = (Get-Field @('search'))
    maxTemplates    = 10
    includeInactive = (Get-Flag @('includeInactive') $false)
    usage           = (Get-Field @('usage')).ToLowerInvariant()
    category        = (Get-Field @('category'))
    sendToPsa       = (Get-Flag @('sendToPsa') $true)
}
$s = Get-Field @('companyId', 'company_id')
if ($s -and $s -notmatch '^\d+$') { Stop-Run 'incomplete' "companyId must be a CloudRadial company number; '$s' isn't. Nothing was read." }
if ($s) { $f.companyId = [int]$s }
if ($f.companyId -le 0) { Stop-Run 'incomplete' 'companyId is missing. Send the CloudRadial company number the forms go into (your own company, so you can review them and add them to a package). Nothing was read.' }
if (-not $f.usage) { $f.usage = 'auto' }
if (@('auto', 'request', 'problem') -notcontains $f.usage) { Stop-Run 'incomplete' "usage must be auto, request or problem; '$($f.usage)' isn't. Nothing was read." }
$s = Get-Field @('maxTemplates')
if ($s) { if ($s -notmatch '^\d+$' -or [int]$s -lt 1 -or [int]$s -gt 25) { Stop-Run 'incomplete' "maxTemplates must be a whole number from 1 to 25; '$s' isn't. Nothing was read." }; $f.maxTemplates = [int]$s }
$ids = Get-Prop $raw 'templateIds'
if ($null -ne $ids) {
    $list = if ($ids -is [string]) { @($ids -split '[,;\s]+') } else { @($ids) }
    foreach ($i in $list) { $t = ([string]$i).Trim(); if (-not $t) { continue }; if ($t -notmatch '^\d+$') { Stop-Run 'incomplete' "templateIds must be Halo template numbers; '$t' isn't. Nothing was read." }; $f.templateIds += [int]$t }
}

# ---- CloudRadial: the company, and the forms already moved ----
$actions = New-Object System.Collections.ArrayList
$null = Connect-Cr
$co = @(Get-CrAll "/v2/odata/company?`$filter=companyId eq $($f.companyId)&`$select=companyId,name")
if (-not $co.Count) { Stop-Run 'incomplete' "CloudRadial has no company $($f.companyId). Check the companyId. Nothing was read." }
$f.companyName = [string](Get-CrProp $co[0] 'name')
$existing = @(Get-CrAll "/v2/odata/catalog?`$filter=companyId eq $($f.companyId)&`$select=companyCatalogId,subject,tags")
$moved = @{}; $subjects = @{}
foreach ($c in $existing) {
    $tags = Get-CrProp $c 'tags'
    $tagText = if ($tags -is [string]) { $tags } else { (@($tags) | ForEach-Object { if ($_ -is [string]) { $_ } else { [string](Get-CrProp $_ 'tag') } }) -join ' ' }
    foreach ($m in [regex]::Matches([string]$tagText, 'halo-template:(\d+)')) { $moved[$m.Groups[1].Value] = [int](Get-CrProp $c 'companyCatalogId') }
    $subj = ([string](Get-CrProp $c 'subject')).Trim().ToLowerInvariant(); if ($subj) { $subjects[$subj] = [int](Get-CrProp $c 'companyCatalogId') }
}
$null = $actions.Add("Read $($existing.Count) existing form(s) in CloudRadial company '$($f.companyName)'.")

# ---- Halo: the template list ----
$null = Connect-Psa -Psa 'halopsa'
$need = 'read ticket templates, ticket types, custom fields and lookups'
$all = New-Object System.Collections.ArrayList
$q = if ($f.search) { "&search=$(ConvertTo-PsaQuery $f.search)" } else { '' }
for ($p = 1; $p -le 40; $p++) {
    $r = Invoke-PsaRead "/Template?pageinate=true&page_size=50&page_no=$p$q" 'read the ticket templates' $need
    $rows = @(Get-PsaListReply $r @('templates', 'records', 'data'))
    foreach ($t in $rows) { $null = $all.Add($t) }
    $total = Get-Prop $r 'record_count'
    if ($rows.Count -lt 50 -or ($null -ne $total -and $all.Count -ge [int]$total)) { break }
}
$null = $actions.Add("Read $($all.Count) ticket template(s) from HaloPSA.")
if (-not $all.Count) { Stop-Run 'incomplete' 'HaloPSA returned no ticket templates. Check that the API application can read templates. Nothing was created.' }

$skipped = New-Object System.Collections.ArrayList
$todo = New-Object System.Collections.ArrayList
foreach ($t in $all) {
    $tid = [string](Get-First $t @('id', 'template_id'))
    $name = ([string](Get-First $t @('name', 'templatename', 'summary'))).Trim()
    if (-not $tid -or -not $name) { continue }
    if ($f.templateIds.Count -and $f.templateIds -notcontains [int]$tid) { continue }
    if (-not $f.includeInactive -and (Get-Prop $t 'inactive') -eq $true) { $null = $skipped.Add([ordered]@{ templateId = [int]$tid; template = $name; action = 'skipped'; catalogId = 0; questions = 0; note = 'Inactive in HaloPSA.' }); continue }
    if ($moved.ContainsKey($tid)) { $null = $skipped.Add([ordered]@{ templateId = [int]$tid; template = $name; action = 'skipped'; catalogId = $moved[$tid]; questions = 0; note = 'Already moved.' }); continue }
    if ($subjects.ContainsKey($name.ToLowerInvariant())) { $null = $skipped.Add([ordered]@{ templateId = [int]$tid; template = $name; action = 'skipped'; catalogId = $subjects[$name.ToLowerInvariant()]; questions = 0; note = 'A form with this name already exists in the company, so it was left alone.' }); continue }
    $null = $todo.Add(@{ id = $tid; name = $name })
}
foreach ($i in $f.templateIds) { if (-not @($all | Where-Object { [string](Get-First $_ @('id', 'template_id')) -eq [string]$i }).Count) { $null = $warnings.Add("Halo template $i wasn't found, so it was skipped.") } }
$batch = @($todo | Select-Object -First $f.maxTemplates)
$remaining = [Math]::Max(0, $todo.Count - $batch.Count)
if (-not $batch.Count) {
    $msg = "Nothing new to move: every matching Halo template is already in '$($f.companyName)', inactive, or named like an existing form."
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = 'ok'; facts_json = '{"skip": true}'; plan_json = '[]'; request_json = ($f | ConvertTo-Json -Depth 5 -Compress); skipped_json = (ConvertTo-Json -InputObject @($skipped) -Depth 5 -Compress); remaining = 0; message = $msg; warnings_json = (ConvertTo-Json -InputObject @(Get-AllWarnings $warnings) -Compress); actions_json = (ConvertTo-Json -InputObject @($actions) -Compress) })
    return
}

# ---- Halo: lookups, read once ----
$lookups = @{ priority = @{}; status = @{}; types = @{}; fields = @{} }
function Read-Lookup {
    param([string]$Path, [string[]]$Holders, [string[]]$IdNames, [string]$What)
    $map = @{}
    try {
        foreach ($row in @(Get-PsaListReply (Invoke-PsaRead $Path "read the $What" $need) $Holders)) {
            $lid = [string](Get-First $row $IdNames); $lname = [string](Get-First $row @('name', 'description'))
            if ($lid -and $lname -and -not $map.ContainsKey($lid)) { $map[$lid] = $lname }
        }
    }
    catch { $null = $warnings.Add("HaloPSA wouldn't list its $What, so those names were left to CloudRadial's defaults: $($_.Exception.Message)") }
    return $map
}
$lookups.priority = Read-Lookup '/Priority' @('priorities', 'records') @('priorityid', 'id') 'priorities'
$lookups.status = Read-Lookup '/Status' @('statuses', 'records') @('id') 'statuses'

function Get-HaloType {
    param([string]$TypeId)
    if (-not $TypeId -or $TypeId -eq '0') { return $null }
    if (-not $lookups.types.ContainsKey($TypeId)) { $lookups.types[$TypeId] = Invoke-PsaRead "/TicketType/$($TypeId)?includedetails=true" 'read a ticket type' $need }
    return $lookups.types[$TypeId]
}
function Get-HaloField {
    param([string]$FieldId)
    if (-not $lookups.fields.ContainsKey($FieldId)) {
        $lookups.fields[$FieldId] = $null
        try { $lookups.fields[$FieldId] = Invoke-PsaRead "/Field/$($FieldId)?includedetails=true" 'read a custom field' $need } catch { $null = $warnings.Add("HaloPSA field $FieldId couldn't be read, so it became a text question: $($_.Exception.Message)") }
    }
    return $lookups.fields[$FieldId]
}
# Halo field types to a plain kind. Unverified: Halo's type numbers; names are matched too.
function Get-FieldKind {
    param($Field, $Def)
    $tv = Get-First $Field @('type', 'fieldtype', 'inputtype'); if ($null -eq $tv -and $null -ne $Def) { $tv = Get-First $Def @('type', 'fieldtype', 'inputtype') }
    $tn = ([string](Get-First $Field @('type_name', 'typename'))).ToLowerInvariant(); if (-not $tn -and $null -ne $Def) { $tn = ([string](Get-First $Def @('type_name', 'typename'))).ToLowerInvariant() }
    if ($tn -match 'multi') { return 'multi' }
    if ($tn -match 'select|single|lookup|drop') { return 'choice' }
    if ($tn -match 'memo|rich|multi.?line|text ?area') { return 'memo' }
    if ($tn -match 'date') { return 'date' }
    if ($tn -match 'check|bool|tick') { return 'checkbox' }
    if ($tn -match 'number|integer|decimal|money') { return 'number' }
    if ($tn -match 'text|string') { return 'text' }
    switch ([string]$tv) { '0' { return 'text' } '1' { return 'memo' } '2' { return 'choice' } '3' { return 'multi' } '4' { return 'date' } '5' { return 'text' } '6' { return 'checkbox' } '8' { return 'memo' } '9' { return 'number' } }
    return ''
}
function Get-FieldOptions {
    param($Field, $Def)
    $vals = $null
    foreach ($src in @($Field, $Def)) { if ($null -eq $src) { continue }; foreach ($n in @('values', 'lookup_values', 'options', 'choices')) { $v = Get-Prop $src $n; if ($null -ne $v -and @($v).Count) { $vals = @($v); break } }; if ($null -ne $vals) { break } }
    $out = New-Object System.Collections.ArrayList
    foreach ($v in @($vals)) {
        if ($null -eq $v) { continue }
        $label = if ($v -is [string]) { $v } else { [string](Get-First $v @('name', 'value', 'label', 'display')) }
        # CloudRadial separates options with commas, so a comma inside an option becomes a space.
        $label = ($label -replace ',', ' ' -replace '\s+', ' ').Trim()
        if ($label -and -not $out.Contains($label)) { $null = $out.Add($label) }
    }
    return @($out)
}
# Text for the AI and for the form: HTML tags out, whitespace tidied.
function ConvertTo-Plain { param([string]$Html, [int]$Max) $t = [regex]::Replace([string]$Html, '(?is)<(script|style)[^>]*>.*?</\1>', ' '); $t = [regex]::Replace($t, '(?i)<br\s*/?>|</p>|</li>|</div>', "`n"); $t = [regex]::Replace($t, '<[^>]+>', ' '); $t = [System.Net.WebUtility]::HtmlDecode($t); $t = [regex]::Replace($t, '[ \t]+', ' '); $t = [regex]::Replace($t, '\s*\n\s*', "`n").Trim(); if ($Max -gt 0 -and $t.Length -gt $Max) { $t = $t.Substring(0, $Max) }; return $t }
# The template's own HTML, safe to show in the portal: scripts, styles, event handlers and javascript: links removed.
function ConvertTo-SafeHtml { param([string]$Html) $h = [regex]::Replace([string]$Html, '(?is)<(script|style|iframe|object|embed)[^>]*>.*?</\1>', ''); $h = [regex]::Replace($h, '(?is)<(script|iframe|object|embed)[^>]*/?>', ''); $h = [regex]::Replace($h, '(?i)\s+on[a-z]+\s*=\s*("[^"]*"|''[^'']*''|[^\s>]+)', ''); $h = [regex]::Replace($h, '(?i)(href|src)\s*=\s*("|'')\s*javascript:[^"'']*\2', '$1=$2#$2'); return $h.Trim() }
# Halo built-in fields the template or CloudRadial already covers: never asked.
$systemFields = @('summary', 'details', 'user', 'user_id', 'client', 'client_id', 'site', 'site_id', 'status', 'status_id', 'priority', 'priority_id', 'category_1', 'category_2', 'category_3', 'category_4', 'team', 'agent', 'agent_id', 'sla', 'sla_id', 'impact', 'urgency', 'tickettype', 'tickettype_id', 'attachments', 'emailtolist', 'emailcclist')

$plan = New-Object System.Collections.ArrayList
$facts = New-Object System.Collections.ArrayList
foreach ($b in $batch) {
    $t = Invoke-PsaRead "/Template/$($b.id)?includedetails=true" 'read a ticket template' $need
    $typeId = [string](Get-First $t @('tickettype_id', 'tickettypeid'))
    $type = $null
    try { $type = Get-HaloType $typeId } catch { $null = $warnings.Add("Template '$($b.name)': its ticket type $typeId couldn't be read, so it has no type-specific questions: $($_.Exception.Message)") }
    $typeName = [string](Get-First $t @('tickettype_name', 'tickettypename')); if (-not $typeName -and $null -ne $type) { $typeName = [string](Get-First $type @('name')) }
    $prioId = [string](Get-First $t @('priority_id', 'priorityid'))
    $prio = if ($prioId -and $lookups.priority.ContainsKey($prioId)) { $lookups.priority[$prioId] } else { [string](Get-First $t @('priority_name', 'priority')) }
    $statusId = [string](Get-First $t @('status_id', 'statusid'))
    $statusName = if ($statusId -and $lookups.status.ContainsKey($statusId)) { $lookups.status[$statusId] } else { [string](Get-First $t @('status_name')) }
    $team = [string](Get-First $t @('team', 'team_name'))
    $cat1 = [string](Get-First $t @('category_1', 'category1'))
    $group = [string](Get-First $t @('templategroup_name', 'group_name', 'templategroup'))

    # Request or problem: an incident-style ticket type becomes a Problem Report. Unverified: Halo's
    # ITIL type field and numbers (1 = incident, 4 = problem); the type name is checked too.
    $usage = $f.usage
    if ($usage -eq 'auto') {
        $itil = [string](Get-First $type @('itil_requesttype_id', 'itil_ticket_type', 'itiltype'))
        $usage = if ($itil -in @('1', '4') -or ($typeName + ' ' + $b.name) -match '(?i)\b(incident|problem|fault|issue|outage|broken|error|not working)\b') { 'problem' } else { 'request' }
    }

    # Fixed values the template sets: those fields aren't asked.
    $fixed = @{}
    foreach ($cf in @(Get-PsaListReply (Get-Prop $t 'customfields') @('customfields'))) {
        $cfName = [string](Get-First $cf @('name')); $val = Get-First $cf @('value', 'display')
        if ($cfName -and $null -ne $val -and -not [string]::IsNullOrWhiteSpace([string]$val)) { $fixed[$cfName.ToLowerInvariant()] = $true }
    }
    $fields = New-Object System.Collections.ArrayList
    $typeFields = if ($null -ne $type) { @(Get-PsaListReply (Get-First $type @('fields', 'field_list')) @('fields')) } else { @() }
    foreach ($tf in $typeFields) {
        if ($fields.Count -ge 30) { $null = $warnings.Add("Template '$($b.name)': only the first 30 fields were offered as questions."); break }
        $fid = [string](Get-First $tf @('fieldid', 'field_id', 'id'))
        $fname = [string](Get-First $tf @('name', 'fieldname'))
        $inner = Get-Prop $tf 'field'
        if (-not $fname -and $null -ne $inner) { $fname = [string](Get-First $inner @('name')) }
        if (-not $fid -or -not $fname) { continue }
        $lname = $fname.ToLowerInvariant()
        # Only custom fields (Halo names them CF...), never the built-in ones or the ones the template fixes.
        if ($systemFields -contains $lname -or $lname -notmatch '^cf' -or $fixed.ContainsKey($lname)) { continue }
        if ((Get-Prop $tf 'visible') -eq $false -or (Get-Prop $tf 'hidden') -eq $true -or (Get-Prop $tf 'usercanedit') -eq $false) { continue }
        $def = $inner
        $kind = Get-FieldKind $tf $def
        $opts = @(Get-FieldOptions $tf $def)
        if (-not $kind -or (($kind -eq 'choice' -or $kind -eq 'multi') -and -not $opts.Count)) { $def = Get-HaloField $fid; if ($null -ne $def) { if (-not $kind) { $kind = Get-FieldKind $tf $def }; if (-not $opts.Count) { $opts = @(Get-FieldOptions $tf $def) } } }
        if (-not $kind) { $kind = 'text'; $null = $warnings.Add("Template '$($b.name)': field '$fname' has a type this workflow doesn't know, so it became a text question.") }
        if (($kind -eq 'choice' -or $kind -eq 'multi') -and -not $opts.Count) { $kind = 'text'; $null = $warnings.Add("Template '$($b.name)': field '$fname' is a list with no values, so it became a text question.") }
        $label = [string](Get-First $tf @('label', 'display_name', 'displayname')); if (-not $label -and $null -ne $def) { $label = [string](Get-First $def @('label', 'display_name')) }; if (-not $label) { $label = $fname }
        $null = $fields.Add([ordered]@{ id = $fid; name = $fname; label = $label.Trim(); kind = $kind; options = @($opts); required = ((Get-First $tf @('mandatory', 'required', 'isrequired')) -eq $true) })
    }

    $details = [string](Get-First $t @('details_html', 'details'))
    $key = "t$($b.id)"
    $null = $plan.Add([ordered]@{
            key = $key; templateId = [int]$b.id; name = $b.name; usage = $usage
            category = $(if ($f.category) { $f.category } elseif ($group) { $group } elseif ($typeName) { $typeName } else { 'General' })
            description = (ConvertTo-SafeHtml $details); summary = (ConvertTo-Plain ([string](Get-First $t @('summary'))) 200)
            psa = [ordered]@{ type = $typeName; priority = $prio; category = $cat1; board = $team; status = $statusName }
            fields = @($fields)
        })
    $null = $facts.Add([ordered]@{
            key = $key; name = $b.name; ticketType = $typeName; kind = $usage
            summary = (ConvertTo-Plain ([string](Get-First $t @('summary'))) 200); details = (ConvertTo-Plain $details 600)
            fields = @($fields | ForEach-Object { [ordered]@{ id = $_.id; label = $_.label; kind = $_.kind; required = $_.required; options = @($_.options | Select-Object -First 10) } })
        })
}
$null = $actions.Add("Read $($plan.Count) template(s) in detail from HaloPSA$(if ($remaining) { "; $remaining more are left for the next run" }).")

$stopState.done = $true
Set-NodeOutput ([ordered]@{
        status        = 'ok'
        facts_json    = (ConvertTo-Json -InputObject ([ordered]@{ company = $f.companyName; forms = @($facts) }) -Depth 8 -Compress)
        plan_json     = (ConvertTo-Json -InputObject @($plan) -Depth 8 -Compress)
        request_json  = ($f | ConvertTo-Json -Depth 5 -Compress)
        skipped_json  = (ConvertTo-Json -InputObject @($skipped) -Depth 5 -Compress)
        remaining     = $remaining
        message       = "Read $($plan.Count) Halo template(s) to move into '$($f.companyName)'."
        warnings_json = (ConvertTo-Json -InputObject @(Get-AllWarnings $warnings) -Compress)
        actions_json  = (ConvertTo-Json -InputObject @($actions) -Compress)
    })
