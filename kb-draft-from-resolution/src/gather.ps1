# === NODE: Read the resolution ===
# Reads the ticket and how it was resolved, then takes client and personal details out before anything
# reaches the AI step. The resolution text comes from, in order: the resolutionNotes input; the ticket's
# own resolution field (Autotask resolution, HaloPSA clearance note, Kaseya BMS Resolution); ConnectWise
# notes flagged as the resolution; otherwise the newest technician notes.
# Stops quietly when a draft was already made from this ticket. Fails closed when there is too little
# resolution text to write an article from.
# Accepts a flat {key:value} body (PSA webhook, ServiceAI Action, manual run), the CloudRadial
# {Ticket:{...}, Company:{...}} shape, or either one wrapped in {trigger:...}.
# Read-only: this step never writes to the PSA or CloudRadial.
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
# >>> _shared/psa-tickets.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa-tickets.ps1
# @@ src/scrub.ps1 @@
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
$stopState = @{ done = $false }
$warnings = New-Object System.Collections.ArrayList
$actions = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    param($Own)
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($Own) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
function Stop-Run {
    param([string]$Status, [string]$Why, [string]$TicketId = '')
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{
            status = $Status; message = $Why; public_note = ''
            internal_note = "No knowledge base draft was made: $Why"
            ticket_id = $TicketId; actions = @(); warnings = @(Get-AllWarnings $warnings)
        })
    throw $Why
}
# A quiet stop (already drafted): the later steps see skip and the run ends with success.
function Skip-Run {
    param([string]$Why)
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = 'ok'; facts_json = '{"skip": true}'; ctx_json = ([ordered]@{ skip = $Why; number = $f.ticketId; actions = @($actions); warnings = @(Get-AllWarnings $warnings) } | ConvertTo-Json -Depth 5 -Compress) })
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = [string]$_.Exception.Message; public_note = ''; internal_note = "The knowledge base draft failed while reading the ticket: $($_.Exception.Message) Nothing was saved."; ticket_id = ''; actions = @(); warnings = @(Get-AllWarnings $warnings) }) }; break }

$raw = Get-NodeInput
if ($null -eq $raw) { Stop-Run 'incomplete' 'No input was received. Send at least ticketId.' }
if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The input was text that is not valid JSON.' } }
$wrap = Get-Prop $raw 'trigger'; if ($null -ne $wrap) { $raw = $wrap; if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The trigger body was text that is not valid JSON.' } } }
$answers = @{}
if ($raw -is [System.Collections.IDictionary]) { foreach ($k in @($raw.Keys)) { $answers[[string]$k] = $raw[$k] } }
else { foreach ($p in $raw.PSObject.Properties) { $answers[$p.Name] = $p.Value } }
$crTicket = Get-Prop $raw 'Ticket'
if ($null -ne $crTicket) {
    foreach ($q in @(Get-Prop $crTicket 'Questions')) { $qid = [string](Get-Prop $q 'Id'); if ($qid) { $answers[$qid] = Get-Prop $q 'Value' } }
    $tid = Get-Prop $crTicket 'TicketId'; if ($null -ne $tid) { $answers['ticketId'] = $tid }
}
function Get-Field {
    param([string[]]$Names)
    foreach ($n in $Names) {
        if (-not $answers.ContainsKey($n)) { continue }
        $v = $answers[$n]
        if ($null -eq $v -or $v -is [System.Management.Automation.PSCustomObject] -or $v -is [System.Collections.IDictionary]) { continue }
        $s = ([string]$v).Trim()
        # A bare @token (an unfilled CloudRadial placeholder) counts as not given.
        if (-not $s -or $s -match '^@[A-Za-z][A-Za-z0-9_]*$' -or $s -match '^\{\{.*\}\}$' -or $s -match '^<[^>]*>$') { continue }
        return $s
    }
    return ''
}
function Get-Flag { param([string[]]$Names, [bool]$Default) $s = (Get-Field $Names).ToLowerInvariant(); if (-not $s) { return $Default }; return (@('true', 'yes', '1', 'y') -contains $s) }

$f = [ordered]@{
    ticketId   = (Get-Field @('ticketId', 'ticket_id', 'TicketId', 'ticketNumber', 'id'))
    psa        = (Get-Field @('psa'))
    confirm    = (Get-Flag @('confirm', 'approvedToWrite') $false)
    resolution = (Get-Field @('resolutionNotes', 'resolution_notes', 'resolution'))
    category   = (Get-Field @('category'))
}
if (-not $f.ticketId) { Stop-Run 'incomplete' 'ticketId is missing. Send the PSA ticket number of the resolved ticket. Nothing was read.' }

$conn = Connect-Psa -Psa (Get-PsaType $f.psa)
$f.psa = $conn.Psa
$psaName = Get-PsaName
$id = ''
try { $id = Resolve-PsaTicketId $f.ticketId } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) wasn't found in $($psaName): $($_.Exception.Message)" $f.ticketId }
$t = $null
try { $t = Get-PsaTicket -Id $id } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) couldn't be read from $($psaName): $($_.Exception.Message)" $f.ticketId }
$row = ConvertTo-PsaTicketRow -Raw $t.raw
try { $null = Resolve-PsaTicketNames @($row) } catch { $null = $warnings.Add("The company name couldn't be looked up, so it may still need taking out by hand: $($_.Exception.Message)") }
# Autotask and Zendesk tickets carry only the contact's id, so the name and email are read from the contact.
if (-not $row.contactEmail -and -not (Test-PsaBlank $row.contactId)) {
    try {
        switch ($f.psa) {
            'autotask' { $ct = Get-PsaProp (Invoke-PsaRead "/Contacts/$($row.contactId)" 'read the ticket''s contact' 'read contacts') 'item'; $row.contactEmail = [string](Get-PsaProp $ct 'emailAddress'); if (-not $row.contactName) { $row.contactName = ("$(Get-PsaProp $ct 'firstName') $(Get-PsaProp $ct 'lastName')").Trim() } }
            'zendesk' { $ct = Get-PsaProp (Invoke-PsaRead "/users/$($row.contactId)" 'read the ticket''s requester' 'read users') 'user'; $row.contactEmail = [string](Get-PsaProp $ct 'email'); if (-not $row.contactName) { $row.contactName = [string](Get-PsaProp $ct 'name') } }
        }
    }
    catch { $null = $warnings.Add("The ticket's contact couldn't be read, so their name may still need taking out by hand: $($_.Exception.Message)") }
}
$null = $actions.Add("Read ticket $($f.ticketId) from $psaName.")
if (-not $row.isClosed) { $null = $warnings.Add("Ticket $($f.ticketId) isn't closed yet, so the fix may not be final.") }

$notes = @()
try { $notes = @(Get-PsaTicketNotes -Id $id) } catch { Stop-Run 'incomplete' "The notes on ticket $($f.ticketId) couldn't be read: $($_.Exception.Message)" $f.ticketId }
if (Test-PsaNoteMarker -Id $id -Marker 'kb-draft' -Notes @($notes | Where-Object { $_.internal })) { Skip-Run "A knowledge base draft was already made from ticket $($f.ticketId), so another wasn't made."; return }

# ---- the resolution text ----
$res = $f.resolution; $from = 'the resolutionNotes input'
if (-not $res) {
    # Unverified: the HaloPSA and Kaseya BMS resolution field names.
    $field = @{ autotask = 'resolution'; halopsa = 'clearance_note'; kaseyabms = 'Resolution' }[$f.psa]
    if ($field) { $v = [string](Get-PsaProp $t.raw $field); if ($v.Trim()) { $res = $v; $from = "the ticket's $field field" } }
}
if (-not $res -and $f.psa -eq 'connectwise') {
    $rn = @($notes | Where-Object { (Get-PsaProp $_.raw 'resolutionFlag') -eq $true })
    if ($rn.Count) { $res = (@($rn | ForEach-Object { [string]$_.text }) -join "`n`n"); $from = 'the notes marked as the resolution' }
}
if (-not $res) {
    $tech = @($notes | Where-Object { -not $_.fromClient -and ([string]$_.text).Trim() } | Select-Object -Last 3)
    if ($tech.Count) { $res = (@($tech | ForEach-Object { [string]$_.text }) -join "`n`n"); $from = 'the newest technician notes' }
}
$res = (ConvertTo-PsaPlainText $res).Trim()
if ($res.Length -lt 60) { Stop-Run 'incomplete' "Ticket $($f.ticketId) has too little resolution text to write an article from$(if ($res) { " ($($res.Length) characters)" }). Add the fix to the ticket's resolution, or send resolutionNotes." $f.ticketId }
$null = $actions.Add("Took the resolution from $from.")

# ---- take client and personal details out before the AI sees anything ----
$authors = @($notes | ForEach-Object { [string]$_.author } | Where-Object { $_ } | Select-Object -Unique)
$names = Get-KbNames -Company ([string]$row.companyName) -People (@([string]$row.contactName) + $authors)
$domains = @(@([string]$row.contactEmail) | Where-Object { $_ -match '@(.+)$' } | ForEach-Object { ($_ -split '@')[1] })
$removed = New-Object System.Collections.ArrayList
$clean = {
    param([string]$s, [int]$Max)
    $r = Invoke-KbScrub -Text $s -Companies $names.companies -People $names.people -Domains $domains
    foreach ($k in @($r.removed)) { if (-not $removed.Contains($k)) { $null = $removed.Add($k) } }
    $out = [string]$r.text; if ($out.Length -gt $Max) { $out = $out.Substring(0, $Max) + ' [cut]' }
    return $out
}
$problem = & $clean ((ConvertTo-PsaPlainText ([string]$t.description)).Trim()) 1500
$facts = [ordered]@{
    summary    = (& $clean ([string]$row.summary) 300)
    problem    = $problem
    resolution = (& $clean $res 4000)
    category   = $f.category
}
if ($removed.Count) { $null = $actions.Add("Took out $($removed -join ', ') before drafting.") }
$ctx = [ordered]@{
    ticketId = $id; number = $f.ticketId; psa = $f.psa; confirm = $f.confirm; category = $f.category
    companies = @($names.companies); people = @($names.people); domains = @($domains); removed = @($removed)
    warnings = @(Get-AllWarnings $warnings); actions = @($actions)
}
Set-NodeOutput ([ordered]@{ status = 'ok'; facts_json = ($facts | ConvertTo-Json -Depth 5 -Compress); ctx_json = ($ctx | ConvertTo-Json -Depth 5 -Compress) })
