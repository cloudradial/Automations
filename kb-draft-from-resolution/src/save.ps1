# === NODE: Save the draft for review ===
# Checks the AI's article, takes client and personal details out again, and builds the article. With
# confirm true it saves it as a draft for review in CloudRadial and adds an internal note to the ticket.
# CloudRadial has no draft state, so a draft is kept out of clients' sight two ways:
#   - it is saved under the MSP's own CloudRadial company (the KbDraft-CompanyId secret), never the client's
#     company or company 0 (the MSP-wide articles every client sees);
#   - its publish date is 2099-12-31, so it isn't visible until a reviewer sets the real date.
# A preview (confirm false) saves nothing and returns the draft. One draft per ticket: the article's author
# names the ticket, and the ticket's internal note carries a marker.
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/cloudradial.ps1
# @@ src/scrub.ps1 @@
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
function Read-Json { param($v) if ($null -eq $v) { return $null }; if ($v -isnot [string]) { return $v }; if (-not $v.Trim()) { return $null }; try { return ($v | ConvertFrom-Json) } catch { return $null } }
function ConvertTo-KbHtml { param([string]$s) return [System.Net.WebUtility]::HtmlEncode([string]$s) }
$stopState = @{ done = $false; ticket = '' }
$warnings = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    param($Own)
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($Own) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = [string]$_.Exception.Message; public_note = ''; internal_note = "The knowledge base draft failed while saving: $($_.Exception.Message)"; ticket_id = $stopState.ticket; actions = @(); warnings = @(Get-AllWarnings $warnings) }) }; break }

$ctx = Read-Json (Get-NodeInput -Name 'ctx')
if ($null -eq $ctx) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = 'The ticket details from the first step are missing. Run the workflow from the start.'; public_note = ''; internal_note = ''; ticket_id = ''; actions = @(); warnings = @() }); throw 'The ticket details from the first step are missing.' }
$num = [string](Get-Prop $ctx 'number'); $stopState.ticket = $num
$actions = New-Object System.Collections.ArrayList; foreach ($a in @(Get-Prop $ctx 'actions')) { if ($a) { $null = $actions.Add([string]$a) } }
foreach ($w in @(Get-Prop $ctx 'warnings')) { if ($w) { $null = $warnings.Add([string]$w) } }
$counts = [ordered]@{ draftsSaved = 0; notesWritten = 0 }
function Complete-Run {
    param([string]$Status, [string]$Message, [string]$Internal, $Draft = $null)
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = $Status; message = $Message; public_note = ''; internal_note = $Internal; ticket_id = $num; draft = $Draft; counts = $counts; actions = @($actions); warnings = @(Get-AllWarnings $warnings) })
}
$skip = [string](Get-Prop $ctx 'skip')
if ($skip) { Complete-Run 'success' $skip $skip; return }
$confirm = [bool](Get-Prop $ctx 'confirm')
$id = [string](Get-Prop $ctx 'ticketId')
# The ticket note, only when confirmed. The marker means one note (and one draft) per ticket.
function Add-TicketNote {
    param([string]$Text)
    try {
        $null = Connect-Psa -Psa ([string](Get-Prop $ctx 'psa'))
        $r = Add-PsaNote -Id $id -Text $Text -Title 'Knowledge base draft' -Internal -Marker 'kb-draft'
        if ($r -eq 'written') { $counts.notesWritten = 1; $null = $actions.Add("Added the internal note to ticket $num.") }
    }
    catch { $null = $warnings.Add("The internal note couldn't be added to ticket $($num): $($_.Exception.Message)") }
}

# ---- the AI's article ----
$aiRaw = Get-NodeInput -Name 'judgment'
$ai = $null; $aiText = [string]$aiRaw
if ($aiRaw -and $aiRaw -isnot [string]) { $ai = $aiRaw }
elseif ($aiText -match '(?s)\{.*\}') { try { $ai = $Matches[0] | ConvertFrom-Json } catch { $ai = $null } }
if ($null -eq $ai) { Complete-Run 'incomplete' "The AI step gave no readable article for ticket $num, so nothing was saved." "No knowledge base draft was made from ticket $($num): the AI step gave no readable article."; return }
$reason = [string](Get-Prop $ai 'reason')
if ((Get-Prop $ai 'worthPublishing') -ne $true) {
    $msg = "Ticket $num isn't a good fit for a knowledge base article$(if ($reason) { ": $reason" } else { '.' })"
    if ($confirm) { Add-TicketNote "No knowledge base draft was made from this ticket. $msg" }
    Complete-Run 'success' "$msg Nothing was saved." $msg
    return
}

# Every field is cleaned again, in case the AI put back a detail.
$names = @{ companies = @(Get-Prop $ctx 'companies'); people = @(Get-Prop $ctx 'people'); domains = @(Get-Prop $ctx 'domains') }
$found = New-Object System.Collections.ArrayList
$clean = {
    param($v, [int]$Max)
    $r = Invoke-KbScrub -Text (([string]$v) -replace '\s+', ' ').Trim() -Companies $names.companies -People $names.people -Domains $names.domains
    foreach ($k in @($r.removed)) { if (-not $found.Contains($k)) { $null = $found.Add($k) } }
    $s = [string]$r.text; if ($s.Length -gt $Max) { $s = $s.Substring(0, $Max).TrimEnd() + '...' }
    return $s
}
$subject = & $clean (Get-Prop $ai 'subject') 120
$category = $(if ([string](Get-Prop $ctx 'category')) { [string](Get-Prop $ctx 'category') } else { & $clean (Get-Prop $ai 'category') 60 })
if (-not $category) { $category = 'Drafts for review' }
$appliesTo = & $clean (Get-Prop $ai 'appliesTo') 150
$cause = & $clean (Get-Prop $ai 'cause') 600
$symptoms = @(@(Get-Prop $ai 'symptoms') | ForEach-Object { & $clean $_ 300 } | Where-Object { $_ } | Select-Object -First 8)
$steps = @(@(Get-Prop $ai 'steps') | ForEach-Object { & $clean $_ 300 } | Where-Object { $_ } | Select-Object -First 20)
if ($found.Count) { $null = $warnings.Add("The AI's draft still had $($found -join ', '), which was taken out again. Check the draft before publishing.") }
if (-not $subject -or -not $steps.Count) { Complete-Run 'incomplete' "The AI's article for ticket $num had no title or no steps, so nothing was saved." "No knowledge base draft was made from ticket $($num): the AI's article had no title or no steps."; return }

$html = New-Object System.Text.StringBuilder
$null = $html.Append('<p><strong>Draft for review.</strong> Written by AutomationAI from a resolved ticket. Check every step, then move it to the right company and set the publish date before clients can see it.</p>')
if ($appliesTo) { $null = $html.Append("<p><strong>Applies to:</strong> $(ConvertTo-KbHtml $appliesTo)</p>") }
if ($symptoms.Count) { $null = $html.Append('<h2>Symptoms</h2><ul>'); foreach ($s in $symptoms) { $null = $html.Append("<li>$(ConvertTo-KbHtml $s)</li>") }; $null = $html.Append('</ul>') }
if ($cause) { $null = $html.Append("<h2>Cause</h2><p>$(ConvertTo-KbHtml $cause)</p>") }
$null = $html.Append('<h2>How to fix it</h2><ol>'); foreach ($s in $steps) { $null = $html.Append("<li>$(ConvertTo-KbHtml $s)</li>") }; $null = $html.Append('</ol>')
$author = "AutomationAI draft (ticket $num)"
$draft = [ordered]@{ subject = "[Draft] $subject"; category = $category; author = $author; body = $html.ToString() }

if (-not $confirm) {
    Complete-Run 'pending_confirmation' "Preview only, nothing was saved. Would save the draft '$subject' for review." "Would save the knowledge base draft '$subject' from ticket $num.$(if ($reason) { " $reason" })" $draft
    return
}

# ---- confirmed: save it under the MSP's own company, dated so clients can't see it ----
$cidRaw = [string](Get-CrSecret 'KbDraft-CompanyId')
if ($cidRaw -notmatch '^\d+$' -or [int]$cidRaw -le 0) {
    Complete-Run 'incomplete' "The draft wasn't saved: add the KbDraft-CompanyId secret with your own CloudRadial company id (not 0, which every client sees)." "The knowledge base draft from ticket $num wasn't saved because the KbDraft-CompanyId secret isn't set." $draft
    return
}
$cid = [int]$cidRaw
$null = Connect-Cr
$filter = "companyId eq $cid and author eq '$($author.Replace("'", "''"))'"
$prior = @(Get-CrAll "/v2/odata/article?`$filter=$([uri]::EscapeDataString($filter))&`$select=articleId,subject,author")
if ($prior.Count) {
    $aid = [string](Get-CrProp $prior[0] 'articleId')
    $null = $actions.Add("Draft article $aid from ticket $num already exists, so another wasn't saved.")
    Add-TicketNote "A knowledge base draft from this ticket is waiting for review in CloudRadial: article $aid, '$(Get-CrProp $prior[0] 'subject')'."
    Complete-Run 'success' "A draft from ticket $num already exists (article $aid), so another wasn't saved." "Draft article $aid already exists." $draft
    return
}
$body = [ordered]@{ companyId = $cid; subject = $draft.subject; category = $category; datePublished = '2099-12-31T00:00:00Z'; body = $draft.body; author = $author; isFavorite = $false; isFrontPage = $false }
$res = Invoke-CrApi -Path '/v2/article' -Method 'POST' -Body $body
$data = Get-CrProp $res 'data'; if ($null -ne $data) { $res = $data }
$aid = [string](Get-CrProp $res 'articleId')
$counts.draftsSaved = 1
$null = $actions.Add("Saved the draft '$subject' as CloudRadial article $(if ($aid) { $aid } else { '(id not returned)' }) under company $cid, dated 2099-12-31.")
$note = "A knowledge base draft was written from this ticket and saved for review in CloudRadial: '$($draft.subject)'$(if ($aid) { " (article $aid)" }). It is dated 2099-12-31, so no client sees it until a reviewer checks it, moves it to the right company and sets the publish date."
Add-TicketNote $note
Complete-Run 'success' "Saved the draft '$subject' for review$(if ($aid) { " (article $aid)" })." $note $draft
