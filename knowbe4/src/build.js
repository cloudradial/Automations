// Builds ../knowbe4.yml: puts company.ps1, records.ps1 and ticket.ps1 into their steps, with the shared libraries
// pasted in by ../../_shared/inject.js, and wires the company into the records and ticket steps.
// Usage: node build.js                 rewrite the .yml
//        node build.js --check         exit 1 if the .yml is out of date
//        node build.js --extract <dir>  write each step's finished script to <dir>/<node-id>.ps1 (used by test.ps1)
// Edit the files in src/, never the scripts in the .yml.
// Needs js-yaml: set JS_YAML_PATH (or NODE_PATH) to an existing copy, or npm install in _shared.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

// Returns js-yaml and sets JS_YAML_PATH so inject.js uses the same copy.
function loadYaml() {
  const tries = [process.env.JS_YAML_PATH, 'js-yaml', path.join(__dirname, '..', '..', '_shared', 'node_modules', 'js-yaml')].filter(Boolean);
  for (const t of tries) {
    try { const p = require.resolve(t); const y = require(p); process.env.JS_YAML_PATH = p; return y; } catch { /* next */ }
  }
  throw new Error('js-yaml not found. Set JS_YAML_PATH, or run npm install in _shared.');
}

const here = __dirname;
const out = path.join(here, '..', 'knowbe4.yml');
const inject = path.join(here, '..', '..', '_shared', 'inject.js');

const steps = [
  { id: 'resolve-company', file: 'company.ps1', libs: ['cloudradial.ps1'] },
  { id: 'create-assets', file: 'records.ps1', libs: ['cloudradial.ps1'] },
  { id: 'summarize-and-ticket', file: 'ticket.ps1', libs: ['psa.ps1'] },
];
const marker = (lib) => `# >>> _shared/${lib} (generated by _shared/inject.js; edit the source, not this block)\n# <<< _shared/${lib}`;
const src = (s) => [...s.libs.map(marker), '', fs.readFileSync(path.join(here, s.file), 'utf8').replace(/\r\n/g, '\n').trimEnd()].join('\n');

function render(y) {
  const doc = y.load(fs.readFileSync(out, 'utf8'));
  doc.description = 'Reads KnowBe4 users with incomplete security-awareness training, writes one CloudRadial flexible asset per user for the client, and opens one ticket for the company in ConnectWise PSA, Autotask, HaloPSA, Kaseya BMS, Syncro or Zendesk listing who is overdue.';
  const d = doc.definition;
  const byId = (id) => d.activities.find((a) => a.id === id);

  // The company step runs first, so a wrong company stops the run before KnowBe4 is read.
  if (!byId('resolve-company')) {
    d.activities.splice(1, 0, {
      id: 'resolve-company', name: 'Pick the CloudRadial company', type: 'powershell-script', position: { x: 180, y: 120 },
      properties: { script: '', timeoutSeconds: 120, retryCount: 0, parameters: [{ name: 'trigger', expression: '{{ nodes.trigger.output }}' }], aiExtensions: [] },
    });
    d.connections = d.connections.filter((c) => !(c.source === 'start' && c.target === 'fetch-incomplete-users'));
    d.connections.unshift({ source: 'start', target: 'resolve-company', sourceHandle: null }, { source: 'resolve-company', target: 'fetch-incomplete-users', sourceHandle: null });
  }
  // One step reads the existing records once and creates or updates them (up to 1.1.0 a foreach created a new
  // record per user on every run). The node id stays, so the ticket step's binding to its items is unchanged.
  const rec = byId('create-assets');
  rec.name = 'Create or update CloudRadial records';
  rec.type = 'powershell-script';
  rec.properties = {
    script: '', timeoutSeconds: 600, retryCount: 0,
    parameters: [
      { name: 'users', expression: '{{ nodes.fetch-incomplete-users.output.users }}' },
      { name: 'flexibleAssetTypeId', expression: '{{ nodes.ensure-asset-type.output.flexibleAssetTypeId }}' },
      { name: 'companyId', expression: '{{ nodes.resolve-company.output.companyId }}' },
    ],
    aiExtensions: [],
  };
  for (const s of steps) byId(s.id).properties.script = src(s);

  const sum = byId('summarize-and-ticket').properties;
  for (const n of ['companyId', 'companyName']) if (!sum.parameters.some((p) => p.name === n)) sum.parameters.push({ name: n, expression: `{{ nodes.resolve-company.output.${n} }}` });
  sum.aiExtensions = [];
  return y.dump(doc, { lineWidth: -1, noRefs: true });
}

function main(argv) {
  const y = loadYaml();
  const ex = argv.indexOf('--extract');
  if (ex >= 0) {
    const dir = argv[ex + 1];
    if (!dir) throw new Error('--extract needs a folder');
    fs.mkdirSync(dir, { recursive: true });
    const doc = y.load(fs.readFileSync(out, 'utf8'));
    const ps = doc.definition.activities.filter((a) => a.properties && a.properties.script);
    for (const a of ps) fs.writeFileSync(path.join(dir, `${a.id}.ps1`), a.properties.script);
    console.log(`Extracted ${ps.length} steps to ${dir}`);
    return 0;
  }
  const check = argv.includes('--check');
  const tmpDir = fs.mkdtempSync(path.join(require('os').tmpdir(), 'kb4-'));
  const tmp = path.join(tmpDir, 'knowbe4.yml');
  fs.writeFileSync(tmp, render(y));
  execFileSync(process.execPath, [inject, tmpDir], { stdio: 'pipe', env: process.env });
  const next = fs.readFileSync(tmp, 'utf8');
  fs.rmSync(tmpDir, { recursive: true, force: true });
  y.load(next);
  const was = fs.readFileSync(out, 'utf8');
  const same = was === next;
  console.log(`knowbe4.yml${same ? ' current' : check ? ' OUT OF DATE' : ' written'}`);
  if (!same && !check) fs.writeFileSync(out, next);
  return !same && check ? 1 : 0;
}

if (require.main === module) {
  try { process.exit(main(process.argv.slice(2))); } catch (e) { console.error(e.message); process.exit(2); }
}
