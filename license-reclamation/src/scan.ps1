# === STEP: Find unused licences ===
# Edit this file, then run: node license-reclamation/src/build.js
# Read-only. Reads the tenant's subscriptions, every user's licences and last sign-in, and (when allowed)
# mailbox activity, then lists users holding a paid licence they haven't used in the last <days> days.
# Disabled accounts that still hold a paid licence are always listed. Free and trial SKUs are ignored.
# Graph application permissions: Organization.Read.All (or Directory.Read.All), User.Read.All,
# AuditLog.Read.All (needs Entra ID P1). Optional: Reports.Read.All for mailbox activity.
# >>> _shared/graph.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/graph.ps1

$in = Get-NodeInput
$days = [int](Get-GraphProp $in 'days'); if ($days -le 0) { $days = 60 }
$overrides = @{}
$po = Get-GraphProp $in 'price_overrides'
if ($po -is [System.Collections.IDictionary]) { foreach ($k in $po.Keys) { $overrides[([string]$k).ToUpperInvariant()] = [double]$po[$k] } }
elseif ($null -ne $po) { foreach ($p in $po.PSObject.Properties) { $overrides[$p.Name.ToUpperInvariant()] = [double]$p.Value } }
$warnings = New-Object System.Collections.ArrayList

function Stop-LrScan {
    param([string]$Why)
    Set-NodeOutput ([ordered]@{ status = 'error'; message = $Why; public_note = ''; internal_note = $Why; ticket_id = ''; actions = @(); warnings = @($warnings) })
    throw $Why
}

