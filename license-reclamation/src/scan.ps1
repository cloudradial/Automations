function Test-LrFreeSku { param([string]$Part) $u = $Part.ToUpperInvariant(); if ($LrFree -contains $u) { return $true }; return ($u -match '(_FREE$|^FREE_|_VIRAL|VIRAL_|_TRIAL|TRIAL_|_IW_SKU$|_IW$|EXPLORATORY)') }
function ConvertTo-LrDate {
    param($v)
    if ($null -eq $v) { return $null }
    if ($v -is [datetime]) { return $v.ToUniversalTime() }
    if ($v -is [datetimeoffset]) { return $v.UtcDateTime }
    $s = ([string]$v).Trim(); if (-not $s) { return $null }
    $d = [datetime]::MinValue
    if ([datetime]::TryParse($s, [System.Globalization.CultureInfo]::InvariantCulture, [System.Globalization.DateTimeStyles]'AdjustToUniversal,AssumeUniversal', [ref]$d)) { if ($d.Year -le 1601) { return $null }; return $d }
    return $null
}
function Get-LrLatest { param([object[]]$Dates) $m = $null; foreach ($d in $Dates) { if ($null -ne $d -and ($null -eq $m -or $d -gt $m)) { $m = $d } }; return $m }

# ---- Graph ----
try { $conn = Connect-Graph } catch { Stop-LrScan ([string]$_.Exception.Message) }
$tenantId = [string]$conn.TenantId
$now = (Get-Date).ToUniversalTime()
$cutoff = $now.AddDays(-$days)

$skus = @()
try { $skus = @(Get-GraphAll -Path '/v1.0/subscribedSkus' -Permission 'Organization.Read.All (or Directory.Read.All)') }
catch {
    if ($GraphState.LastStatus -eq 403) { Stop-LrScan "Microsoft Graph refused to list the tenant's subscriptions. Grant the app registration the Organization.Read.All (or Directory.Read.All) application permission, with admin consent, then run again." }
    Stop-LrScan "Couldn't read the tenant's Microsoft 365 subscriptions: $($_.Exception.Message)"
}
$skuMap = @{}
foreach ($s in $skus) {
    $sid = [string](Get-GraphProp $s 'skuId'); $part = [string](Get-GraphProp $s 'skuPartNumber')
    if (-not $sid -or -not $part) { continue }
    $applies = [string](Get-GraphProp $s 'appliesTo')
    $u = $part.ToUpperInvariant()
    $free = (Test-LrFreeSku $part) -or ($applies -and $applies -ne 'User')
    $name = $part; $price = $null; $source = 'unknown'
    if ($LrPrices.Contains($u)) { $name = $LrPrices[$u].name; $price = [double]$LrPrices[$u].price; $source = 'list' }
    if ($overrides.ContainsKey($u)) { $price = [double]$overrides[$u]; $source = 'override' }
    $skuMap[$sid.ToLowerInvariant()] = @{ part = $part; name = $name; price = $price; source = $source; free = $free }
}

$sel = 'id,displayName,userPrincipalName,accountEnabled,userType,createdDateTime,assignedLicenses,signInActivity'
$users = @()
try { $users = @(Get-GraphAll -Path "/v1.0/users?`$select=$sel&`$top=120" -Permission 'AuditLog.Read.All (with User.Read.All)') }
catch {
    $msg = [string]$_.Exception.Message
    if ($GraphState.LastStatus -eq 403 -and $msg -match '(?i)premium licen|NonPremium|tenant is B2C') { Stop-LrScan 'Microsoft Graph refused to read last sign-in times because this tenant has no Microsoft Entra ID P1 (or Business Premium) licence. Last sign-in data needs Entra ID P1, so this check cannot run for this tenant.' }
    if ($GraphState.LastStatus -eq 403) { Stop-LrScan 'Microsoft Graph refused to read last sign-in times. Grant the app registration the AuditLog.Read.All application permission (with User.Read.All), with admin consent, then run again.' }
    Stop-LrScan "Couldn't read the tenant's users: $msg"
}

# Mailbox activity (optional). The report is CSV; it names users only when concealed names are turned off.
$mailbox = @{}
$mailboxChecked = $false
try {
    $csv = Invoke-Graph -Method GET -Path "/v1.0/reports/getMailboxUsageDetail(period='D90')" -Permission 'Reports.Read.All'
    if ($csv -is [byte[]]) { $csv = [Text.Encoding]::UTF8.GetString($csv) }
    $rows = @(([string]$csv).TrimStart([char]0xFEFF) | ConvertFrom-Csv)
    $named = @($rows | Where-Object { ([string](Get-GraphProp $_ 'User Principal Name')) -like '*@*' })
    if ($rows.Count -and -not $named.Count) {
        $null = $warnings.Add('Mailbox activity was not used because Microsoft 365 reports hide user names in this tenant. To include it, turn off "Display concealed user, group, and site names in all reports" in the Microsoft 365 admin center under Settings > Org settings > Reports.')
    }
    else {
        foreach ($r in $named) {
            $upn = ([string](Get-GraphProp $r 'User Principal Name')).ToLowerInvariant()
            $mailbox[$upn] = ConvertTo-LrDate (Get-GraphProp $r 'Last Activity Date')
        }
        $mailboxChecked = $true
    }
}
catch {
    if ($GraphState.LastStatus -eq 403) { $null = $warnings.Add('Mailbox activity was not checked because the app registration does not have the Reports.Read.All permission, so this list is based on sign-in times only.') }
    else { $null = $warnings.Add("Mailbox activity could not be read, so this list is based on sign-in times only. ($($_.Exception.Message))") }
}

# ---- find unused paid licences ----
$found = New-Object System.Collections.ArrayList
$licensedUsers = 0
foreach ($usr in $users) {
    $paid = @()
    foreach ($al in @(Get-GraphProp $usr 'assignedLicenses')) {
        $sid = ([string](Get-GraphProp $al 'skuId')).ToLowerInvariant()
        if ($sid -and $skuMap.ContainsKey($sid) -and -not $skuMap[$sid].free) { $paid += $skuMap[$sid] }
    }
    if (-not $paid.Count) { continue }
    $licensedUsers++
    $upn = [string](Get-GraphProp $usr 'userPrincipalName')
    $ae = Get-GraphProp $usr 'accountEnabled'
    $enabled = ($null -eq $ae -or [bool]$ae)
    $sia = Get-GraphProp $usr 'signInActivity'
    $lastSignIn = Get-LrLatest @((ConvertTo-LrDate (Get-GraphProp $sia 'lastSignInDateTime')), (ConvertTo-LrDate (Get-GraphProp $sia 'lastNonInteractiveSignInDateTime')), (ConvertTo-LrDate (Get-GraphProp $sia 'lastSuccessfulSignInDateTime')))
    $lastMail = $null; if ($upn -and $mailbox.ContainsKey($upn.ToLowerInvariant())) { $lastMail = $mailbox[$upn.ToLowerInvariant()] }
    $created = ConvertTo-LrDate (Get-GraphProp $usr 'createdDateTime')
    $reason = ''
    if (-not $enabled) { $reason = 'disabled' }
    else {
        if ($null -ne $created -and $created -gt $cutoff) { continue }   # too new to judge
        $lastActive = Get-LrLatest @($lastSignIn, $lastMail)
        if ($null -ne $lastActive -and $lastActive -gt $cutoff) { continue }
        $reason = $(if ($null -eq $lastActive) { 'never' } else { 'inactive' })
    }
    $known = @($paid | Where-Object { $null -ne $_.price })
    $monthly = 0.0; foreach ($k in $known) { $monthly += [double]$k.price }
    $null = $found.Add([ordered]@{
            name           = [string](Get-GraphProp $usr 'displayName')
            upn            = $upn
            enabled        = $enabled
            reason         = $reason
            lastSignIn     = $(if ($null -ne $lastSignIn) { $lastSignIn.ToString('yyyy-MM-dd') } else { '' })
            lastMailbox    = $(if ($null -ne $lastMail) { $lastMail.ToString('yyyy-MM-dd') } else { '' })
            licences       = @($paid | ForEach-Object { [ordered]@{ sku = $_.part; name = $_.name; price = $_.price; priceSource = $_.source } })
            monthly        = [Math]::Round($monthly, 2)
            unknownPrices  = ($paid.Count - $known.Count)
        })
}

$rowsOut = @($found | Sort-Object -Property @{ Expression = { $_.monthly }; Descending = $true }, @{ Expression = { $_.name }; Descending = $false })
$licenceCount = 0; $saving = 0.0; $unknownSkus = @{}; $disabled = 0
foreach ($r in $rowsOut) {
    $licenceCount += @($r.licences).Count; $saving += [double]$r.monthly
    if (-not $r.enabled) { $disabled++ }
    foreach ($l in @($r.licences)) { if ($null -eq $l.price) { $unknownSkus[$l.sku] = 1 } }
}

Set-NodeOutput ([ordered]@{
        status          = 'ok'
        days            = $days
        company_id      = [int](Get-GraphProp $in 'company_id')
        preview         = [bool](Get-GraphProp $in 'preview')
        tenantId        = $tenantId
        checkedOn       = $now.ToString('yyyy-MM-dd')
        licensedUsers   = $licensedUsers
        mailboxChecked  = $mailboxChecked
        userCount       = $rowsOut.Count
        disabledCount   = $disabled
        licenceCount    = $licenceCount
        monthlySaving   = [Math]::Round($saving, 2)
        unknownPriceSkus = @($unknownSkus.Keys | Sort-Object)
        overridesUsed   = @($overrides.Keys | Sort-Object)
        users           = $rowsOut
        warnings        = @($warnings)
    })
