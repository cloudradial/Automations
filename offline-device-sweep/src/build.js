// Builds ../offline-device-sweep.yml from the step sources in this folder, then pastes the shared PSA library
// into it (_shared/inject.js injectText).
// Usage: node build.js          rewrite the .yml
//        node build.js --check  exit 1 if the .yml is out of date
// Edit find.ps1, ticket.ps1, common.ps1 and datto.ps1 (or _shared/psa.ps1 and _shared/psa-tickets.ps1), never the .yml.
// Needs js-yaml: set JS_YAML_PATH (or NODE_PATH) to an existing copy, or npm install in _shared.
const fs = require('fs');
const path = require('path');
const { injectText } = require('../../_shared/inject.js');

function loadYaml() {
  try { return require('js-yaml'); } catch { /* fall through */ }
  if (process.env.JS_YAML_PATH) return require(process.env.JS_YAML_PATH);
  throw new Error('js-yaml not found. Set JS_YAML_PATH, or npm install in _shared.');
}

const here = __dirname;
const name = 'offline-device-sweep.yml';
const out = path.join(here, '..', name);
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const block = (text, indent) => text.split('\n').map((l) => (l ? indent + l : '')).join('\n');
// Shared libraries are marked for inject.js; this folder's own helpers are pasted here with the same marker pattern.
const shared = (lib) => `# >>> _shared/${lib} (generated by _shared/inject.js; edit the source, not this block)\n# <<< _shared/${lib}`;
const local = (f) => `# >>> src/${f} (generated by src/build.js; edit the source, not this block)\n${read(f)}\n# <<< src/${f}`;
const script = (libs, locals, body) => [...libs.map(shared), ...locals.map(local), read(body)].join('\n');

const testInput = JSON.stringify({ preview: true }, null, 2);

function psStep({ id, name: n, x, body, test }) {
  let s = `  - id: ${id}
    name: ${n}
    type: powershell-script
    position:
      x: ${x}
      y: 80
    properties:
      script: |-
${block(body, '        ')}
      timeoutSeconds: 900
      retryCount: 0
      parameters: []
      aiExtensions: []
`;
  if (test) s += `      testInput: |-\n${block(test, '        ')}\n`;
  return s;
}

// Both steps are unbound: the first reads Get-NodeInput (a Routine sends nothing), the second reads the first's output.
const steps = [
  { id: 'node-find', name: 'Find offline devices', body: script(['psa.ps1', 'psa-tickets.ps1'], ['common.ps1', 'datto.ps1'], 'find.ps1'), test: testInput },
  { id: 'node-ticket', name: 'Open or update tickets', body: script(['psa.ps1'], ['common.ps1'], 'ticket.ps1') },
];

const template = `automationsWorkflow: 1
name: Offline Device Sweep
description: Once a day, reads Datto RMM and finds managed devices that have been offline longer than a
  threshold (7 days for workstations and laptops, 4 hours for servers). Opens one PSA ticket per client company
  listing them, servers first, or adds an internal note to the open one with newly offline and recovered
  devices. Reads Datto RMM only. Run with preview true first.
definition:
  schemaVersion: 1
  activities:
  - id: start
    name: Start
    type: start
    position:
      x: 100
      y: 80
    properties:
      webhookEnabled: false
%%STEPS%%  - id: end
    name: End
    type: end
    position:
      x: %%ENDX%%
      y: 80
  connections:
%%CONNECTIONS%%  startActivityId: start
`;

let x = 280;
const stepText = steps.map((s) => { const r = psStep({ ...s, x }); x += 180; return r; }).join('');
const chain = ['start', ...steps.map((s) => s.id), 'end'];
const connText = chain.slice(0, -1).map((src, i) => `  - source: ${src}\n    target: ${chain[i + 1]}\n    sourceHandle: null\n`).join('');
// Function replacements, so a "$" in the PowerShell is never read as a replacement pattern.
const yml = template.replace('%%STEPS%%', () => stepText).replace('%%ENDX%%', () => String(x)).replace('%%CONNECTIONS%%', () => connText);

const y = loadYaml();
const { text } = injectText(yml, name, new Map());
const doc = y.load(text);
// Guard rails: the shape every workflow must have.
if (doc.automationsWorkflow !== 1) throw new Error('automationsWorkflow marker missing');
const acts = doc.definition.activities;
if (acts.length !== steps.length + 2) throw new Error('unexpected activity count after parsing');
if (acts.find((a) => a.id === 'start').properties.webhookEnabled !== false) throw new Error('webhook must ship disabled');
if (acts.some((a) => a.properties && a.properties.model)) throw new Error('model must be blank');
if (/\{\{\s*input\./.test(text)) throw new Error('use nodes.<id>.output bindings, never input.*');
if (text.includes(String.fromCharCode(0x2014))) throw new Error('no em dashes');
const ids = new Set(acts.map((a) => a.id));
for (const c of doc.definition.connections) if (!ids.has(c.source) || !ids.has(c.target)) throw new Error(`bad connection ${c.source} -> ${c.target}`);
for (const a of acts.filter((z) => z.type === 'powershell-script')) {
  if (!a.properties.script.includes('function Connect-Psa')) throw new Error(`${a.id}: _shared/psa.ps1 was not pasted`);
  if (!a.properties.script.includes('function Get-OdsMarker')) throw new Error(`${a.id}: src/common.ps1 was not pasted`);
}
const find = acts.find((a) => a.id === 'node-find').properties.script;
if (!find.includes('function Find-PsaTickets')) throw new Error('node-find: _shared/psa-tickets.ps1 was not pasted');
if (!find.includes('function Connect-Datto')) throw new Error('node-find: src/datto.ps1 was not pasted');
const bad = text.split('\n').findIndex((l) => /[ \t]+$/.test(l) || l.includes('\t'));
if (bad >= 0) throw new Error(`trailing whitespace or a tab on line ${bad + 1} of the .yml`);

const check = process.argv.includes('--check');
const was = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
if (text === was) { console.log(`${name}: current`); process.exit(0); }
if (check) { console.log(`${name}: OUT OF DATE (run node src/build.js)`); process.exit(1); }
fs.writeFileSync(out, text);
console.log(`${name}: written`);
