# === NODE: Post the notice and record it ===
# Builds one plan for every affected company, previews it, and only makes the changes when confirm is true.
#   Banner token: the CloudRadial API has no news, announcement or banner resource, so the notice goes
#     into a company token (default @ServiceStatus) that the portal's home page or banner shows. Broadcast
#     sets it; resolved clears it, but only when it still shows this service.
#   Service Status article: one knowledge base article per company in the "Service Status" category,
#     pinned to the portal front page while the outage is open and unpinned with a resolution when it ends.
#   Email (off unless emailContacts is true): the company's primary contact from the PSA, one email per
#     company through Postmark. Without the Postmark secrets nothing is emailed and the ticket note says so.
#   Problem ticket: an internal note listing what ran, on the ticket in problemTicketId (or ticketId). The note
#     carries a marker built from the mode, service and message, so a retried or repeated run doesn't add it twice.
# A company whose banner and article already show this exact notice is skipped, so a retried run doesn't email twice.
# >>> _shared/plan.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/plan.ps1
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/cloudradial.ps1
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
