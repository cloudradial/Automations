// Builds ../password-expiry-reminder.yml from the step scripts in this folder. Pastes common.ps1 into every
// step, then the shared libraries (_shared/graph.ps1 and _shared/postmark.ps1) with _shared/inject.js.
// Usage: node build.js                  rewrite the .yml
//        node build.js --check          exit 1 if the .yml is out of date
//        node build.js --extract <dir>  write each step's finished script to <dir>/<node-id>.ps1 (used by test.ps1)
// Edit the .ps1 files here, never the .yml.
// Needs js-yaml: set JS_YAML_PATH (or NODE_PATH) to an existing copy, or npm install in _shared.
const fs = require('fs');
const path = require('path');
const { injectText } = require('../../_shared/inject.js');

function loadYaml() {
  const tries = [process.env.JS_YAML_PATH, 'js-yaml', path.join(__dirname, '..', '..', '_shared', 'node_modules', 'js-yaml')].filter(Boolean);
  for (const t of tries) {
    try { return require(require.resolve(t)); } catch { /* next */ }
  }
  throw new Error('js-yaml not found. Set JS_YAML_PATH, or run npm install in _shared.');
}

const here = __dirname;
const out = path.join(here, '..', 'password-expiry-reminder.yml');
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const block = (text, indent) => text.split('\n').map((l) => (l ? indent + l : '')).join('\n');
const COMMON = '__PE_COMMON__';

const steps = [
  { id: 'node-inputs', name: 'Read inputs', file: 'read-inputs.ps1', libs: [], timeout: 120,
    testInput: { preview: true, daysBeforeExpiry: '14,7,1', onlyUsers: '' } },
  { id: 'node-find', name: 'Find passwords that expire soon', file: 'find-expiring.ps1', libs: ['graph.ps1'], timeout: 900 },
  { id: 'node-send', name: 'Send reminders', file: 'send-reminders.ps1', libs: ['graph.ps1', 'postmark.ps1'], timeout: 1800 },
];

function render() {
  const L = [];
  L.push('automationsWorkflow: 1');
  L.push('name: Password Expiry Reminder');
  L.push("description: 'Daily check of Microsoft 365 passwords. Emails each person whose password expires in 14, 7 or 1 days with the date and how to change it, so nobody is locked out. Cloud accounts only: accounts synced from on-premises Active Directory are listed in warnings, never emailed. Run with preview true first. No AI.'");
  L.push('definition:');
  L.push('  schemaVersion: 1');
  L.push('  activities:');
  L.push('  - id: start', '    name: Start', '    type: start', '    position:', '      x: 100', '      y: 200', '    properties:',
    '      # Manual run or daily Routine: the first step reads Get-NodeInput, so the webhook stays off.',
    '      webhookEnabled: false');
  steps.forEach((s, i) => {
    const body = [];
    for (const lib of s.libs) body.push(`# >>> _shared/${lib} (generated by _shared/inject.js; edit the source, not this block)`, `# <<< _shared/${lib}`);
    body.push(COMMON, '', read(s.file));
    L.push(`  - id: ${s.id}`, `    name: ${s.name}`, '    type: powershell-script', '    position:', `      x: ${280 + i * 200}`, '      y: 200', '    properties:');
    L.push('      script: |-', block(body.join('\n'), '        '));
    L.push(`      timeoutSeconds: ${s.timeout}`, '      retryCount: 0', '      parameters: []', '      aiExtensions: []');
    if (s.testInput) L.push('      testInput: |-', block(JSON.stringify(s.testInput, null, 2), '        '));
  });
  L.push('  - id: end', '    name: End', '    type: end', '    position:', `      x: ${280 + steps.length * 200}`, '      y: 200');
  L.push('  connections:');
  const ids = ['start', ...steps.map((s) => s.id), 'end'];
  for (let i = 0; i < ids.length - 1; i++) L.push(`  - source: ${ids[i]}`, `    target: ${ids[i + 1]}`, '    sourceHandle: null');
  L.push('  startActivityId: start', '');
  // A function replacement, so the $ signs in the PowerShell are pasted as they are.
  const yml = L.join('\n').replace(new RegExp(`^( *)${COMMON}$`, 'gm'), (m, ind) => block(read('common.ps1'), ind));
  return injectText(yml, 'password-expiry-reminder.yml', new Map()).text;
}

function main(argv) {
  const y = loadYaml();
  const text = render();
  const doc = y.load(text);
  if (doc.automationsWorkflow !== 1) throw new Error('automationsWorkflow marker missing');
  const acts = doc.definition.activities;
  if (acts.find((a) => a.id === 'start').properties.webhookEnabled !== false) throw new Error('webhook must ship disabled');
  const scripts = acts.filter((a) => a.type === 'powershell-script');
  if (scripts.length !== steps.length) throw new Error('Wrong number of steps after build');
  if (/\{\{\s*input\./.test(text)) throw new Error('use nodes.<id>.output bindings, never input.*');
  if (/[\u2013\u2014]/.test(text)) throw new Error('no en or em dashes');
  if (text.includes(COMMON) || /# >>> _shared\/\S+ \(generated[^\n]*\n\s*# <<< /.test(text)) throw new Error('a library was not pasted');

  const ex = argv.indexOf('--extract');
  if (ex >= 0) {
    const dir = argv[ex + 1];
    if (!dir) throw new Error('--extract needs a folder');
    const cur = y.load(fs.readFileSync(out, 'utf8'));
    fs.mkdirSync(dir, { recursive: true });
    for (const a of cur.definition.activities) if (a.type === 'powershell-script') fs.writeFileSync(path.join(dir, `${a.id}.ps1`), a.properties.script);
    console.log(`Extracted ${scripts.length} steps to ${dir}`);
    return 0;
  }
  const check = argv.includes('--check');
  const was = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  const same = was === text;
  console.log(`password-expiry-reminder.yml: ${scripts.length} steps${same ? ' current' : check ? ' OUT OF DATE (run node src/build.js)' : ' written'}`);
  if (!same && !check) fs.writeFileSync(out, text);
  return !same && check ? 1 : 0;
}

if (require.main === module) {
  try { process.exit(main(process.argv.slice(2))); } catch (e) { console.error(e.message); process.exit(2); }
}
