# === NODE: Score the ticket ===
# Reads the ticket and its requester, then scores its impact with fixed rules (no AI):
#   - words that mean something is down or compromised, that someone is blocked, or that it's only a request;
#   - how many people are affected ("everyone", "the whole office", "12 users");
#   - the VIP list (the VIP-Companies secret, the same list VIP Ticket Alert uses);
#   - the company's tier (the Priority-CompanyTiers secret).
# The score picks a level. Automatic priority stops at high: a possible P1 is flagged to the dispatcher
# instead. A priority is only ever raised, never lowered.
# Accepts a flat {key:value} body (PSA webhook, ServiceAI Action, manual run), the CloudRadial
# {Ticket:{...}, Company:{...}} shape, or either one wrapped in {trigger:...}.
# Read-only: this step never writes to the PSA.
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
# >>> _shared/psa-tickets.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa-tickets.ps1
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
$stopState = @{ done = $false }
$warnings = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    param($Own)
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($Own) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
function Stop-Run {
    param([string]$Status, [string]$Why, [string]$TicketId = '')
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{
            status = $Status; message = $Why; public_note = ''
            internal_note = "Priority scoring stopped before anything was changed: $Why"
            ticket_id = $TicketId; actions = @(); warnings = @(Get-AllWarnings $warnings)
        })
    throw $Why
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = [string]$_.Exception.Message; public_note = ''; internal_note = "Priority scoring failed while reading the PSA: $($_.Exception.Message) Nothing was changed."; ticket_id = ''; actions = @(); warnings = @(Get-AllWarnings $warnings) }) }; break }

$raw = Get-NodeInput
if ($null -eq $raw) { Stop-Run 'incomplete' 'No input was received. Send at least ticketId.' }
if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The input was text that is not valid JSON.' } }
$wrap = Get-Prop $raw 'trigger'; if ($null -ne $wrap) { $raw = $wrap; if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The trigger body was text that is not valid JSON.' } } }
$answers = @{}
if ($raw -is [System.Collections.IDictionary]) { foreach ($k in @($raw.Keys)) { $answers[[string]$k] = $raw[$k] } }
else { foreach ($p in $raw.PSObject.Properties) { $answers[$p.Name] = $p.Value } }
$crTicket = Get-Prop $raw 'Ticket'
if ($null -ne $crTicket) {
    foreach ($q in @(Get-Prop $crTicket 'Questions')) { $qid = [string](Get-Prop $q 'Id'); if ($qid) { $answers[$qid] = Get-Prop $q 'Value' } }
    $tid = Get-Prop $crTicket 'TicketId'; if ($null -ne $tid) { $answers['ticketId'] = $tid }
}
function Get-Field {
    param([string[]]$Names)
    foreach ($n in $Names) {
        if (-not $answers.ContainsKey($n)) { continue }
        $v = $answers[$n]
        if ($null -eq $v -or $v -is [System.Management.Automation.PSCustomObject] -or $v -is [System.Collections.IDictionary]) { continue }
        $s = ([string]$v).Trim()
        # A bare @token (an unfilled CloudRadial placeholder) counts as not given; @contoso.com is a real value.
        if (-not $s -or $s -match '^@[A-Za-z][A-Za-z0-9_]*$' -or $s -match '^\{\{.*\}\}$' -or $s -match '^<[^>]*>$') { continue }
        return $s
    }
    return ''
}
function Get-Flag { param([string[]]$Names, [bool]$Default) $s = (Get-Field $Names).ToLowerInvariant(); if (-not $s) { return $Default }; return (@('true', 'yes', '1', 'y') -contains $s) }

$f = [ordered]@{
    ticketId   = (Get-Field @('ticketId', 'ticket_id', 'TicketId', 'ticketNumber', 'id'))
    psa        = (Get-Field @('psa'))
    confirm    = (Get-Flag @('confirm', 'approvedToWrite') $false)
    addNote    = (Get-Flag @('addNote') $true)
    vipList    = (Get-Field @('vip_list', 'vipList'))
    tiers      = (Get-Field @('company_tiers', 'companyTiers'))
    dispatcher = (Get-Field @('dispatcher_email', 'dispatcherEmail'))
}
if (-not $f.ticketId) { Stop-Run 'incomplete' 'ticketId is missing. Send the PSA ticket number of the ticket to score. Nothing was read.' }

$actions = New-Object System.Collections.ArrayList
$conn = Connect-Psa -Psa (Get-PsaType $f.psa)
$f.psa = $conn.Psa
$psaName = Get-PsaName
$id = ''
try { $id = Resolve-PsaTicketId $f.ticketId } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) wasn't found in $($psaName): $($_.Exception.Message)" $f.ticketId }
$t = $null
try { $t = Get-PsaTicket -Id $id } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) couldn't be read from $($psaName): $($_.Exception.Message)" $f.ticketId }
$row = ConvertTo-PsaTicketRow -Raw $t.raw
try { $null = Resolve-PsaTicketNames @($row) } catch { $null = $warnings.Add("The company name couldn't be looked up: $($_.Exception.Message)") }
$summary = $(if ($row.summary) { [string]$row.summary } else { [string]$t.summary })
$desc = $(if ($t.description) { [string]$t.description } else { [string]$row.description })
$companyName = [string]$row.companyName; $companyId = [string]$(if ($row.companyId) { $row.companyId } else { $t.companyId })
$contact = ([string]$row.contactEmail).ToLowerInvariant()
$null = $actions.Add("Read ticket $($f.ticketId) from $psaName.")

# ---- the score ----
$text = (" $summary `n $desc ").ToLowerInvariant()
$parts = New-Object System.Collections.ArrayList
function Add-Part { param([string]$Why, [int]$Points) $null = $parts.Add([ordered]@{ why = $Why; points = $Points }) }
function Find-Words { param([string]$Pattern) return @([regex]::Matches($text, $Pattern) | ForEach-Object { $_.Value.Trim() } | Select-Object -Unique) }
Add-Part 'starting score' 10
$w = @(Find-Words '\b(outage|is down|are down|went down|server down|site down|network down|internet (is )?down|no internet|ransomware|breach|hacked|compromised|malware|virus|data loss|lost (all )?data|security incident|encrypted files)\b')
if ($w.Count) { Add-Part "something is down or compromised ($($w -join ', '))" 40 }
$w = @(Find-Words "\b(can ?not|can't|cannot|unable to|not able to) (work|log ?in|sign ?in|access|connect|print|send|receive|open)\b|\b(locked out|not working|keeps crashing|crashed)\b")
if ($w.Count) { Add-Part "someone is blocked ($($w -join ', '))" 20 }
$w = @(Find-Words '\b(urgent|asap|emergency|immediately|right away)\b')
if ($w.Count) { Add-Part "marked urgent ($($w -join ', '))" 10 }
$w = @(Find-Words '\b(how do i|how to|question|request(ing)?|new user|set ?up|install|when convenient|no rush|whenever)\b')
if ($w.Count) { Add-Part "reads as a request or question ($($w -join ', '))" -10 }
$many = @(Find-Words '\b(everyone|everybody|all (users|staff|employees)|whole (office|company|team|site)|entire (office|company|team|site)|company-?wide|multiple (users|people)|several (users|people))\b')
$n = 0; foreach ($m in [regex]::Matches($text, '\b(\d{1,4})\s+(users|people|staff|employees|computers|machines|pcs|devices)\b')) { $v = [int]$m.Groups[1].Value; if ($v -gt $n) { $n = $v } }
if ($many.Count -or $n -ge 10) { Add-Part "many people affected ($(@($many) + @($(if ($n -ge 10) { "$n affected" })) -join ', '))" 25 }
elseif ($n -ge 2) { Add-Part "$n people affected" 15 }

# VIP: the same list format as VIP Ticket Alert (company name, PSA company id, contact email or @domain;
# anything after = is ignored here).
$listRaw = $(if ($f.vipList) { $f.vipList } else { [string](Get-PsaSecret 'VIP-Companies') })
$vip = ''
$cn = (($companyName -replace '\s+', ' ').Trim()).ToLowerInvariant()
$cd = $(if ($contact -match '@(.+)$') { '@' + $Matches[1] } else { '' })
foreach ($e in @($listRaw -split '[,;\r\n]+' | ForEach-Object { $_.Trim() } | Where-Object { $_ })) {
    $k = ((($e -replace '=.*$', '') -replace '\s+', ' ').Trim()).ToLowerInvariant(); if (-not $k) { continue }
    $hit = $(if ($k.StartsWith('@')) { $cd -and $k -eq $cd } elseif ($k.Contains('@')) { $contact -and $k -eq $contact } elseif ($k -match '^\d+$') { $companyId -and $k -eq $companyId } else { $cn -and $k -eq $cn })
    if ($hit) { $vip = $k; break }
}
if ($vip) { Add-Part "VIP ($vip is on the VIP list)" 15 }

# Tier: "Contoso=premium, Fabrikam=basic" (company name or PSA company id). Standard scores nothing.
$tierRaw = $(if ($f.tiers) { $f.tiers } else { [string](Get-PsaSecret 'Priority-CompanyTiers') })
$tier = 'standard'
foreach ($e in @($tierRaw -split '[,;\r\n]+' | ForEach-Object { $_.Trim() } | Where-Object { $_ -match '=' })) {
    $k = ((($e -replace '=.*$', '') -replace '\s+', ' ').Trim()).ToLowerInvariant(); $v = (($e -replace '^.*?=', '').Trim()).ToLowerInvariant()
    if (($cn -and $k -eq $cn) -or ($companyId -and $k -eq $companyId)) { $tier = $v; break }
}
if ($tier -match '^(premium|gold|platinum|enterprise)$') { Add-Part "$tier company" 10 }
elseif ($tier -match '^(basic|bronze|break-?fix)$') { Add-Part "$tier company" -5 }

$sum = 0; foreach ($pt in $parts) { $sum += [int]$pt.points }
$score = [Math]::Max(0, [Math]::Min(100, $sum))
$rank = @{ low = 1; medium = 2; high = 3; critical = 4 }
$scored = $(if ($score -ge 70) { 'critical' } elseif ($score -ge 45) { 'high' } elseif ($score -ge 25) { 'medium' } else { 'low' })
$target = $(if ($scored -eq 'critical') { 'high' } else { $scored })
$current = [string]$row.priorityLevel; $currentLabel = [string]$row.priority
$change = $false; $why = ''
if (-not $current) { $why = "The current priority ($(if ($currentLabel) { "'$currentLabel'" } else { 'none' })) couldn't be matched to a level, so it was left as it is." }
elseif ($rank[$current] -ge $rank[$target]) { $why = "The current priority ($currentLabel) is already $current or higher, so it was left as it is (this workflow never lowers a priority)." }
else { $change = $true; $why = "Raise from $current ($currentLabel) to $target." }
$flagP1 = ($scored -eq 'critical' -and $current -ne 'critical')
$null = $actions.Add("Scored ticket $($f.ticketId): $score of 100 ($scored).")

$ctx = [ordered]@{
    ticketId = $id; number = $f.ticketId; psa = $f.psa; confirm = $f.confirm; addNote = $f.addNote
    summary = $summary; company = $(if ($companyName) { $companyName } else { "company $companyId" }); dispatcher = $f.dispatcher
    score = $score; scored = $scored; target = $target; current = $current; currentLabel = $currentLabel
    change = $change; why = $why; flagP1 = $flagP1; parts = @($parts); vip = $vip; tier = $tier
    url = [string]$row.url; warnings = @(Get-AllWarnings $warnings); actions = @($actions)
}
Set-NodeOutput ([ordered]@{ status = 'ok'; score = $score; level = $scored; ctx_json = ($ctx | ConvertTo-Json -Depth 8 -Compress) })
