function ConvertTo-QbrUtc { param($v) if ($null -eq $v) { return $null }; if ($v -is [datetime]) { if ($v.Kind -eq [DateTimeKind]::Unspecified) { return [datetime]::SpecifyKind($v, [DateTimeKind]::Utc) }; return $v.ToUniversalTime() }; if ($v -is [datetimeoffset]) { return $v.UtcDateTime }; $d = [datetime]::MinValue; if ([string]$v -and [datetime]::TryParse([string]$v, [System.Globalization.CultureInfo]::InvariantCulture, [System.Globalization.DateTimeStyles]'AdjustToUniversal,AssumeUniversal', [ref]$d)) { return $d }; return $null }
function Get-QbrDay { param($v) $d = ConvertTo-QbrUtc $v; if ($null -ne $d) { return $d.ToString('d MMM yyyy', $ci) }; return [string]$v }
function Add-QbrTable {
    param($Sb, [string]$Caption, [string[]]$Head, [object[]]$Rows)
    $null = $Sb.Append("<p><strong>$(Enc $Caption)</strong></p><table><thead><tr>")
    foreach ($h in $Head) { $null = $Sb.Append("<th>$(Enc $h)</th>") }
    $null = $Sb.Append('</tr></thead><tbody>')
    foreach ($r in $Rows) { $null = $Sb.Append('<tr>'); foreach ($c in @($r)) { $null = $Sb.Append("<td>$(Enc $c)</td>") }; $null = $Sb.Append('</tr>') }
    $null = $Sb.Append('</tbody></table>')
}

