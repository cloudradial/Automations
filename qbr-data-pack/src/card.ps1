function Get-QbrTrend {
    param($cur, $prev)
    if ($null -eq $prev -or $null -eq $cur) { return '' }
    $c = [int]$cur; $p = [int]$prev
    if ($p -eq 0) { if ($c -eq 0) { return ', the same as the previous period' }; return ', compared with none in the previous period' }
    if ($c -eq $p) { return ", the same as the $p in the previous period" }
    $pct = [int][Math]::Round([Math]::Abs($c - $p) * 100.0 / $p)
    return ", $(if ($c -gt $p) { 'up' } else { 'down' }) $pct% from $p in the previous period"
}
