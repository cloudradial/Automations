# === STEP: Read CloudRadial data ===
# Edit this file, then run: node qbr-data-pack/src/build.js
# Read-only. Works out which CloudRadial company this run is for, then reads that company's endpoints,
# Planner cards, domains and certificates. Device age, warranty and operating system use the same rules as
# Endpoint LifeCycle Manager (endpoint-lifecycle-manager/src/elm.ps1).
# Every list is filtered to the one company, and filtered again here, so no other client's data is carried on.
# Secrets: CloudRadial-BaseUrl, CloudRadial-PublicKey, CloudRadial-PrivateKey, optional CloudRadial-CompanyId.
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
