# ---- device rules (same as Endpoint LifeCycle Manager) ----
function Get-QbrAge {
    param($ep)
    foreach ($f in @('manufacturedDate', 'biosDate', 'cpuDate')) { $d = ConvertTo-QbrDate (Get-QbrProp $ep $f); if ($d) { return @{ years = [math]::Round(($runDate - $d).TotalDays / 365.25, 1); estimated = ($f -ne 'manufacturedDate') } } }
    return $null
}
function Get-QbrWarranty {
    param($ep)
    $d = ConvertTo-QbrDate (Get-QbrProp $ep 'expirationDate')
    if (-not $d) { return @{ status = 'unknown'; date = $null } }
    if ($d -lt $runDate) { return @{ status = 'expired'; date = $d } }
    if ($d -le $runDate.AddDays(90)) { return @{ status = 'expiring'; date = $d } }
    return @{ status = 'active'; date = $d }
}
function Get-QbrOsType { param([string]$os) if ($os -match '(?i)windows') { 'windows' } elseif ($os -match '(?i)mac\s?os|os x') { 'macos' } else { 'other' } }
function Get-QbrOsSupport {
    param([string]$os, [string]$type)
    if ($type -eq 'windows') { if ($os -match '(?i)windows\s*11') { return 'supported' }; if ($os -match '(?i)windows\s*(10|8|7|xp|vista)') { return 'unsupported' }; return 'unknown' }
    if ($type -eq 'macos') { if ($os -match '(?i)mac\s?os[^\d]*(\d+)') { if ([int]$Matches[1] -ge 14) { return 'supported' }; return 'unsupported' }; return 'unknown' }
    return 'other'
}
function Get-QbrRamGb { param($ep) $b = 0.0; if ([double]::TryParse([string](Get-QbrProp $ep 'memory'), [System.Globalization.NumberStyles]::Float, $ci, [ref]$b) -and $b -gt 0) { return [math]::Round($b / 1073741824, 1) }; return $null }

# ---- endpoints ----
$dev = [ordered]@{
    available = $true; reason = ''; total = 0; workstations = 0; servers = 0; virtual = 0
    age = [ordered]@{ 'Under 3 years' = 0; '3 to 5 years' = 0; '5 to 7 years' = 0; '7 years or more' = 0; 'Unknown' = 0 }
    ageEstimated = 0
    warranty = [ordered]@{ expired = 0; expiring = 0; active = 0; unknown = 0 }
    os = [ordered]@{ supported = 0; unsupported = 0; unknown = 0; other = 0 }
    replace = 0; stale = 0; warrantySoon = @()
}
try {
    $eps = @(Get-CrAll "/v2/odata/endpoint?`$filter=companyId eq $companyId" | Where-Object { $null -ne $_ -and [int](Get-QbrProp $_ 'companyId') -eq $companyId })
    $soon = New-Object System.Collections.ArrayList
    foreach ($ep in $eps) {
        $dev.total++
        $isServer = [bool](Get-QbrProp $ep 'isServer'); $isVirtual = [bool](Get-QbrProp $ep 'isVirtual')
        if ($isVirtual) { $dev.virtual++ } elseif ($isServer) { $dev.servers++ } else { $dev.workstations++ }
        $os = [string](Get-QbrProp $ep 'os'); $type = Get-QbrOsType $os; $sup = Get-QbrOsSupport $os $type
        $dev.os[$sup]++
        $seen = ConvertTo-QbrDate (Get-QbrProp $ep 'lastCheckIn'); if ($seen -and $seen -lt $runDate.AddDays(-30)) { $dev.stale++ }
        if ($isVirtual) { continue }   # age and warranty mean nothing for a virtual machine
        $a = Get-QbrAge $ep
        $bucket = if ($null -eq $a) { 'Unknown' } elseif ($a.years -ge 7) { '7 years or more' } elseif ($a.years -ge 5) { '5 to 7 years' } elseif ($a.years -ge 3) { '3 to 5 years' } else { 'Under 3 years' }
        $dev.age[$bucket]++
        if ($null -ne $a -and $a.estimated) { $dev.ageEstimated++ }
        $war = Get-QbrWarranty $ep
        $dev.warranty[$war.status]++
        if ($war.status -eq 'expiring') { $null = $soon.Add(@{ name = [string](Get-QbrProp $ep 'name'); date = $war.date }) }
        # Endpoint LifeCycle Manager's "Replace" rule for a workstation.
        $ram = Get-QbrRamGb $ep
        $w11 = ([string](Get-QbrProp $ep 'windows11Readiness')) -match '(?i)installed|ready|capable'
        if (-not $isServer -and $type -ne 'other' -and (($null -ne $a -and $a.years -ge 5) -or ($sup -eq 'unsupported' -and -not $w11) -or ($null -ne $ram -and $ram -lt 4))) { $dev.replace++ }
    }
    $dev.warrantySoon = @($soon | Sort-Object { $_.date } | ForEach-Object { @{ name = $_.name; ends = (Format-QbrDate $_.date) } })
}
catch {
    $dev.available = $false; $dev.reason = "Couldn't read the endpoints: $($_.Exception.Message)"
    $null = $warnings.Add($dev.reason)
}
$out.devices = $dev

