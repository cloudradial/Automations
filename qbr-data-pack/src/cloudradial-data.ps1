$out.planner = $plan

# ---- domains (60 days) and certificates (30 days) ----
function Get-QbrExpiring {
    param([object[]]$Rows, [string]$DateField, [int]$Window, [string[]]$NameFields)
    $list = New-Object System.Collections.ArrayList; $total = 0
    foreach ($r in $Rows) {
        $total++
        $d = ConvertTo-QbrDate (Get-QbrProp $r $DateField); if (-not $d) { continue }
        if ($d -gt $runDate.AddDays($Window)) { continue }
        $name = ''; foreach ($f in $NameFields) { $name = [string](Get-QbrProp $r $f); if ($name) { break } }
        $left = [int][math]::Floor(($d - $runDate).TotalDays)
        $null = $list.Add([ordered]@{ name = $name; expires = (Format-QbrDate $d); daysLeft = $left; status = $(if ($left -lt 0) { 'expired' } else { 'expiring' }) })
    }
    return @{ total = $total; items = @($list | Sort-Object { $_.daysLeft }) }
}
$dom = [ordered]@{ available = $true; reason = ''; window = 60; total = 0; items = @() }
$domainNames = @()
try {
    $rows = @(Get-CrAll "/v2/odata/domain?`$filter=companyId eq $companyId" | Where-Object { $null -ne $_ -and [int](Get-QbrProp $_ 'companyId') -eq $companyId -and -not [bool](Get-QbrProp $_ 'isDeleted') })
    $domainNames = @($rows | ForEach-Object { ([string](Get-QbrProp $_ 'name')).Trim().ToLowerInvariant() } | Where-Object { $_ })
    $e = Get-QbrExpiring $rows 'dateExpires' 60 @('name'); $dom.total = $e.total; $dom.items = $e.items
}
catch { $dom.available = $false; $dom.reason = "Couldn't read the domains: $($_.Exception.Message)"; $null = $warnings.Add($dom.reason) }
$cert = [ordered]@{ available = $true; reason = ''; window = 30; total = 0; items = @() }
try {
    $rows = @(Get-CrAll "/v2/odata/certificate?`$filter=companyId eq $companyId" | Where-Object { $null -ne $_ -and [int](Get-QbrProp $_ 'companyId') -eq $companyId -and -not [bool](Get-QbrProp $_ 'isDeleted') })
    $e = Get-QbrExpiring $rows 'expirationDate' 30 @('name', 'subject', 'url'); $cert.total = $e.total; $cert.items = $e.items
}
catch { $cert.available = $false; $cert.reason = "Couldn't read the certificates: $($_.Exception.Message)"; $null = $warnings.Add($cert.reason) }
$out.domains = $dom
$out.certificates = $cert
$out.domainNames = $domainNames
$out.warnings = @($warnings)
$out.status = 'ok'
Set-NodeOutput $out
