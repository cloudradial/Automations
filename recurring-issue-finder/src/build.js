// Builds the Recurring Issue Finder agent and goal workflow for each PSA:
//   recurring-issue-finder-<psa>.agent.yml  and  recurring-issue-finder-<psa>.yml
// from src/prompt.md, src/psa.js and src/settings.ps1. Never edit the .yml files by hand.
//   node src/build.js          write the six files
//   node src/build.js --check  exit 1 if any file is out of date
const fs = require('fs');
const path = require('path');
const PSAS = require('./psa');

const VERSION = '1.0.0';
const ROOT = path.join(__dirname, '..');
const SLUG = 'recurring-issue-finder';

const block = (text, indent) => '|\n' + text.replace(/\r\n/g, '\n').replace(/\s+$/, '').split('\n')
  .map((l) => (l ? ' '.repeat(indent) + l : '')).join('\n');
const q = (s) => JSON.stringify(s);

const INPUT_SCHEMA = {
  type: 'object',
  properties: {
    request: { type: 'string', description: 'Check-in settings in plain words: look-back days, minimum tickets per theme, most proposals, and today\'s date. Optional; the defaults are 30 days, 3 tickets and 3 proposals.' },
  },
};
const OUTPUT_SCHEMA = {
  type: 'object',
  properties: {
    window: { type: 'string', description: 'The look-back used, for example "2026-10-14 to 2026-11-13".' },
    ticketsRead: { type: 'number' },
    themes: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          client: { type: 'string' },
          clientId: { type: 'string' },
          theme: { type: 'string' },
          ticketIds: { type: 'array', items: { type: 'string' } },
          count: { type: 'number' },
          proposed: { type: 'boolean' },
          reason: { type: 'string', description: 'Why it was or was not proposed.' },
        },
        required: ['client', 'theme', 'ticketIds', 'count', 'proposed'],
      },
    },
    proposals: { type: 'number', description: 'Problem tickets proposed in this check-in.' },
    standardsApplied: { type: 'array', items: { type: 'string' }, description: 'Each rule used, as "document - heading: rule".' },
    standardsSource: { type: 'string', enum: ['knowledge', 'mixed', 'default'] },
    questions: { type: 'array', items: { type: 'string' } },
    summary: { type: 'string' },
  },
  required: ['ticketsRead', 'themes', 'proposals', 'summary'],
};

function systemPrompt(p) {
  return fs.readFileSync(path.join(__dirname, 'prompt.md'), 'utf8').replace(/\r\n/g, '\n')
    .replace('{{PSA_LABEL}}', p.label)
    .replace('{{PSA_STEPS}}', p.steps)
    .replace('{{KB_WHERE}}', p.kbWhere);
}

function details(p, key) {
  return `## What it does

Looks at each client's recent ${p.name} service tickets, finds the issues that keep coming back, and proposes a problem ticket with a knowledge base draft for the top three. Built for a Pulsar that checks in once a week; also runs from its goal workflow, **Recurring Issue Finder (${p.name})**.

## Safe by design

- It only reads tickets. Its only writes are ${p.writeTools.map((t) => '`' + t + '`').join(' and ')}, and each one is a proposal a person approves.
- It never changes, merges or closes an existing ticket.
- It never proposes a theme that is already pending or that an open problem ticket covers.

## Your rules

Upload **Recurring Issue Rules** and **Problem Ticket Standards** (templates in the repo's \`${SLUG}/knowledge/\` folder) to the Pulsar's notes folder. Without them it uses built-in defaults: 30 days, themes of 3 or more tickets, the top 3, and a board or queue whose name contains "Problem".

## Needs

The **${p.extension}** extension, connected. Setup steps: the README in \`${SLUG}/\` in the CloudRadial Automations repo.`;
}

function agentYaml(key, p) {
  return `# CloudRadial AutomationAI - Recurring Issue Finder agent for ${p.name}.
# GENERATED by recurring-issue-finder/src/build.js from src/prompt.md and src/psa.js. Do not edit by hand.
# Upload on Agents > Custom. Uploading is keyed on the slug below.
# Use it as the agent of a Recurring Issue Finder Pulsar (README), or run it from
# ${SLUG}-${key}.yml. Every write it makes is a proposal a person approves.

automationsAgent: 1
agent:
  slug: ${SLUG}-${key}
  name: ${q('Recurring Issue Finder (' + p.name + ')')}
  vendor: CloudRadial
  version: ${VERSION}
  description: ${q('Finds the issues that keep coming back in each client\'s ' + p.name + ' tickets and proposes a problem ticket with a KB draft for the top ones.')}
  category: Ticketing
  tags:
    - ticketing
    - problem-management
    - knowledge-base
    - pulsar
    - ${key}
  detailsMarkdown: ${block(details(p, key), 4)}
  systemPrompt: ${block(systemPrompt(p), 4)}
  model: ""   # blank = the tenant's own model (OpenAI or Anthropic); pinning a model name fails on other providers
  requiredExtensionSlugs:
    - ${p.extension}
  requiredSecretNames: []
  variablesJson: |
    []
  inputSchema: |
    ${JSON.stringify(INPUT_SCHEMA)}
  outputSchema: |
    ${JSON.stringify(OUTPUT_SCHEMA)}
  dryRunDefault: true
`;
}

function workflowYaml(key, p) {
  const settings = fs.readFileSync(path.join(__dirname, 'settings.ps1'), 'utf8');
  const goal = `Run one Recurring Issue Finder check-in in ${p.name}. Your request input gives the look-back, the minimum tickets per theme, the most proposals and today's date. Read your notes and the Recurring Issue Rules and Problem Ticket Standards when you have them. Read the tickets in one or two bulk queries, group each client's tickets into themes, rank them, and propose a problem ticket with a KB draft for each top theme that isn't already proposed or covered by an open problem ticket. Every write is a proposal for approval; change nothing else. Return the structured output.`;
  const agentIn = { type: 'object', properties: { request: { type: 'string' } }, required: ['request'], additionalProperties: false };
  return `# GENERATED by recurring-issue-finder/src/build.js. Do not edit by hand.
automationsWorkflow: 1
name: ${q('Recurring Issue Finder (' + p.name + ')')}
description: ${q('Runs one Recurring Issue Finder check-in by hand: finds the issues that keep coming back in each client\'s last 30 days of ' + p.name + ' tickets and proposes a problem ticket with a KB draft for the top three, each waiting for approval. Import the Recurring Issue Finder (' + p.name + ') agent first. Optional run input: {"lookback_days": 30, "min_tickets": 3, "max_proposals": 3}.')}
definition:
  schemaVersion: 1
  activities:
    - id: start
      name: Start
      type: start
      position:
        x: 100
        y: 120
      properties:
        webhookEnabled: false
    - id: node-settings
      name: Check-in settings
      type: powershell-script
      position:
        x: 300
        y: 120
      properties:
        script: ${block(settings, 10)}
        timeoutSeconds: 60
        retryCount: 0
        parameters: []
        aiExtensions: []
        testInput: |-
          {"lookback_days": 30, "min_tickets": 3, "max_proposals": 3}
    - id: node-agent
      name: Find recurring issues
      type: agent
      position:
        x: 520
        y: 120
      properties:
        agentSlug: ${SLUG}-${key}
        goal: ${q(goal)}
        model: ""
        # Never leave this list empty: an empty list gives the agent every installed extension.
        allowedExtensions:
          - ${p.extension}
        timeoutSeconds: 900
        autoApprove: false
        inputBindingsJson: '{"request":"{{ nodes.node-settings.output.request }}"}'
        inputSchema: '${JSON.stringify(agentIn)}'
        outputSchema: '${JSON.stringify(OUTPUT_SCHEMA).replace(/'/g, "''")}'
    - id: end
      name: End
      type: end
      position:
        x: 740
        y: 120
  connections:
    - source: start
      target: node-settings
      sourceHandle: null
    - source: node-settings
      target: node-agent
      sourceHandle: null
    - source: node-agent
      target: end
      sourceHandle: null
  startActivityId: start
`;
}

function outputs() {
  const files = {};
  for (const [key, p] of Object.entries(PSAS)) {
    files[`${SLUG}-${key}.agent.yml`] = agentYaml(key, p);
    files[`${SLUG}-${key}.yml`] = workflowYaml(key, p);
  }
  return files;
}

module.exports = { outputs, VERSION, SLUG, ROOT };

if (require.main === module) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [name, text] of Object.entries(outputs())) {
    const file = path.join(ROOT, name);
    const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (cur === text) continue;
    if (check) { console.log('OUT OF DATE: ' + name); stale++; } else { fs.writeFileSync(file, text); console.log('wrote ' + name); }
  }
  if (check) { console.log(stale ? `${stale} file(s) out of date` : 'all files current'); process.exit(stale ? 1 : 0); }
}
