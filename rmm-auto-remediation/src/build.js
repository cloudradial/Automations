// Builds ../rmm-auto-remediation.yml: the rmm-agent node, then the "Open PSA ticket" step from ticket.ps1,
// with the shared libraries pasted in by ../../_shared/inject.js.
// Usage: node build.js                 rewrite the .yml
//        node build.js --check         exit 1 if the .yml is out of date
//        node build.js --extract <dir>  write each step's finished script to <dir>/<node-id>.ps1 (used by test.ps1)
// Edit ticket.ps1 and the agent node below, never the .yml.
// Needs js-yaml: set JS_YAML_PATH (or NODE_PATH) to an existing copy, or npm install in _shared.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

// Returns js-yaml and sets JS_YAML_PATH so inject.js uses the same copy.
function loadYaml() {
  const tries = [process.env.JS_YAML_PATH, 'js-yaml', path.join(__dirname, '..', '..', '_shared', 'node_modules', 'js-yaml')].filter(Boolean);
  for (const t of tries) {
    try { const p = require.resolve(t); const y = require(p); process.env.JS_YAML_PATH = p; return y; } catch { /* next */ }
  }
  throw new Error('js-yaml not found. Set JS_YAML_PATH, or run npm install in _shared.');
}

const here = __dirname;
const folder = path.join(here, '..');
const out = path.join(folder, 'rmm-auto-remediation.yml');
const inject = path.join(here, '..', '..', '_shared', 'inject.js');

const goal = `A Datto RMM alert has fired. Use exactly the alert in your input (alertUid, and
usually deviceUid and siteUid); never pick a different alert or device.
The trigger: {{ nodes.trigger.output }}
1. Read the alert (datto_get_device_alerts or datto_get_site_alerts) and
   the device (datto_get_device; datto_get_device_hardware for disk free
   space). Note the device's Datto site and match it to a CloudRadial
   company as your instructions describe.
2. SAFETY: if the device category is Server, do NOT remediate. Escalate
   (escalate true, with the ticket fields) and stop.
3. For a low-disk alert on a workstation, run the disk-cleanup component
   with datto_run_quick_job (use the cleanupComponentUid variable), poll
   datto_get_job until it completes, then re-read datto_get_device_hardware.
4. If free space is back above the threshold, resolve the alert
   (datto_resolve_alert), report the before/after free-space numbers and
   return escalate false. Otherwise escalate with the detail and leave the
   alert open.
5. Any other alert type: don't remediate; escalate it.
You have no PSA tools. A later step opens the ticket in the MSP's PSA from
your escalate, ticketSummary, ticketDescription, ticketNote, ticketPriority,
siteName and cloudradialCompanyId fields. Keep technical detail in ticketNote.
Always return alertUid, and dryRun true when this run is a preview.
If the input has no alertUid, don't search for one: return escalate false and
say the trigger had no alert.`;

const agentInput = { type: 'object', properties: { alertUid: { type: 'string' }, deviceUid: { type: 'string' }, siteUid: { type: 'string' } }, required: ['alertUid'] };
// The trigger fields are bound to the agent's input; without this the agent never sees the alert.
const agentBindings = { alertUid: '{{ nodes.trigger.output.alertUid }}', deviceUid: '{{ nodes.trigger.output.deviceUid }}', siteUid: '{{ nodes.trigger.output.siteUid }}' };
const agentOutput = {
  type: 'object',
  properties: {
    status: { type: 'string' }, action: { type: 'string' }, alertUid: { type: 'string' }, deviceUid: { type: 'string' },
    alertResolved: { type: 'boolean' }, escalate: { type: 'boolean' },
    ticketSummary: { type: 'string' }, ticketDescription: { type: 'string' }, ticketNote: { type: 'string' },
    ticketPriority: { type: 'string', enum: ['critical', 'high', 'medium', 'low'] },
    siteName: { type: 'string' }, cloudradialCompanyId: { type: 'number' }, dryRun: { type: 'boolean' }, notes: { type: 'string' },
  },
  required: ['alertUid', 'escalate'],
};
const ticketStep = { id: 'node-ticket', name: 'Open PSA ticket', file: 'ticket.ps1', libs: ['psa.ps1', 'cloudradial.ps1'], timeout: 300 };

const marker = (lib) => [`# >>> _shared/${lib} (generated by _shared/inject.js; edit the source, not this block)`, `# <<< _shared/${lib}`];
const ind = (lines, n) => lines.map((l) => (l ? ' '.repeat(n) + l : ''));

function render() {
  const L = [];
  L.push('automationsWorkflow: 1');
  L.push('name: RMM Auto-Remediation');
  L.push("description: 'A Datto RMM alert gets a safe fix by the RMM agent: a workstation low-disk alert runs the cleanup component, is re-checked and resolved. Servers are never remediated. Anything that can not be fixed safely becomes a ticket in ConnectWise PSA, Autotask, HaloPSA, Kaseya BMS, Syncro or Zendesk, opened by a PowerShell step from the text the agent returns.'");
  L.push('definition:');
  L.push('  schemaVersion: 1');
  L.push('  activities:');
  L.push('  - id: start', '    name: Start', '    type: start', '    position:', '      x: 100', '      y: 80', '    properties:', '      webhookEnabled: false');
  L.push('  - id: node-1', '    name: Agent', '    type: agent', '    position:', '      x: 310', '      y: 110', '    properties:');
  L.push('      goal: |-', ...ind(goal.split('\n'), 8));
  L.push('      model: ""');
  L.push('      allowedExtensions:', '      - datto-rmm', '      - cloudradial-v2-companies');
  L.push('      timeoutSeconds: 600', '      autoApprove: false', '      agentSlug: rmm-agent');
  L.push(`      inputBindingsJson: '${JSON.stringify(agentBindings)}'`);
  L.push(`      inputSchema: '${JSON.stringify(agentInput)}'`);
  L.push(`      outputSchema: '${JSON.stringify(agentOutput)}'`);
  const src = fs.readFileSync(path.join(here, ticketStep.file), 'utf8').replace(/\r\n/g, '\n').trimEnd().split('\n');
  const body = [];
  for (const lib of ticketStep.libs) body.push(...marker(lib));
  body.push('', ...src);
  L.push(`  - id: ${ticketStep.id}`, `    name: ${ticketStep.name}`, '    type: powershell-script', '    position:', '      x: 520', '      y: 110', '    properties:');
  L.push('      script: |-', ...ind(body, 8));
  L.push(`      timeoutSeconds: ${ticketStep.timeout}`, '      retryCount: 0', '      parameters: []', '      aiExtensions: []');
  L.push('  - id: end', '    name: End', '    type: end', '    position:', '      x: 730', '      y: 80');
  L.push('  connections:');
  const ids = ['start', 'node-1', ticketStep.id, 'end'];
  for (let i = 0; i < ids.length - 1; i++) L.push(`  - source: ${ids[i]}`, `    target: ${ids[i + 1]}`, '    sourceHandle: null');
  L.push('  startActivityId: start', '');
  return L.join('\n');
}

function main(argv) {
  const y = loadYaml();
  const ex = argv.indexOf('--extract');
  if (ex >= 0) {
    const dir = argv[ex + 1];
    if (!dir) throw new Error('--extract needs a folder');
    fs.mkdirSync(dir, { recursive: true });
    const doc = y.load(fs.readFileSync(out, 'utf8'));
    const ps = doc.definition.activities.filter((a) => a.type === 'powershell-script');
    for (const a of ps) fs.writeFileSync(path.join(dir, `${a.id}.ps1`), a.properties.script);
    console.log(`Extracted ${ps.length} steps to ${dir}`);
    return 0;
  }
  const check = argv.includes('--check');
  // Render with empty marker blocks, fill them in a temp copy, and compare with (or replace) the real file.
  const tmpDir = fs.mkdtempSync(path.join(require('os').tmpdir(), 'rar-'));
  const tmp = path.join(tmpDir, 'rmm-auto-remediation.yml');
  fs.writeFileSync(tmp, render());
  execFileSync(process.execPath, [inject, tmpDir], { stdio: 'pipe', env: process.env });
  const next = fs.readFileSync(tmp, 'utf8');
  fs.rmSync(tmpDir, { recursive: true, force: true });
  const doc = y.load(next);
  const agent = doc.definition.activities.find((a) => a.id === 'node-1');
  JSON.parse(agent.properties.inputSchema); JSON.parse(agent.properties.outputSchema);
  if (doc.definition.activities.filter((a) => a.type === 'powershell-script').length !== 1) throw new Error('Wrong number of steps after build');
  const was = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  const same = was === next;
  console.log(`rmm-auto-remediation.yml${same ? ' current' : check ? ' OUT OF DATE' : ' written'}`);
  if (!same && !check) fs.writeFileSync(out, next);
  return !same && check ? 1 : 0;
}

if (require.main === module) {
  try { process.exit(main(process.argv.slice(2))); } catch (e) { console.error(e.message); process.exit(2); }
}
