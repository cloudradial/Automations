// Builds scalepad-warranty-sync.yml from warranty.ps1, then pastes the shared CloudRadial library into it
// (_shared/inject.js).
// Usage: node build.js          rewrite the .yml
//        node build.js --check  exit 1 if the .yml is out of date
// Edit warranty.ps1 (or _shared/cloudradial.ps1), never the .yml.
// Needs js-yaml: set JS_YAML_PATH (or NODE_PATH) to an existing copy, or npm install in _shared.
const fs = require('fs');
const path = require('path');
const { injectText } = require('../../_shared/inject.js');

function loadYaml() {
  try { return require('js-yaml'); } catch { /* fall through */ }
  if (process.env.JS_YAML_PATH) return require(process.env.JS_YAML_PATH);
  throw new Error('js-yaml not found. Set JS_YAML_PATH, or npm install in _shared.');
}

const here = __dirname;
const name = 'scalepad-warranty-sync';
const out = path.join(here, '..', `${name}.yml`);
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const block = (text, indent) => text.split('\n').map((l) => (l ? indent + l : '')).join('\n');
const shared = (lib) => `# >>> _shared/${lib} (generated by _shared/inject.js; edit the source, not this block)\n# <<< _shared/${lib}`;
const body = [shared('cloudradial.ps1'), read('warranty.ps1')].join('\n');

// A preview: a test run in the designer changes nothing.
const testInput = JSON.stringify({ confirm: false }, null, 2);

const yml = `automationsWorkflow: 1
name: ScalePad Warranty Sync
description: Keeps CloudRadial endpoint warranty dates matched to ScalePad Lifecycle Manager for every company that
  matches a ScalePad client by name, and keeps one Endpoint Warranty Renewal Planner card per company listing the
  computers whose warranty has ended. Moves nothing else from ScalePad, and the card never mentions ScalePad.
  Previews by default; run with confirm true (for example from a weekly Routine) to make the changes.
definition:
  schemaVersion: 1
  activities:
  - id: start
    name: Start
    type: start
    position:
      x: 100
      y: 80
    properties:
      webhookEnabled: false
  - id: node-sync
    name: Sync warranty dates
    type: powershell-script
    position:
      x: 320
      y: 80
    properties:
      script: |-
${block(body, '        ')}
      timeoutSeconds: 1800
      retryCount: 0
      # No binding: a manual run or Routine hands this step its input through Get-NodeInput.
      parameters: []
      aiExtensions: []
      testInput: |-
${block(testInput, '        ')}
  - id: end
    name: End
    type: end
    position:
      x: 540
      y: 80
  connections:
  - source: start
    target: node-sync
    sourceHandle: null
  - source: node-sync
    target: end
    sourceHandle: null
  startActivityId: start
`;

const y = loadYaml();
const { text } = injectText(yml, `${name}.yml`, new Map());
const doc = y.load(text);
// Guard rails: the shape every workflow must have.
if (doc.automationsWorkflow !== 1) throw new Error('automationsWorkflow marker missing');
const acts = doc.definition.activities;
if (acts.find((a) => a.id === 'start').properties.webhookEnabled !== false) throw new Error('webhook must ship disabled');
if (acts.some((a) => a.properties && a.properties.model)) throw new Error('model must be blank');
if (/\{\{\s*input\./.test(text)) throw new Error('use nodes.<id>.output bindings, never input.*');
if (/[\u2013\u2014]/.test(text)) throw new Error('no en or em dashes');
if (/webhookSecret/.test(text)) throw new Error('no webhook secret in the export');
if (!acts.find((a) => a.id === 'node-sync').properties.script.includes('function Set-CrPlannerCard')) throw new Error('the shared CloudRadial library was not pasted in');
const ids = new Set(acts.map((a) => a.id));
for (const c of doc.definition.connections) if (!ids.has(c.source) || !ids.has(c.target)) throw new Error(`bad connection ${c.source} -> ${c.target}`);

const check = process.argv.includes('--check');
const was = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
if (text === was) { console.log(`${name}.yml: current`); process.exit(0); }
if (check) { console.log(`${name}.yml: OUT OF DATE (run node src/build.js)`); process.exit(1); }
fs.writeFileSync(out, text);
console.log(`${name}.yml: written`);
