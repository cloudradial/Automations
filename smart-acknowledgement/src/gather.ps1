# === NODE: Read the ticket and plan the acknowledgement ===
# Reads the ticket, its contact and priority, and works out the facts the acknowledgement may state:
#   - the response target only (never a resolution time): the PSA's own SLA response target when it has one,
#     else the target for the ticket's priority (the Ack-ResponseTargets secret, or the defaults below);
#   - up to eight published CloudRadial knowledge base articles from the ticket's own company or the
#     MSP-wide articles, ranked by shared words, for the AI step to choose from.
# Stops quietly when the ticket is closed, has no contact email, or was already acknowledged.
# Accepts a flat {key:value} body (PSA webhook, ServiceAI Action, manual run), the CloudRadial
# {Ticket:{...}, Company:{...}} shape, or either one wrapped in {trigger:...}.
# Read-only: this step never writes to the PSA or CloudRadial.
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
# >>> _shared/psa-tickets.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa-tickets.ps1
# >>> _shared/cloudradial.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/cloudradial.ps1
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
$stopState = @{ done = $false }
$warnings = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    param($Own)
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($Own) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
function Stop-Run {
    param([string]$Status, [string]$Why, [string]$TicketId = '')
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{
            status = $Status; message = $Why; public_note = ''
            internal_note = "Acknowledgement not sent: $Why"
            ticket_id = $TicketId; actions = @(); warnings = @(Get-AllWarnings $warnings)
        })
    throw $Why
}
# A quiet stop (closed, already acknowledged): the later steps see skip and the run ends with success.
function Skip-Run {
    param([string]$Why)
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = 'ok'; facts_json = '{"skip": true}'; ctx_json = ([ordered]@{ skip = $Why; number = $f.ticketId; actions = @($actions); warnings = @(Get-AllWarnings $warnings) } | ConvertTo-Json -Depth 5 -Compress) })
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = [string]$_.Exception.Message; public_note = ''; internal_note = "Acknowledgement failed while reading the ticket: $($_.Exception.Message) Nothing was sent."; ticket_id = ''; actions = @(); warnings = @(Get-AllWarnings $warnings) }) }; break }

$raw = Get-NodeInput
if ($null -eq $raw) { Stop-Run 'incomplete' 'No input was received. Send at least ticketId.' }
if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The input was text that is not valid JSON.' } }
$wrap = Get-Prop $raw 'trigger'; if ($null -ne $wrap) { $raw = $wrap; if ($raw -is [string]) { try { $raw = $raw | ConvertFrom-Json } catch { Stop-Run 'incomplete' 'The trigger body was text that is not valid JSON.' } } }
$answers = @{}
if ($raw -is [System.Collections.IDictionary]) { foreach ($k in @($raw.Keys)) { $answers[[string]$k] = $raw[$k] } }
else { foreach ($p in $raw.PSObject.Properties) { $answers[$p.Name] = $p.Value } }
$crTicket = Get-Prop $raw 'Ticket'
if ($null -ne $crTicket) {
    foreach ($q in @(Get-Prop $crTicket 'Questions')) { $qid = [string](Get-Prop $q 'Id'); if ($qid) { $answers[$qid] = Get-Prop $q 'Value' } }
    $tid = Get-Prop $crTicket 'TicketId'; if ($null -ne $tid) { $answers['ticketId'] = $tid }
}
function Get-Field {
    param([string[]]$Names)
    foreach ($n in $Names) {
        if (-not $answers.ContainsKey($n)) { continue }
        $v = $answers[$n]
        if ($null -eq $v -or $v -is [System.Management.Automation.PSCustomObject] -or $v -is [System.Collections.IDictionary]) { continue }
        $s = ([string]$v).Trim()
        # A bare @token (an unfilled CloudRadial placeholder) counts as not given.
        if (-not $s -or $s -match '^@[A-Za-z][A-Za-z0-9_]*$' -or $s -match '^\{\{.*\}\}$' -or $s -match '^<[^>]*>$') { continue }
        return $s
    }
    return ''
}
function Get-Flag { param([string[]]$Names, [bool]$Default) $s = (Get-Field $Names).ToLowerInvariant(); if (-not $s) { return $Default }; return (@('true', 'yes', '1', 'y') -contains $s) }

$f = [ordered]@{
    ticketId     = (Get-Field @('ticketId', 'ticket_id', 'TicketId', 'ticketNumber', 'id'))
    psa          = (Get-Field @('psa'))
    confirm      = (Get-Flag @('confirm', 'approvedToWrite') $false)
    crCompanyId  = (Get-Field @('crCompanyId', 'cloudRadialCompanyId'))
    includeKb    = (Get-Flag @('includeArticles', 'include_articles') $true)
}
if (-not $f.ticketId) { Stop-Run 'incomplete' 'ticketId is missing. Send the PSA ticket number to acknowledge. Nothing was read.' }

$actions = New-Object System.Collections.ArrayList
$conn = Connect-Psa -Psa (Get-PsaType $f.psa)
$f.psa = $conn.Psa
$psaName = Get-PsaName
$id = ''
try { $id = Resolve-PsaTicketId $f.ticketId } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) wasn't found in $($psaName): $($_.Exception.Message)" $f.ticketId }
$t = $null
try { $t = Get-PsaTicket -Id $id } catch { Stop-Run 'incomplete' "Ticket $($f.ticketId) couldn't be read from $($psaName): $($_.Exception.Message)" $f.ticketId }
$row = ConvertTo-PsaTicketRow -Raw $t.raw
$row.id = $id
$null = $actions.Add("Read ticket $($f.ticketId) from $psaName.")
# Autotask and Zendesk tickets carry only the contact's id, so the email and name are read from the contact.
if (-not $row.contactEmail -and -not (Test-PsaBlank $row.contactId)) {
    try {
        switch ($f.psa) {
            'autotask' { $ct = Get-PsaProp (Invoke-PsaRead "/Contacts/$($row.contactId)" 'read the ticket''s contact' 'read contacts') 'item'; $row.contactEmail = [string](Get-PsaProp $ct 'emailAddress'); if (-not $row.contactName) { $row.contactName = ("$(Get-PsaProp $ct 'firstName') $(Get-PsaProp $ct 'lastName')").Trim() } }
            'zendesk' { $ct = Get-PsaProp (Invoke-PsaRead "/users/$($row.contactId)" 'read the ticket''s requester' 'read users') 'user'; $row.contactEmail = [string](Get-PsaProp $ct 'email'); if (-not $row.contactName) { $row.contactName = [string](Get-PsaProp $ct 'name') } }
        }
    }
    catch { $null = $warnings.Add("The ticket's contact couldn't be read: $($_.Exception.Message)") }
}
if ($row.isClosed) { Skip-Run "Ticket $($f.ticketId) is already closed, so no acknowledgement was needed."; return }
$email = [string]$row.contactEmail
if (-not ($email -match '^[^@\s]+@[^@\s]+\.[^@\s]+$')) { Stop-Run 'incomplete' "Ticket $($f.ticketId) has no contact email address, so $psaName wouldn't email an acknowledgement to anyone. Nothing was sent." $f.ticketId }
# Already acknowledged by this workflow (its internal note carries the marker): a rerun or Retry is quiet.
$notes = @()
try { $notes = @(Get-PsaTicketNotes -Id $id -Newest -TextOnly) } catch { Stop-Run 'incomplete' "The notes on ticket $($f.ticketId) couldn't be read, so it isn't safe to send in case it was already acknowledged: $($_.Exception.Message)" $f.ticketId }
if (Test-PsaNoteMarker -Id $id -Marker 'smart-acknowledgement' -Notes @($notes | Where-Object { $_.internal })) { Skip-Run "Ticket $($f.ticketId) was already acknowledged, so nothing was sent again."; return }

# ---- the response target: never a resolution time ----
$level = $(if ($row.priorityLevel) { [string]$row.priorityLevel } else { 'medium' })
$targets = @{ critical = '1 hour'; high = '4 hours'; medium = '1 business day'; low = '2 business days' }
$tRaw = [string](Get-PsaSecret 'Ack-ResponseTargets')
foreach ($e in @($tRaw -split '[,;\r\n]+' | Where-Object { $_ -match '=' })) { $k = (($e -replace '=.*$', '').Trim()).ToLowerInvariant(); $v = ($e -replace '^.*?=', '').Trim(); if ($targets.ContainsKey($k) -and $v) { $targets[$k] = $v } }
$responseLine = "We aim to respond within $($targets[$level])."
$responseFrom = "the $level-priority target"
$sla = $null; try { $sla = Get-PsaTicketSla -Ticket $row } catch { $sla = $null }
if ($sla -and $sla.source -eq 'psa' -and $sla.kind -eq 'respond' -and $sla.target -is [datetime] -and $sla.target -gt (Get-Date).ToUniversalTime()) {
    $tzId = [string](Get-PsaSecret 'Ack-TimeZone'); $tz = [TimeZoneInfo]::Utc
    if ($tzId) { try { $tz = [TimeZoneInfo]::FindSystemTimeZoneById($tzId) } catch { $null = $warnings.Add("The Ack-TimeZone secret ('$tzId') isn't a known time zone, so UTC was used.") } }
    $local = [TimeZoneInfo]::ConvertTimeFromUtc($sla.target, $tz)
    $zone = $(if ($tz.Id -eq 'UTC') { 'UTC' } else { $tz.StandardName })
    $responseLine = "We aim to respond by $($local.ToString('dddd d MMMM, h:mm tt', [System.Globalization.CultureInfo]::InvariantCulture)) ($zone)."
    $responseFrom = "$psaName's SLA response target"
}

# ---- knowledge base articles from the ticket's own company (or MSP-wide) ----
$articles = @()
$crCompany = ''
if ($f.includeKb -and (Get-CrSecret 'CloudRadial-BaseUrl')) {
    try {
        $null = Connect-Cr
        $cid = 0
        if ($f.crCompanyId -match '^\d+$') { $cid = [int]$f.crCompanyId }
        elseif ([string]$row.companyId -match '^\d+$') {
            $hits = @(Get-CrAll "/v2/odata/company?`$filter=$([uri]::EscapeDataString("psaKey eq $($row.companyId)"))&`$select=companyId,name,psaKey" | Where-Object { [string](Get-CrProp $_ 'psaKey') -eq [string]$row.companyId })
            if ($hits.Count -eq 1) { $cid = [int](Get-CrProp $hits[0] 'companyId'); $crCompany = [string](Get-CrProp $hits[0] 'name') }
            elseif ($hits.Count -gt 1) { $null = $warnings.Add("More than one CloudRadial company is linked to this ticket's company, so no articles were offered. Send crCompanyId to name it.") }
        }
        if ($cid -gt 0) {
            $msp = 0; $m = [string](Get-CrSecret 'Ack-MspCompanyId'); if ($m -match '^\d+$') { $msp = [int]$m }
            $filter = "companyId eq $cid or companyId eq 0$(if ($msp) { " or companyId eq $msp" })"
            $rows = @(Get-CrAll "/v2/odata/article?`$filter=$([uri]::EscapeDataString($filter))&`$select=articleId,companyId,subject,datePublished,category")
            $now = (Get-Date).ToUniversalTime()
            $stop = @('the', 'and', 'for', 'with', 'from', 'this', 'that', 'have', 'has', 'not', 'are', 'was', 'can', 'cant', 'how', 'what', 'when', 'please', 'help', 'issue', 'problem', 'need', 'want', 'my', 'our', 'your', 'you', 'its', 'into', 'out', 'get', 'set', 'use', 'new')
            $words = { param([string]$s) @(([regex]::Matches($s.ToLowerInvariant(), '[a-z0-9]{3,}') | ForEach-Object { $_.Value }) | Where-Object { $stop -notcontains $_ } | Select-Object -Unique) }
            $tw = @(& $words "$($row.summary) $($t.description)")
            $scored = foreach ($a in $rows) {
                $pub = [datetime]::MinValue; $pr = [string](Get-CrProp $a 'datePublished')
                if (-not $pr -or -not [datetime]::TryParse($pr, [System.Globalization.CultureInfo]::InvariantCulture, [System.Globalization.DateTimeStyles]::AdjustToUniversal, [ref]$pub) -or $pub.Year -lt 2000 -or $pub -gt $now) { continue }
                $aw = @(& $words "$(Get-CrProp $a 'subject') $(Get-CrProp $a 'category')")
                $shared = @($aw | Where-Object { $tw -contains $_ })
                if ($shared.Count) { [pscustomobject]@{ id = [int](Get-CrProp $a 'articleId'); title = [string](Get-CrProp $a 'subject'); score = $shared.Count } }
            }
            $articles = @(@($scored) | Where-Object { $null -ne $_ } | Sort-Object -Property @{ Expression = 'score'; Descending = $true }, id | Select-Object -First 8)
            $null = $actions.Add("Found $($articles.Count) published knowledge base article(s) that share words with the ticket.")
        }
        elseif (-not @($warnings | Where-Object { $_ -like '*More than one CloudRadial company*' }).Count) { $null = $warnings.Add("No CloudRadial company is linked to this ticket's company, so no articles were offered. Send crCompanyId to name it.") }
    }
    catch { $null = $warnings.Add("Knowledge base articles couldn't be read from CloudRadial, so none were offered: $($_.Exception.Message)") }
}

$first = ''; if ([string]$row.contactName -match '^\s*([^\s,]+)') { $first = $Matches[1] }
$facts = [ordered]@{
    ticket   = [ordered]@{ summary = [string]$row.summary; description = $(if (([string]$t.description).Length -gt 2000) { ([string]$t.description).Substring(0, 2000) + ' [cut]' } else { [string]$t.description }) }
    contact  = $first
    articles = @($articles | ForEach-Object { [ordered]@{ id = $_.id; title = $_.title } })
}
$ctx = [ordered]@{
    ticketId = $id; number = $f.ticketId; psa = $f.psa; confirm = $f.confirm
    contactEmail = $email; contactFirst = $first; summary = [string]$row.summary
    responseLine = $responseLine; responseFrom = $responseFrom; level = $level
    articles = @($articles); articleUrlTemplate = [string](Get-PsaSecret 'Ack-ArticleUrlTemplate')
    warnings = @(Get-AllWarnings $warnings); actions = @($actions)
}
Set-NodeOutput ([ordered]@{ status = 'ok'; facts_json = ($facts | ConvertTo-Json -Depth 6 -Compress); ctx_json = ($ctx | ConvertTo-Json -Depth 6 -Compress) })
