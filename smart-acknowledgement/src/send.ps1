# === NODE: Send the acknowledgement ===
# Builds the message from fixed facts (greeting, the ticket number and summary, the response target,
# the chosen articles) around the AI's one paragraph. The paragraph is dropped when it mentions a time
# or a fix, asks for credentials, or carries a link, so the client is never promised a resolution.
# With confirm true it posts the message as a public note, so the PSA emails the ticket's contact, then
# an internal note saying the acknowledgement was sent. A preview (confirm false) writes nothing and
# returns the message. Both notes carry markers, so a rerun or a ServiceAI Retry never sends it twice.
# >>> _shared/psa.ps1 (generated by _shared/inject.js; edit the source, not this block)
# <<< _shared/psa.ps1
$ErrorActionPreference = 'Stop'

function Get-Prop { param($o, [string]$n) if ($null -eq $o) { return $null }; if ($o -is [System.Collections.IDictionary]) { if ($o.Contains($n)) { return $o[$n] }; return $null }; $p = $o.PSObject.Properties[$n]; if ($p) { return $p.Value }; return $null }
function Read-Json { param($v) if ($null -eq $v) { return $null }; if ($v -isnot [string]) { return $v }; if (-not $v.Trim()) { return $null }; try { return ($v | ConvertFrom-Json) } catch { return $null } }
$stopState = @{ done = $false; ticket = '' }
$warnings = New-Object System.Collections.ArrayList
function Get-AllWarnings {
    param($Own)
    $all = New-Object System.Collections.ArrayList
    foreach ($w in @(@($Own) + @($PsaState.Warnings))) { $t = [string]$w; if ($t -and -not $all.Contains($t)) { $null = $all.Add($t) } }
    return @($all)
}
trap { if (-not $stopState.done) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = [string]$_.Exception.Message; public_note = ''; internal_note = "The acknowledgement failed while writing to the PSA: $($_.Exception.Message)"; ticket_id = $stopState.ticket; actions = @(); warnings = @(Get-AllWarnings $warnings) }) }; break }

$ctx = Read-Json (Get-NodeInput -Name 'ctx')
if ($null -eq $ctx) { $stopState.done = $true; Set-NodeOutput ([ordered]@{ status = 'error'; message = 'The ticket details from the first step are missing. Run the workflow from the start.'; public_note = ''; internal_note = ''; ticket_id = ''; actions = @(); warnings = @() }); throw 'The ticket details from the first step are missing.' }
$num = [string](Get-Prop $ctx 'number'); $stopState.ticket = $num
$actions = New-Object System.Collections.ArrayList; foreach ($a in @(Get-Prop $ctx 'actions')) { if ($a) { $null = $actions.Add([string]$a) } }
foreach ($w in @(Get-Prop $ctx 'warnings')) { if ($w) { $null = $warnings.Add([string]$w) } }
$counts = [ordered]@{ acknowledgementsSent = 0; notesWritten = 0; articlesLinked = 0 }
function Complete-Run {
    param([string]$Status, [string]$Message, [string]$Public, [string]$Internal)
    $stopState.done = $true
    Set-NodeOutput ([ordered]@{ status = $Status; message = $Message; public_note = $Public; internal_note = $Internal; ticket_id = $num; counts = $counts; actions = @($actions); warnings = @(Get-AllWarnings $warnings) })
}
$skip = [string](Get-Prop $ctx 'skip')
if ($skip) { Complete-Run 'success' $skip '' $skip; return }

# ---- the AI's paragraph and articles, checked ----
$aiRaw = Get-NodeInput -Name 'judgment'
$ai = $null; $aiText = [string]$aiRaw
if ($aiRaw -and $aiRaw -isnot [string]) { $ai = $aiRaw }
elseif ($aiText -match '(?s)\{.*\}') { try { $ai = $Matches[0] | ConvertFrom-Json } catch { $ai = $null } }
$para = ''
if ($null -eq $ai) { $null = $warnings.Add('The AI step gave no readable answer, so the acknowledgement uses the standard wording.') }
else {
    $para = (([string](Get-Prop $ai 'paragraph')) -replace '\s+', ' ').Trim()
    $bad = ''
    if ($para.Length -gt 600) { $bad = 'it was too long' }
    elseif ($para -match '(?i)\b(resolv\w*|fix(ed|es)?|repair\w*|solv\w*)\b.{0,40}\b(by|within|in|today|tomorrow|soon|shortly)\b') { $bad = 'it promised a fix' }
    elseif ($para -match '(?i)\b\d+\s*(min(ute)?s?|hours?|hrs?|days?|weeks?)\b|\b(today|tomorrow|tonight|this (morning|afternoon|evening|week)|next week|asap|within)\b|\b(mon|tues|wednes|thurs|fri|satur|sun)day\b') { $bad = 'it mentioned a time' }
    elseif ($para -match '(?i)password|passcode|\bpin\b|one-time code|verification code|mfa code') { $bad = 'it mentioned credentials' }
    elseif ($para -match '(?i)https?://|www\.|@[a-z0-9-]+\.[a-z]') { $bad = 'it carried a link or address' }
    if ($bad) { $null = $warnings.Add("The AI's paragraph was left out because $bad; the standard wording was used."); $para = '' }
}
$byId = @{}; foreach ($a in @(Get-Prop $ctx 'articles')) { if ($null -ne $a) { $byId[[string](Get-Prop $a 'id')] = $a } }
$chosen = @()
if ($null -ne $ai) {
    foreach ($x in @(Get-Prop $ai 'articleIds')) {
        $k = [string]$x
        if ($byId.ContainsKey($k) -and @($chosen | Where-Object { [string](Get-Prop $_ 'id') -eq $k }).Count -eq 0 -and $chosen.Count -lt 2) { $chosen += , $byId[$k] }
        elseif ($k -and -not $byId.ContainsKey($k)) { $null = $warnings.Add("The AI picked article $k, which wasn't offered, so it was left out.") }
    }
}

# ---- the message ----
$first = [string](Get-Prop $ctx 'contactFirst')
$summary = [string](Get-Prop $ctx 'summary')
$tpl = [string](Get-Prop $ctx 'articleUrlTemplate')
$lines = @("Hello$(if ($first) { " $first" }),", '')
$about = $(if ($summary) { ', "' + $summary + '",' } else { '' })
$lines += "Thanks for getting in touch. We've received your request$about as ticket $num."
if ($para) { $lines += ''; $lines += $para }
$lines += ''; $lines += [string](Get-Prop $ctx 'responseLine')
if ($chosen.Count) {
    $lines += ''; $lines += $(if ($chosen.Count -eq 1) { 'While you wait, this article may help:' } else { 'While you wait, these articles may help:' })
    foreach ($a in $chosen) {
        $link = $(if ($tpl -match '\{id\}') { $tpl.Replace('{id}', [string](Get-Prop $a 'id')) } else { '' })
        $lines += " - $(Get-Prop $a 'title')$(if ($link) { ": $link" } else { ' (in your support portal''s knowledge base)' })"
    }
}
$lines += ''; $lines += 'To add anything, just reply to this email.'
$public = $lines -join "`n"
$counts.articlesLinked = $chosen.Count
$internal = "Acknowledgement sent to $([string](Get-Prop $ctx 'contactEmail')) for ticket $num. Response target stated: $([string](Get-Prop $ctx 'responseLine')) (from $([string](Get-Prop $ctx 'responseFrom'))). No resolution time was given.$(if ($chosen.Count) { ' Articles: ' + (($chosen | ForEach-Object { "$(Get-Prop $_ 'id') $(Get-Prop $_ 'title')" }) -join '; ') + '.' })$(if (-not $para) { ' Standard wording was used.' })"

if (-not [bool](Get-Prop $ctx 'confirm')) {
    Complete-Run 'pending_confirmation' "Preview only, nothing was sent. Would send this acknowledgement to $([string](Get-Prop $ctx 'contactEmail')) on ticket $num." $public $internal
    return
}

$conn = Connect-Psa -Psa ([string](Get-Prop $ctx 'psa'))
$psaName = Get-PsaName
$id = [string](Get-Prop $ctx 'ticketId')
$r = Add-PsaNote -Id $id -Text $public -Title 'We received your request' -Public -Marker 'smart-acknowledgement-public'
if ($r -eq 'written') { $counts.acknowledgementsSent = 1; $null = $actions.Add("Posted the acknowledgement as a public note on ticket $num, so $psaName emails the contact.") }
else { $null = $actions.Add("The acknowledgement was already on ticket $num, so it was not sent again.") }
try {
    $r2 = Add-PsaNote -Id $id -Text $internal -Title 'Acknowledgement sent' -Internal -Marker 'smart-acknowledgement'
    if ($r2 -eq 'written') { $counts.notesWritten = 1; $null = $actions.Add("Added the internal note to ticket $num.") }
}
catch { $null = $warnings.Add("The acknowledgement was sent, but the internal note couldn't be added to ticket $($num): $($_.Exception.Message)") }
Complete-Run 'success' "Sent the acknowledgement for ticket $num." $public $internal
